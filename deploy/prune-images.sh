#!/usr/bin/env bash
#
# Чистка образов на узле после удавшейся выкатки.
#
# Выкатка помечает образ sha коммита, поэтому висячим он не бывает никогда, а
# `docker image prune` снимает только висячее: без этой чистки образы копятся до тех пор, пока
# диск узла не кончится.
#
# Зовётся ПОСЛЕ пробы живости: прежний sha — это то, на что откатываются, когда новый не
# поднялся, и снимать его до пробы значит убрать страховку ровно тогда, когда она нужна.
#
# Чужое не трогается: отбор идёт по имени своего реестра, а не по возрасту. База и проксировщик
# старые по определению, и общая чистка унесла бы вместе с ними хранилище. `docker system prune`
# здесь не пишется никогда.
set -euo pipefail

# Сколько прошлых sha остаётся — глубина отката. Меньше трёх брать нельзя: поломка, замеченная
# через две выкатки, откатывается уже некуда.
KEEP="${KEEP:-3}"

# Свой реестр. Всё, что не подошло под эту маску, сценарий не видит вовсе.
REFERENCE='ghcr.io/eyhenij/message-bus-*'

# Печатает, что снял бы, и ничего не делает: DRY_RUN=1
DRY_RUN="${DRY_RUN:-0}"

echo "prune-images: оставляем ${KEEP} последних sha образов ${REFERENCE}"

# Образы поднятых контейнеров остаются всегда, каким бы тегом ни были помечены: это то, что
# сейчас отвечает.
running="$(docker ps --format '{{.Image}}' | sort -u)"

# Список снимается один раз: вызов `docker` на каждый тег растянул бы шаг выкатки на минуты.
listing="$(docker images --filter "reference=${REFERENCE}" --format '{{.CreatedAt}}|{{.Tag}}|{{.Repository}}:{{.Tag}}' | sort -r)"

# Теги по времени создания, новые сверху, без повторов: один sha приезжает двумя образами —
# приёмником и дорогой, — и считать их порознь значило бы оставить полтора sha вместо трёх.
#
# Только sha: «последний» — не точка отката, а подвижная метка, и слот отката она занимала бы
# навсегда, потому что не стареет.
sha_tags="$(printf '%s\n' "${listing}" | cut -d'|' -f2 | grep -E '^[0-9a-f]{40}$' | awk '!seen[$0]++' || true)"

if [ -z "${sha_tags}" ]; then
    echo 'prune-images: образов своего реестра по sha на узле нет'
    exit 0
fi

keep_tags="$(printf '%s\n' "${sha_tags}" | head -n "${KEEP}")"
drop_tags="$(printf '%s\n' "${sha_tags}" | tail -n "+$((KEEP + 1))")"

echo 'prune-images: остаются'
printf '  %s\n' ${keep_tags}

if [ -z "${drop_tags}" ]; then
    echo 'prune-images: снимать нечего'
else
    # Отбор грепом по списку тегов, а не переменной awk: в переменную `-v` перевод строки не
    # кладётся, и видно это только на прогоне.
    drop_images="$(printf '%s\n' "${listing}" |
        grep -F -f <(printf '%s\n' "${drop_tags}") | cut -d'|' -f3 | awk '!seen[$0]++')"

    for image in ${drop_images}; do
        if printf '%s\n' "${running}" | grep -qxF "${image}"; then
            echo "prune-images: работает, оставлен ${image}"
            continue
        fi
        if [ "${DRY_RUN}" = '1' ]; then
            echo "prune-images: снял бы ${image}"
            continue
        fi
        # Без `-f`: занятый образ так и остаётся на месте, а отказ на нём прогон не роняет —
        # чистка не обязана быть полной.
        docker rmi "${image}" >/dev/null 2>&1 && echo "prune-images: снят ${image}" || echo "prune-images: занят, оставлен ${image}"
    done
fi

if [ "${DRY_RUN}" = '1' ]; then
    echo 'prune-images: вхолостую, слои и кэш сборки не тронуты'
    exit 0
fi

# Слои, оставшиеся без образа.
docker image prune -f >/dev/null

# Кэша сборки на узле нет и быть не должно: собирает конвейер, узел только тянет готовое
# `--no-build`. Лежал бы он мёртвым грузом на диске в 24 ГБ.
docker builder prune -af >/dev/null

docker system df
