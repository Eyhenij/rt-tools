#!/usr/bin/env bash
# Надстройка карты гейта: то, чего нет у других деревьев мастерской.
#
# Умолчание везёт пакет — `.claude/rt-kit/defaults/gate-map.sh`: тесты, компоненты, стили,
# барели, манифесты, документы и команды поставки разобраны там. Здесь остаётся своё — витрина,
# у которой правило этого дерева, и барели с манифестами ng-packagr.
#
# Функция печатает ИМЯ ПРАВИЛА или молчит. Молчание — «правила на это нет», и гейт пропускает.
#
# Порядок веток решает: первое совпадение выигрывает, поэтому частное идёт раньше общего.
# Файл витрины и файл теста — не файлы компонента, и обе ветки обязаны стоять до общей ветки
# расширения, а своё частное — до вызова умолчания.

skill_for() {
    kind="$1"
    target="$2"
    written="$3"

    case "$kind" in
        edit)
            case "$target" in
                # Файлы самого агента правятся без правила: правило на них — это оно само.
                */.claude/*) return 0 ;;

                # Сгенерированный клиент хранилища: его переписывает генератор целиком, и спорить
                # с ним о приёмах некому.
                */persistence/util/src/generated/*) return 0 ;;

                # Сквозной набор админки. Его спеки идут путём человека и живут на стенде: правит
                # их общее правило проверяемости вместе с правилом стенда, а не правило спеки
                # компонента кита. Ветка стоит до общей ветки `*.spec.ts` и до серверной: имена
                # файлов у них те же.
                */apps/message-bus-admin-e2e/*)
                    printf '%s\n' 'testing'
                    printf '%s\n' 'browser-verification'
                    return 0
                    ;;

                # Серверная сторона. Правила фронта на неё не действуют — они сами это говорят, —
                # а спека приёмника гоняется общим правилом проверяемости, а не правилом кита.
                # Ветки стоят до общих: у файлов приёмника те же суффиксы имён.
                */apps/message-bus/*.spec.ts | */libs/message-bus*/*.spec.ts)
                    printf '%s\n' 'testing'
                    return 0
                    ;;
                # Гвард доступа приёмника: отбивку без входа и без права держит он, и правило
                # доступа привязано сюда. Ветка стоит до общей серверной.
                */libs/message-bus-api/access/*)
                    printf '%s\n' 'permissions'
                    return 0
                    ;;

                # Админка. Её либы лежат в семье `libs/message-bus-admin`, и общая серверная
                # ветка ниже забирала бы их себе: имена начинаются одинаково. Частное — раньше.

                # Гвард маршрута админки: он и есть здешняя отбивка без входа.
                */libs/message-bus-admin/*.guard.ts)
                    printf '%s\n' 'permissions'
                    printf '%s\n' 'angular-patterns'
                    return 0
                    ;;

                # Остальной вход записями не заведует: ни панели правки, ни модели сущности у
                # него нет, и правила сущности требовать на нём нечего. Ветка уводит его в
                # умолчание раньше, чем до него доберутся ветки сторов и моделей.
                */libs/message-bus-admin/auth/*)
                    command -v skill_for_default >/dev/null 2>&1 && skill_for_default "$kind" "$target" "$written"
                    return 0
                    ;;

                # Списочный экран раздела.
                */libs/message-bus-admin/*/feature/list/*)
                    printf '%s\n' 'lists'
                    return 0
                    ;;

                # Меню, оболочка и адреса разделов: пункт меню и маршрут заводятся одной
                # декларацией, и правит их обоих одно правило.
                */libs/message-bus-admin/common/container/* | */libs/message-bus-admin/*.routes.ts | */apps/message-bus-admin/src/app/app.routes.ts)
                    printf '%s\n' 'navigation'
                    return 0
                    ;;

                # Стор сущности и панель её правки.
                */libs/message-bus-admin/*.store.ts | */libs/message-bus-admin/*/feature/*-aside/*)
                    printf '%s\n' 'entity-conventions'
                    printf '%s\n' 'angular-patterns'
                    return 0
                    ;;

                # Модель записи и её маппер — что запрашивается на экране и чем переводится.
                */libs/message-bus-admin/*.model.ts | */libs/message-bus-admin/*.mapper.ts | */libs/message-bus-common/*.model.ts | */libs/message-bus-common/*.mapper.ts)
                    printf '%s\n' 'entity-models'
                    return 0
                    ;;

                */apps/message-bus/* | */libs/message-bus*/*)
                    printf '%s\n' 'typescript-conventions'
                    return 0
                    ;;

                # Команда отметки груза: правит её тот, кто груз разбирает, и порядок разбора он
                # обязан знать раньше правки. Правило своё, дерева: приёма у дерева-потребителя
                # нет вовсе, и пакет его не везёт. Перечень долга границы стоял здесь же, пока
                # был жив; заведённый заново, он возвращается в эту ветку.
                */tools/cargo-mark.mjs)
                    printf '%s\n' 'cargo-triage'
                    return 0
                    ;;

                # Обвязка снимков, эталоны, прогонщик и обход историй: правило витрины про
                # форму истории, а не про проверку кадра, — здесь ведёт правило проверки
                # компонента.
                */.storybook/test-runner.ts | */__snapshots__/* | */tools/visual-snapshots-v2.mjs | */tools/story-sweep-v2.mjs)
                    printf '%s\n' 'ui-component-tests'
                    return 0
                    ;;

                # Остальная настройка витрины: провайдеры, порядок боковика, состав историй.
                # Линтер и тайпчек сюда не смотрят вовсе — единственная проверка здесь чтение.
                */.storybook/*.ts)
                    printf '%s\n' 'rt-tools-storybook'
                    return 0
                    ;;

                # Обвязка показа: сетки, ряды, темы, параметры снимка. Это демонстрационный
                # код витрины, а не компоненты приложения, — ведёт то же правило, что истории.
                */src/showcase/*)
                    printf '%s\n' 'rt-tools-storybook'
                    return 0
                    ;;

                # Витрина: у неё своё правило этого дерева, пакет такого не везёт. Ветка стоит
                # после обвязки снимков и перед общей: файл истории — не файл компонента.
                *.stories.ts | */stories/*.ts | */strories/*.ts | *.mdx)
                    printf '%s\n' 'rt-tools-storybook'
                    return 0
                    ;;

                # Спека компонента: у умолчания на неё общее правило проверяемости, а готовый
                # код спеки и порядок проверки лежат в правиле этого дерева.
                *.spec.ts)
                    printf '%s\n' 'ui-component-tests'
                    return 0
                    ;;

                # Опубликованная поверхность пакета: у умолчания её нет — там барели зовутся
                # иначе, а манифеста ng-packagr нет вовсе.
                */public-api.ts | */ng-package.json)
                    printf '%s\n' 'lib-layers'
                    return 0
                    ;;
            esac
            ;;
    esac

    # Всё остальное разбирает умолчание пакета: тесты, компоненты, стили, барели, документы.
    # Проверка на объявленность нужна ровно в одном промежутке: пакет обновлён, а `sync` в этом
    # дереве ещё не прогнан, и умолчания на диске нет. Без неё гейт молчал бы на всём подряд.
    command -v skill_for_default >/dev/null 2>&1 && skill_for_default "$kind" "$target" "$written"

    return 0
}
