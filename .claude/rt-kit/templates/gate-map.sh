#!/usr/bin/env bash
# rt-kit v0.3.0 · templates/gate-map.sh · 6f2e9fcc1635 · правится надстройкой, не здесь
# Карта «что правится — какое правило» этого дерева. Её читает хук гейта правил.
#
# Живёт в проекте, а не в пакете: имена каталогов, расширения и команды поставки у каждого
# дерева свои. Пакет везёт механизм, проект — карту.
#
# Функция печатает ИМЯ ПРАВИЛА или молчит. Молчание — «правила на это нет», и гейт пропускает.
#
# Порядок веток решает: первое совпадение выигрывает, поэтому частное идёт раньше общего.
# Файл спеки — не файл компонента, и обе ветки обязаны стоять до общей ветки расширения.

skill_for() {
    kind="$1"
    target="$2"

    case "$kind" in
        edit)
            case "$target" in
                # Файлы самого агента правятся без правила: правило на них — это оно само.
                */.claude/*)                        return 0 ;;
                *.spec.ts)                          printf '%s' '<правило про тесты>' ;;
                *.component.ts|*.component.html)    printf '%s' '<правило про компонент>' ;;
                *.scss)                             printf '%s' '<правило про оформление>' ;;
                */index.ts)                         printf '%s' '<правило про раскладку либ>' ;;
                *.ts)                               printf '%s' '<правило про код>' ;;
                *.md)                               printf '%s' '<правило про тексты>' ;;
            esac
            ;;
        bash)
            case "$target" in
                *git\ commit*|*git\ push*|*gh\ pr\ create*) printf '%s' '<правило про поставку>' ;;
            esac
            ;;
    esac

    return 0
}
