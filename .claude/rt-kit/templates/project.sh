#!/usr/bin/env bash
# rt-kit v0.2.0 · templates/project.sh · 14f840a53145 · правится надстройкой, не здесь
# Профиль этого дерева: что здесь чем зовётся и какими командами проверяется.
#
# Живёт в проекте, а не в пакете: механизм у сторожевых хуков общий, а команды, порты и пары
# «правка — её документ» у каждого дерева свои. Пакет везёт хуки, проект — этот файл.
#
# Каждая функция вправе промолчать. Молчание значит «правила на это нет», и хук пропускает:
# пустой профиль оставляет хуки безвредными, а не отбивающими наугад.

# Где подняты приложения. Идёт в текст отказа, когда кто-то поднимает второй экземпляр.
RT_STANDS='<приложение> http://localhost:<порт>, <приложение> http://localhost:<порт>'

# Команды, которые обязаны пройти перед пушем. По одной на строку; первая упавшая отбивает пуш.
rt_push_checks() {
    cat <<'EOF'
<команда линтера кода>
<команда линтера стилей>
<команда тестов>
EOF
}

# Какой документ обязан ехать тем же коммитом, что и этот файл. Печатает путь или молчит.
rt_docs_pair_for() {
    case "$1" in
        */<каталог правил>/*)   printf '%s' '<зеркало правила>' ;;
        *.proto)                printf '%s' '<спек задетого домена>' ;;
    esac
}

# Чем линтуется этот файл сразу после правки. Печатает команду или молчит.
rt_lint_for() {
    case "$1" in
        *.scss)  printf '%s' '<команда линтера стилей> "$1"' ;;
        *.ts)    printf '%s' '<команда линтера кода> "$1"' ;;
    esac
}

# Имя ветки, с которой разрешено открывать PR: номер задачи в имени. Успех — годится.
rt_task_branch_ok() {
    printf '%s' "$1" | grep -qE '<выражение имени ветки>'
}
