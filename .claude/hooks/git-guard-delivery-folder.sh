#!/usr/bin/env bash
# rt-kit v0.14.0 · hooks/git-guard-delivery-folder.sh · 6670c6bd1799 · правится надстройкой, не здесь
# Условия поставки о папке задачи. НЕ гард: объявления `rt-hook:` у него нет, к событиям агента
# он не подключается. Его источает гард поставки — тем же приёмом, каким источает хвост отказа и
# запись наблюдений.
#
# Зачем он отдельным файлом. Условий о папке два, и живут они в разных местах вызова: одно на
# открытии заявки, другое на слиянии. Вместе с разбором команды, подписью, основанием и очередью
# работ они переросли предел длины файла, а делить гард по событиям нельзя — он одно целое,
# и разбор команды у него общий. Делится он по предмету: папка задачи — свой предмет, у неё свой
# обход и своя запись в архиве.
#
# ЧТО ЗДЕСЬ. Три вызова, и все три зовутся из гарда поставки, где уже объявлены `deny`, `fault`
# и переменные профиля: `tasks_dir`, `archive_dir`, `main_branch`, `folder_skip_re`, `root`.
# Своих у помощника нет — он не читает ни ввода, ни настроек.

# Есть ли папка задачи в ветке. Смотрим содержимое ветки, а не рабочее дерево: если папку
# удалили, но не закоммитили, проверка прошла бы, а папка всё равно уехала бы в главную. Имя
# ветки подставляем целиком, вместе с косой: у ветки вида `chore/312-slug` папка лежит во
# вложенном каталоге.
rt_folder_in_branch() {
    git ls-tree -d --name-only HEAD -- "$1" 2>/dev/null | head -1
}

# Была ли папка задачи в этой ветке вообще. Спрашивается у ветки, которая её удалила: иначе
# требование записи в архиве цеплялось бы к работе, у которой папки и не было.
rt_folder_was_in_branch() {
    _base="$1"
    _folder="$2"
    _had="$(git ls-tree -d --name-only "$_base" -- "$_folder" 2>/dev/null | head -1)"
    [ -z "$_had" ] && _had="$(git log "$_base..HEAD" --diff-filter=A --name-only --pretty=format: -- "$_folder" 2>/dev/null | head -1)"
    [ -n "$_had" ]
}

# Условие открытия заявки: папка разобрана, и запись в архиве от ветки прибыла. Отказ копится
# вместе с прочими условиями поставки и печатается разом.
#
# Разбор стоит здесь, а не на слиянии. Прежде было наоборот: считалось, что папка нужна на диске
# всё время разбора, потому что правку по замечаниям без замысла отбивает гард хода работы.
# Владелец же вливает, как только видит зелёное, и закрывающему коммиту места не остаётся —
# трижды подряд папка уехала в главную неразобранной, а гард слияния этого не видел вовсе:
# кнопку нажимает человек на хостинге, и до него гард не достаёт. Замысел после уборки гард хода
# работы берёт из истории ветки, а не с диска.
rt_delivery_open_folder() {
    [ -n "$tasks_dir" ] || return 0
    printf '%s' "$cmd" | grep -qiE "$folder_skip_re" && return 0

    _folder="$tasks_dir/$branch"
    _lying="$(rt_folder_in_branch "$_folder")"
    if [ -n "$_lying" ]; then
        fault "в ветке лежит папка задачи «${_lying}» — заявка открывается после уборки, а не до неё. Перенеси в «${archive_dir:-архив}» то, что объясняет принятые решения, остальное удали, закоммить последним коммитом и повтори. Если работа вливается частями, поставь в команду комментарий «# Task-folder-skip: <причина>»."
        return 0
    fi

    [ -n "$archive_dir" ] || return 0
    _base="$(git merge-base "$main_branch" HEAD 2>/dev/null)"
    [ -z "$_base" ] && return 0
    rt_folder_was_in_branch "$_base" "$_folder" || return 0

    _gained="$(git diff --name-only --diff-filter=A "$_base" HEAD -- "$archive_dir" 2>/dev/null | head -1)"
    [ -z "$_gained" ] \
        && fault "папку задачи удалили, но в «${archive_dir}» ветка ничего не добавила. Удалить проще, чем разобрать, — и вместе с папкой пропадает разбор просьбы, единственная запись слов владельца. Перенеси то, что объясняет принятые решения, одним файлом с понятным именем и повтори."
}

# Условие слияния: тот же предмет вторым рубежом. Он ловит слияние, идущее командой, — то, до
# которого гард достаёт. Отсюда выходят только отказом или молчанием: слияние решается целиком.
rt_delivery_merge_folder() {
    [ -n "$tasks_dir" ] || exit 0   # ведения работы папкой в дереве нет

    _branch="$(git branch --show-current 2>/dev/null)"
    [ -z "$_branch" ] && exit 0
    rt_task_branch_ok "$_branch" || exit 0   # за беззадачной веткой папки не стоит

    _folder="$tasks_dir/$_branch"

    # Сначала ищем обход в самой команде — это работает и без сети. Если читать только
    # тело заявки, то без сети гард отбил бы слияние, причина которого в этом теле и написана.
    printf '%s' "$cmd" | grep -qiE "$folder_skip_re" && exit 0

    _number="$(printf '%s' "$cmd" | sed -nE 's/.*(pr|mr)[[:space:]]+(merge|update)[[:space:]]+([0-9]+).*/\3/p' | head -1)"
    if [ -n "$_number" ] && rt_needs rt_report_body git-guard-delivery; then
        _body="$(cd "$root" && rt_report_body "$_number" 2>/dev/null)"
        [ -n "$_body" ] && printf '%s' "$_body" | grep -qiE "$folder_skip_re" && exit 0
    fi

    _lying="$(rt_folder_in_branch "$_folder")"
    [ -n "$_lying" ] \
        && deny "BLOCKED: в ветке осталась папка задачи «${_lying}» — она уедет в главную. Разобрать её потом будет некому: работа перейдёт к следующей задаче, а эта заявка закроется. Перенеси в «${archive_dir:-архив}» то, что объясняет принятые решения, остальное удали и повтори. Если работа вливается частями, поставь в тело заявки строку «Task-folder-skip: <причина>»."

    [ -n "$archive_dir" ] || exit 0
    _base="$(git merge-base "$main_branch" HEAD 2>/dev/null)"
    [ -z "$_base" ] && exit 0
    rt_folder_was_in_branch "$_base" "$_folder" || exit 0

    _gained="$(git diff --name-only --diff-filter=A "$_base" HEAD -- "$archive_dir" 2>/dev/null | head -1)"
    [ -z "$_gained" ] \
        && deny "BLOCKED: папку задачи удалили, но в «${archive_dir}» ветка ничего не добавила. Удалить проще, чем разобрать, — и вместе с папкой пропадает разбор просьбы, единственная запись слов владельца. Перенеси то, что объясняет принятые решения, одним файлом с понятным именем и повтори."

    exit 0
}
