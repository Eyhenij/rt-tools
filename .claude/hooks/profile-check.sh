#!/usr/bin/env bash
# rt-kit v0.8.2 · hooks/profile-check.sh · 311b1c2840ba · правится надстройкой, не здесь
# Нехватка функции профиля, сказанная вслух. НЕ гард: объявления `rt-hook:` у него нет, к
# событиям агента он не подключается. Его источают сами гарды — тем же приёмом, каким гейт
# источает карту, а гарды — запись наблюдений.
#
# Зачем он есть. Девять хуков пакета зовут функции профиля дерева, и у пяти проверка стоит до
# всякого поведения: нет функции — выход с нулём, не сделав ничего. Такой гард хуже
# отсутствующего: он лежит в дереве, стоит в настройке, виден в списке хуков и читается как
# работающий. Тишина при этом означает разом три разных вещи — «нечего проверять», «проверять
# нечем» и «всё в порядке», — и отличить их нечем.
#
# ЧТО ГОВОРИТСЯ. Имя функции и файл, в котором её определяют. Один раз за сессию: на каждый
# вызов та же строка повторялась бы десятки раз за заход и перестала бы читаться.
#
# ДЕЙСТВИЕ ВСЁ РАВНО ПРОПУСКАЕТСЯ. Хук сообщает о своей неполноте, а не судит правку: судить её
# нечем, и отбивать работу из-за ненастроенного дерева он не вправе.

# Куда кладётся отметка «об этом уже сказано». Каталог временных файлов, а не дерево: отметка
# живёт один заход и в историю не едет.
rt_needs_mark_dir() {
    printf '%s' "${TMPDIR:-/tmp}"
}

# Есть ли функция профиля. Успех — есть, и хук работает дальше. Отказ — нет, и об этом сказано.
#
#   rt_needs rt_is_app_code task-flow-guard "$sid"
#
# Третий параметр — признак сессии, если хук его знает. Не знает — отметка кладётся на день:
# без признака «один раз за сессию» превратилось бы в «один раз за всю жизнь машины».
rt_needs() {
    command -v "$1" >/dev/null 2>&1 && return 0

    rt_needs_key="${3:-$(date +%Y%m%d 2>/dev/null || printf 'nosession')}"
    rt_needs_mark="$(rt_needs_mark_dir)/rt-kit-needs-$1-$rt_needs_key"
    if [ ! -f "$rt_needs_mark" ]; then
        printf '%s: нет функции %s — её определяют в .claude/rt-kit/project.sh, а умолчание везёт пакет в .claude/rt-kit/defaults/project.sh\n' \
            "${2:-хук}" "$1" >&2
        printf 'проверка не работает, действие пропущено\n' >&2
        : >"$rt_needs_mark" 2>/dev/null || true
    fi

    return 1
}
