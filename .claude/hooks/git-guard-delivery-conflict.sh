#!/usr/bin/env bash
# rt-kit v0.23.0 · hooks/git-guard-delivery-conflict.sh · c49abea43403 · правится надстройкой, не здесь
# Конфликтующая своя заявка для гарда поставки: пока хоть одна отданная работа помечена
# конфликтующей, новая не берётся.
#
# Строки `# rt-hook:` здесь нет намеренно: событие и образец вызова объявляет сам гард, а
# помощник рядом хуком не регистрируется и в одиночку ничего не решает. Он зовётся из гарда,
# пользуется его переменными и его отказом — тем же приёмом, что помощники папки и подписи.
#
# Зачем именно так. Гард поставки стоит в трёх точках и в каждой требует того, что в эту минуту
# исправимо, а состояние уже отданного не спрашивает нигде. Конфликт приезжает в отданную заявку
# чужим слиянием, без единого действия её автора: влить её человек больше не может, и заявка
# стоит, пока автор не заметит. Заметить её нечем — требование перечитывать свои открытые заявки
# записано текстом и держится памятью: две заявки простояли конфликтующими весь заход, и заметил
# это владелец.
#
# Исправимо это ровно в минуту, когда берётся следующая работа: после неё конфликтов становится
# больше, а не меньше — каждая новая заявка растёт из той же главной ветки и приезжает в ту же
# очередь, которую придётся догонять.
#
# Работой здесь считаются четыре команды: заведение задачи, заведение ветки под задачу, перевод
# колонки в работу и открытие заявки. Всё, чем конфликт чинится, — подтягивание, вливание,
# коммит, отправка, переход между ветками — идёт как прежде: гард, отбивающий починку, запирал
# бы дерево наглухо.
#
# Судится только прямое «конфликтует». Пока хостинг считает сливаемость, он отвечает
# неопределённостью — и считает он её заново после каждой правки главной ветки, — а читать
# неопределённость как конфликт значило бы отбивать работу на каждой свежей вершине.
#
# ОТКАЗ В ПОЛЬЗУ РАБОТЫ: нет функции профиля, нет сети, нет машинной записи — ярус пропускается.

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/utf8.sh" 2>/dev/null || true
# Начало вызова помощник берёт оттуда же, откуда все гарды. Источается он и здесь, хотя зовущий
# гард это уже сделал: пустой образец превратил бы признак в поиск слова по всей строке.
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/hook-input.sh" 2>/dev/null || true

rt_delivery_conflict() {
    # Признак взятия работы читается из текста команды и стоит первым: опрос ходит в сеть, и
    # платить за него на каждой команде оболочки нельзя.
    taking=''
    case "$cmd" in
        *"${task_new}"*) taking='заведение задачи' ;;
    esac
    # Перевод колонки судится вместе с именем колонки работы: перевод в разбор и в закрытые —
    # это конец работы, а не её начало.
    if [ -z "$taking" ] && [ -n "$task_move" ]; then
        case "$cmd" in
            *"${task_move}"*)
                case "$cmd" in
                    *"${RT_BOARD_INPROGRESS_KEY:-in-progress}"*) taking='перевод колонки в работу' ;;
                esac
                ;;
        esac
    fi
    if [ -z "$taking" ] \
        && printf '%s' "$cmd" | grep -qE '(^|[;&|[:space:]])git[[:space:]]+(checkout[[:space:]]+-b|switch[[:space:]]+-c)[[:space:]]+[A-Za-z]+-[0-9]+'; then
        taking='заведение ветки под задачу'
    fi
    if [ -z "$taking" ] \
        && printf '%s' "$cmd" | grep -qE "${RT_CMD_BOUND}(gh[[:space:]]+pr[[:space:]]+create|glab[[:space:]]+mr[[:space:]]+create)([[:space:]]|\$)"; then
        taking='открытие заявки'
    fi
    [ -z "$taking" ] && return 0

    rt_needs rt_conflicting_pulls git-guard-delivery || return 0
    stuck="$(cd "$root" && rt_conflicting_pulls 2>/dev/null)" || return 0
    [ -z "$stuck" ] && return 0

    listed=''
    while IFS= read -r line; do
        [ -z "$line" ] && continue
        listed="${listed}${listed:+
}— ${line}"
    done <<EOF
${stuck}
EOF
    [ -z "$listed" ] && return 0

    deny "BLOCKED: ${taking} при своей конфликтующей заявке. Отданное конфликтует с главной веткой, и влить его человек не может:

${listed}

Конфликт приезжает чужим слиянием, без единого действия автора заявки: она стоит, пока её не догонят. Новая работа его не чинит — она прибавляет к очереди ещё одну ветку, которая растёт из той же главной и отстанет так же.

Ход отсюда один: подтянуть главную, влить её в названную ветку, разобрать конфликт и отправить — и только потом брать новую работу. Что чем чинится — паттерн git-workflow-freshness."
}
