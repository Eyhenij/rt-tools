#!/usr/bin/env bash
# rt-kit v0.11.0 · hooks/git-guard-delivery.sh · ff35bfb41b90 · правится надстройкой, не здесь
# rt-hook: PreToolUse Bash|mcp__webstorm__execute_terminal_command|mcp__webstorm__execute_tool
# Требует: hooks/profile-check.sh, hooks/deny-tail.sh
# Гард поставки. PreToolUse на заведении ветки, пуше и открытии заявки на слияние.
#
# Закон о поставке требует трёх вещей, которых обычно не проверяет ничто: правка начинается с
# задачи, видимой в очереди работ; задача, ветка и PR несут один номер; у задачи есть
# исполнитель. Держатся они памятью — и не удерживаются: задачи стоят вне очереди, исполнитель
# не проставлен, а большинство влитых заявок приходит с веток, за которыми задачи не стояло
# вовсе.
#
# Гард стоит в трёх точках, и в каждой требует того, что в этот момент исправимо:
#
#   заведение ветки — имя с номером разбирается на месте; имя без номера пропускается:
#       локальная ветка под пробу законна, в главную она не поедет, потому что заявка с неё
#       не откроется;
#   пуш — подпись машинного коммита ещё переписывается на месте; после пуша её чинит только
#       силовая отправка;
#   открытие заявки — ветка обязана нести номер, заголовок обязан начинаться с того же номера,
#       а задача — быть открытой, стоять в очереди работ и иметь исполнителя.
#
# Два яруса. Формат — номер в имени ветки, номер в заголовке, их совпадение — читается из
# текста команды и работает всегда. Состояние задачи требует сети: нет её, нет помощника или
# нет токена — ярус пропускается, потому что проверять нечем.
#
# Что здесь чем зовётся, знает профиль дерева:
#   rt_task_branch_ok    — форма имени ветки под задачу;
#   RT_TASK_TITLE_RE     — форма номера в заголовке заявки;
#   rt_task_state        — состояние задачи одним объектом (existsize, open, onBoard, assigned,
#                          numbered); молчание значит «спросить некого»;
#   RT_TASK_NEW_CMD      — чем заводится задача;
#   RT_BOARD_CHECK_CMD   — чем сверяется очередь работ;
#   RT_TASK_BOT          — учётная запись, которую ставят исполнителем; ею же открывается заявка;
#   RT_PULL_TOKEN_VAR    — переменная, которой вызову подставляют её токен;
#   RT_PULL_TOKEN_HINT   — готовая подстановка этого токена, целиком;
#   RT_COMMIT_EMAIL      — почта, которой подписан машинный коммит; её же левой частью он и
#                          опознаётся.
# Отказ называет и то, что не так, и чем это чинится: отказ без действия обходят, а не исполняют.
#
# ОТКАЗ В ПОЛЬЗУ РАБОТЫ: не репозиторий, нет разборщика, битый ввод, нет профиля — пропуск.

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/utf8.sh" 2>/dev/null || true

input="$(cat 2>/dev/null)"
[ -z "$input" ] && exit 0
command -v jq >/dev/null 2>&1 || exit 0

tool="$(printf '%s' "$input" | jq -r '.tool_name // empty' 2>/dev/null)"
sid="$(printf '%s' "$input" | jq -r '.session_id // "nosession"' 2>/dev/null)"
case "$tool" in
    # Терминал среды и универсальный исполнитель кладут команду в то же поле.
    Bash | mcp__webstorm__execute_terminal_command | mcp__webstorm__execute_tool) ;;
    *) exit 0 ;;
esac

cmd="$(printf '%s' "$input" | jq -r '.tool_input.command // empty' 2>/dev/null)"
[ -z "$cmd" ] && exit 0

# Универсальный исполнитель передаёт настоящую команду вложенной строкой. Разбирать надо её,
# а не обёртку.
if [ "$tool" = "mcp__webstorm__execute_tool" ] && command -v perl >/dev/null 2>&1; then
    inner="$(printf '%s' "$cmd" | perl -0ne '
        if (/--command(?:=|\s+)(?:"((?:[^"\\]|\\.)*)"|\x27([^\x27]*)\x27|(.+))/s) {
            print defined $1 ? $1 : (defined $2 ? $2 : $3);
        }
    ' 2>/dev/null)"
    [ -n "$inner" ] && cmd="$inner"
fi

workdir="$(printf '%s' "$input" | jq -r '.cwd // empty' 2>/dev/null)"
[ -z "$workdir" ] && workdir="${CLAUDE_PROJECT_DIR:-.}"
cd "$workdir" 2>/dev/null || exit 0
git rev-parse --is-inside-work-tree >/dev/null 2>&1 || exit 0

root="${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null)}"

# Профиль дерева: сперва умолчание пакета, поверх него — надстройка проекта, если она есть.
# Объявленная в надстройке функция замещает умолчание целиком и вправе позвать его обратно
# суффиксом `_default`. Нет ни того ни другого — хук пропускает: пустой гард лучше гарда,
# отбивающего наугад.
rt_hooks_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
for profile in "$rt_hooks_dir/../rt-kit/defaults/project.sh" "$rt_hooks_dir/../defaults/project.sh" "$root/.claude/rt-kit/defaults/project.sh" "$root/.claude/rt-kit/project.sh"; do
    # shellcheck disable=SC1090
    [ -f "$profile" ] && . "$profile" 2>/dev/null
done

# Слово о нехватке функции профиля: хук, вышедший молча, неотличим от работающего. Файл может
# быть не разложен — тогда остаётся прежнее поведение, молчаливое.
# shellcheck disable=SC1090
[ -f "$rt_hooks_dir/profile-check.sh" ] && . "$rt_hooks_dir/profile-check.sh"
command -v rt_needs >/dev/null 2>&1 || rt_needs() { command -v "$1" >/dev/null 2>&1; }
rt_needs rt_task_branch_ok git-guard-delivery || exit 0

title_re="${RT_TASK_TITLE_RE:-^\[[A-Za-z]+-[0-9]+\][[:space:]]+[^[:space:]]}"
task_new="${RT_TASK_NEW_CMD:-npm run task:new}"
board_check="${RT_BOARD_CHECK_CMD:-npm run check:board}"
task_move="${RT_TASK_MOVE_CMD:-npm run task:move}"
# Первая колонка очереди работ — та, из которой задача уходит, когда её берут. Умолчания у неё
# нет: имена колонок дерево называет своими словами, а выдуманное имя не совпало бы ни с чем и
# молча выключило бы проверку.
backlog_column="${RT_BOARD_BACKLOG:-}"
task_bot="${RT_TASK_BOT:-}"
# Личность вызова приходит окружением, а не словом в строке: из текста команды видно только то,
# подставлен ли токен явно. Дерево, не назвавшее переменной, автора заявки не судит вовсе —
# у него может не быть отдельной машинной записи.
pull_token_var="${RT_PULL_TOKEN_VAR:-}"
pull_token_hint="${RT_PULL_TOKEN_HINT:-}"
commit_email="${RT_COMMIT_EMAIL:-}"
tasks_dir="${RT_TASKS_DIR:-}"
archive_dir="${RT_ARCHIVE_DIR:-}"
main_branch="${RT_MAIN_BRANCH:-main}"

# Обход требования: строка с причиной. Причина видна тому, кто вливает, поэтому обход законен.
# Без причины это просто молчаливый пропуск, поэтому она обязательна. Порог в три знака — тот
# же, что у гарда документа: если сделать по-разному, две формы одного обхода разойдутся.
#
# Строка обхода начинает строку — свою в теле PR или комментарий в конце команды — и
# подстановки не принимает. Без этих двух условий текст, который ОБЪЯСНЯЕТ, что обход называется
# так-то, от самого обхода неотличим: тело PR со строкой-примером снимало требование само
# собой, и тот же пример гард печатает в своём отказе ниже. Нашлось это приёмкой такого же
# признака — прогон обязан был покраснеть на настоящем нарушении и остался зелёным.
folder_skip_re='(^|#)[[:space:]]*Task-folder-skip:[[:space:]]*[^[:space:]<"'"'"'][^[:space:]"'"'"']{2,}'

deny() {
    # Отказ гарда — наблюдение: гард, отбивающий чаще прочих, говорит, какое место поставки раз
    # за разом делают не так. Текст отказа туда не идёт: в нём номера задач и имена веток дерева.
    # shellcheck disable=SC1090
    [ -f "$rt_hooks_dir/observe.sh" ] && . "$rt_hooks_dir/observe.sh" 2>/dev/null
    command -v rt_note >/dev/null 2>&1 && rt_note guard-deny res=git-guard-delivery "sid=$sid"

    # Хвост отказа: два законных хода и форма обхода вторым параметром.
    # shellcheck disable=SC1090
    [ -f "$rt_hooks_dir/deny-tail.sh" ] && . "$rt_hooks_dir/deny-tail.sh" 2>/dev/null
    reason="$1"
    command -v rt_deny_tail >/dev/null 2>&1 && reason="$1 $(rt_deny_tail "$2")"

    jq -n --arg r "$reason" '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:$r}}' 2>/dev/null \
        || printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"Гард поставки."}}\n'
    exit 0
}

# Несошедшиеся условия копятся и называются разом. Отказ по первому промаху заставляет чинить
# их по одному: исполнитель правит основание, повторяет вызов, упирается в заголовок, правит
# заголовок, упирается в задачу — и цена отказа растёт на каждом круге, хотя всё несошедшееся
# было известно уже на первом. Готовность к поставке — одно состояние, и называется оно целиком.
faults=''

fault() {
    faults="${faults}${faults:+
}— $1"
}

# Отказ по накопленному. Пусто — вызывающая сторона идёт дальше.
deny_faults() {
    [ -z "$faults" ] && return 0
    deny "BLOCKED: работа к поставке не готова. Несошедшееся названо целиком — чтобы чинить его
одним заходом, а не по одному промаху на круг:

${faults}"
}

# Подсказка вместо отказа: на открытии PR папка ещё нужна. Решения подсказка не несёт,
# команда идёт дальше своим ходом.
hint() {
    jq -n --arg c "$1" '{hookSpecificOutput:{hookEventName:"PreToolUse",additionalContext:$c}}' 2>/dev/null
    exit 0
}

# Есть ли папка задачи в ветке. Смотрим содержимое ветки, а не рабочее дерево: если папку
# удалили, но не закоммитили, проверка прошла бы, а папка всё равно уехала бы в main. Имя
# ветки подставляем целиком, вместе с косой: у ветки вида `chore/312-slug` папка лежит во
# вложенном каталоге.
folder_in_branch() {
    git ls-tree -d --name-only HEAD -- "$1" 2>/dev/null | head -1
}

check_task() {
    number="$1"
    where="$2"
    # Колонку спрашивают там, где она уже должна быть переставлена. На заведении ветки её ещё
    # не двигали — паттерн работы переставляет колонку следующей командой, — и требование здесь
    # отбивало бы первую же команду работы вместе с той, которая его и снимает.
    judge_column="${3:-нет}"
    rt_needs rt_task_state git-guard-delivery || return 0
    state="$(cd "$root" && rt_task_state "$number" 2>/dev/null)" || return 0
    [ -z "$state" ] && return 0

    printf '%s' "$state" | jq -e '.exists' >/dev/null 2>&1 \
        || fault "${where} ссылается на задачу #${number}, которой нет. Проверь номер или заведи задачу — ${task_new}."
    printf '%s' "$state" | jq -e '.open' >/dev/null 2>&1 \
        || fault "задача #${number} закрыта, а у задачи одна ветка. Работа за закрытой задачей заводится новой задачей — ${task_new}."
    printf '%s' "$state" | jq -e '.onBoard' >/dev/null 2>&1 \
        || fault "задачи #${number} нет в очереди работ — правка за ней не видна. Очередь к репозиторию не привязана и задачу сама не забирает; добавь её и сверь — ${board_check}."
    printf '%s' "$state" | jq -e '.assigned' >/dev/null 2>&1 \
        || fault "у задачи #${number} нет исполнителя — по очереди работ не видно, кто её взял. Поставь исполнителя${task_bot:+: }${task_bot}."
    printf '%s' "$state" | jq -e '.numbered' >/dev/null 2>&1 \
        || fault "заголовок задачи #${number} не начинается с её номера — одну работу придётся узнавать по тексту названия. Поправь заголовок и сверь очередь — ${board_check}."

    # Колонка задачи. Ответ очереди работ отдаёт её давно, и не читал её никто: колонку судила
    # только сверка очереди, то есть уже после того, как PR открыт. Задача, оставшаяся в первой
    # колонке, читается по очереди как невзятая — работа при этом сделана и выложена.
    if [ -n "$backlog_column" ] && [ "$judge_column" = "да" ]; then
        column="$(printf '%s' "$state" | jq -r '.status // empty' 2>/dev/null)"
        [ "$column" = "$backlog_column" ] \
            && fault "задача #${number} стоит в колонке «${column}» — по очереди работ она не взята, хотя работа по ней идёт. Переставь её: ${task_move}."
    fi

    return 0
}

# --- заведение ветки ---------------------------------------------------------------------
branch_arg=''
if printf '%s' "$cmd" | grep -qE '(^|[;&|[:space:]])git[[:space:]]+(checkout[[:space:]]+-b|switch[[:space:]]+-c)[[:space:]]'; then
    branch_arg="$(printf '%s' "$cmd" | sed -nE 's/.*git[[:space:]]+(checkout[[:space:]]+-b|switch[[:space:]]+-c)[[:space:]]+([^[:space:];&|]+).*/\2/p' | head -1)"
    branch_arg="${branch_arg%\'}"; branch_arg="${branch_arg#\'}"
    branch_arg="${branch_arg%\"}"; branch_arg="${branch_arg#\"}"
fi

if [ -n "$branch_arg" ]; then
    # Имя, притворяющееся веткой под задачу, но не совпадающее с формой, — это промах в имени,
    # а не осознанная беззадачная ветка. Ловится до первого коммита.
    if printf '%s' "$branch_arg" | grep -qiE '^[A-Za-z]+-[0-9]+'; then
        rt_task_branch_ok "$branch_arg" \
            || deny "BLOCKED: имя ветки «${branch_arg}» не той формы, что принята здесь. Номер у ветки тот же, что у задачи и у заголовка заявки на слияние."
        check_task "$(printf '%s' "$branch_arg" | sed -nE 's/^[A-Za-z]+-([0-9]+).*/\1/p')" "ветка «${branch_arg}»"

        # Условия поставки, известные уже здесь, спрашиваются здесь. Прежде их спрашивали на
        # пуше и на открытии PR — то есть после того, как работа сделана: основание чинится
        # мержем с разбором конфликта, а подпись коммитов — переписыванием всей ветки. В
        # начале работы обе стоят одну команду.
        #
        # Основание: вершина главной ветки обязана лежать в том, от чего растёт новая ветка.
        # Ветка, заведённая от вчерашнего основания, узнаёт об этом на открытии PR — и узнаёт
        # так, что владелец видит её конфликтующей.
        #
        # Судится названное основание, а не вершина рабочей копии: команда, которой основание
        # как раз и берут свежим — `git checkout -b <ветка> origin/<главная>`, — иначе
        # отбивалась бы наравне с той, у которой основание вчерашнее.
        base_arg="$(printf '%s' "$cmd" | sed -nE 's/.*git[[:space:]]+(checkout[[:space:]]+-b|switch[[:space:]]+-c)[[:space:]]+[^[:space:];&|]+[[:space:]]+([^[:space:];&|-][^[:space:];&|]*).*/\2/p' | head -1)"
        base_ref="${base_arg:-HEAD}"
        if git rev-parse --verify --quiet "refs/remotes/origin/${main_branch}" >/dev/null 2>&1 \
            && git rev-parse --verify --quiet "$base_ref" >/dev/null 2>&1 \
            && ! git merge-base --is-ancestor "origin/${main_branch}" "$base_ref" 2>/dev/null; then
            behind="$(git rev-list --count "${base_ref}..origin/${main_branch}" 2>/dev/null)"
            fault "ветка вырастет из основания, в котором нет вершины «${main_branch}» — она ушла вперёд на ${behind:-несколько} коммитов. Возьми свежее основание: git fetch origin && git checkout -b ${branch_arg} origin/${main_branch}."
        fi

        # Второй ярус: локальная ссылка на главную ветку сама могла протухнуть, и тогда молчание
        # первого яруса значит «основание не старше моей ссылки», а не «основание свежее».
        # Ответа нет — ярус молчит, как и везде, где гард ходит в сеть.
        remote_head="$(GIT_HTTP_LOW_SPEED_LIMIT=1000 GIT_HTTP_LOW_SPEED_TIME=5 GIT_TERMINAL_PROMPT=0 \
            git ls-remote origin "refs/heads/${main_branch}" 2>/dev/null | cut -f1)"
        local_head="$(git rev-parse --verify --quiet "refs/remotes/origin/${main_branch}" 2>/dev/null)"
        if [ -n "$remote_head" ] && [ -n "$local_head" ] && [ "$remote_head" != "$local_head" ]; then
            fault "твоя ссылка origin/${main_branch} отстала от удалённой — ${local_head:0:8} против ${remote_head:0:8}. Ветка вырастет из вчерашнего дерева, и увидит это владелец на открытии заявки. Подтяни и повтори: git fetch origin."
        fi

        # Подпись: почта машинной записи объявлена деревом, а рабочая копия её не знает —
        # значит первый же коммит уедет за чужой подписью, и чинить это придётся после пуша
        # силовой отправкой.
        if [ -n "$commit_email" ]; then
            tree_email="$(git config user.email 2>/dev/null)"
            [ -n "$tree_email" ] && [ "$tree_email" != "$commit_email" ] \
                && fault "рабочая копия подписывает коммиты как «${tree_email}», а дерево объявило почтой машинной записи «${commit_email}». Первый же коммит уедет за чужой подписью: git config user.email \"${commit_email}\"."
        fi

        deny_faults
    fi
    # Ветка без номера законна и живёт локально: заявка с неё не откроется.
    exit 0
fi

# --- подпись машинного коммита ------------------------------------------------------------
# Предмет живёт помощником рядом — `git-guard-delivery-signature.sh`: гард дорос до предела
# длины, и подпись среди его предметов самая отдельная. Нет помощника — подпись не судится, а
# работа идёт дальше: это тот же отказ в пользу работы, что и у остальных условий.
# shellcheck disable=SC1090
[ -f "$rt_hooks_dir/git-guard-delivery-signature.sh" ] \
    && . "$rt_hooks_dir/git-guard-delivery-signature.sh" 2>/dev/null
command -v rt_delivery_signature >/dev/null 2>&1 && rt_delivery_signature

# --- снятие черновика --------------------------------------------------------------------
#
# Ревьювера до этой правки не спрашивал никто. Он стоял прозой в правиле, а хостинг запрос
# разбора на самого себя принимает молча и не создаёт: разбор при этом выглядит запрошенным.
# Раньше снятия черновика спросить негде — до открытия заявки ревьювера нет вовсе, — а само
# снятие и есть тот ход, которым работа объявляется готовой.
#
# Ярус сетевой, и молчит он так же, как ярус состояния задачи: нет ответа — нет требования.
#
# Возврат заявки в черновик под требование не подпадает: он делает ровно то, чего гард и
# добивается, — снимает с работы вид готовой.
if printf '%s' "$cmd" | grep -qE '(^|[;&|(]|&&|\|\|)[[:space:]]*(gh[[:space:]]+pr[[:space:]]+ready|glab[[:space:]]+mr[[:space:]]+update[^|;&]*--ready)([[:space:]]|$)' \
    && ! printf '%s' "$cmd" | grep -q -- '--undo'; then
    # Ссылка на заявку необязательна: без неё клиент берёт заявку текущей ветки, и это самая
    # короткая форма вызова. Требовать номер значило бы снимать всё требование одним пробелом.
    # Поэтому берётся первый довод, каким бы он ни был — номер, адрес или имя ветки, — а его
    # отсутствие означает «спроси про текущую ветку».
    pull_ref="$(printf '%s' "$cmd" | sed -nE 's/.*(gh[[:space:]]+pr[[:space:]]+ready|glab[[:space:]]+mr[[:space:]]+update)[[:space:]]+([^[:space:];&|-][^[:space:];&|]*).*/\2/p' | head -1)"
    if rt_needs rt_pull_state git-guard-delivery; then
        pull="$(cd "$root" && rt_pull_state "$pull_ref" 2>/dev/null)" || pull=''
        if [ -n "$pull" ] && printf '%s' "$pull" | jq -e '.exists' >/dev/null 2>&1; then
            # Номер берётся из ответа, а если его там нет — из самой команды: заявка,
            # названная адресом или именем ветки, в отказе должна остаться узнаваемой.
            pull_name="$(printf '%s' "$pull" | jq -r '.number // empty' 2>/dev/null)"
            # Номер пишется с решёткой, а имя ветки или адрес — в кавычках: решётка перед
            # адресом читается как опечатка, а не как ссылка на заявку.
            [ -z "$pull_name" ] && pull_name="$pull_ref"
            case "$pull_name" in
                '') ;;
                *[!0-9]*) pull_name=" «${pull_name}»" ;;
                *) pull_name=" #${pull_name}" ;;
            esac
            printf '%s' "$pull" | jq -e '.reviewed' >/dev/null 2>&1 \
                || fault "у заявки${pull_name} нет разбора: ревьювер не запрошен и отзыва никто не оставлял. Снятый черновик читается как «можно вливать», а вливать некому — назначь ревьювера и повтори."

            # Конфликт приезжает в отданную заявку чужим слиянием, без единого действия её
            # автора: основание, проверенное на открытии, к моменту снятия черновика уже
            # вчерашнее. Снятый черновик читается как «можно вливать», а вливать нечего —
            # владелец открывает заявку и находит там конфликт. Молчание при неизвестной
            # сливаемости остаётся: хостинг считает её заново после каждой правки главной ветки,
            # и «ещё не посчитано» — не «конфликтует».
            printf '%s' "$pull" | jq -e '.conflicting' >/dev/null 2>&1 \
                && fault "заявка${pull_name} конфликтует с главной веткой. Влей её в свою ветку, разбери конфликт и повтори: снятый черновик читается как «можно вливать», а слить эту заявку нельзя."

            # Автор заявки. На открытии судить было нечем, кроме текста команды: личность вызова
            # приходит окружением. Здесь она уже названа хостингом, и это последний ход, где
            # промах ещё исправим — после снятия черновика заявку вливают, а переоткрыть влитую
            # нельзя. Дерево, не назвавшее машинной записи, автора не судит.
            if [ -n "$task_bot" ]; then
                pull_author="$(printf '%s' "$pull" | jq -r '.author // empty' 2>/dev/null)"
                [ -n "$pull_author" ] && [ "$pull_author" != "$task_bot" ] \
                    && fault "заявку${pull_name} открыла запись «${pull_author}», а не машинная «${task_bot}». Автор заявки её ревьювером не бывает, и разбор ей назначить нечем. Автора не сменить — закрой заявку и открой заново${pull_token_hint:+, подставив токен: ${pull_token_hint} …}."
            fi
        fi
    fi
    deny_faults
fi

# --- слияние заявки ----------------------------------------------------------------------
#
# Папку задачи разбирают тем же PR, что и работу. После слияния этого уже никто не сделает:
# работа перешла к следующей задаче, а PR закрыт. Раньше слияния требовать нельзя — пока идёт
# ревью, plan.md нужен на диске, иначе гард хода работы не даст править код.
# Команду ищем от начала строки или после разделителя, а не где угодно в тексте. Иначе гард
# отбивает сообщение, где `gh pr merge` просто упомянут в кавычках, — так он и сработал на
# правке этого же текста. Полностью подстроку в кавычках так не отсечь, но случайное упоминание
# внутри слова или пути мимо уже не пройдёт.
if printf '%s' "$cmd" | grep -qE '(^|[;&|(]|&&|\|\|)[[:space:]]*(gh[[:space:]]+pr[[:space:]]+merge|glab[[:space:]]+mr[[:space:]]+merge|az[[:space:]]+repos[[:space:]]+pr[[:space:]]+update)([[:space:]]|$)'; then
    [ -n "$tasks_dir" ] || exit 0   # ведения работы папкой в дереве нет

    merge_branch="$(git branch --show-current 2>/dev/null)"
    [ -z "$merge_branch" ] && exit 0
    rt_task_branch_ok "$merge_branch" || exit 0   # за беззадачной веткой папки не стоит

    folder="$tasks_dir/$merge_branch"

    # Сначала ищем обход в самой команде — это работает и без сети. Если читать только
    # тело PR, то без сети гард отбил бы слияние, причина которого в этом теле и написана.
    printf '%s' "$cmd" | grep -qiE "$folder_skip_re" && exit 0

    merge_number="$(printf '%s' "$cmd" | sed -nE 's/.*(pr|mr)[[:space:]]+(merge|update)[[:space:]]+([0-9]+).*/\3/p' | head -1)"
    if [ -n "$merge_number" ] && rt_needs rt_report_body git-guard-delivery; then
        body="$(cd "$root" && rt_report_body "$merge_number" 2>/dev/null)"
        [ -n "$body" ] && printf '%s' "$body" | grep -qiE "$folder_skip_re" && exit 0
    fi

    lying="$(folder_in_branch "$folder")"
    [ -n "$lying" ] \
        && deny "BLOCKED: в ветке осталась папка задачи «${lying}» — она уедет в главную. Разобрать её потом будет некому: работа перейдёт к следующей задаче, а этот PR закроется. Перенеси в «${archive_dir:-архив}» то, что объясняет принятые решения, остальное удали и повтори. Если работа вливается частями, поставь в тело PR строку «Task-folder-skip: <причина>»."

    # Запись в архиве спрашиваем только у ветки, которая папку удалила. Иначе проверка
    # цеплялась бы к работе, у которой папки и не было. Без общего предка с главной веткой
    # сравнивать не с чем — тогда молчим.
    [ -n "$archive_dir" ] || exit 0
    base="$(git merge-base "$main_branch" HEAD 2>/dev/null)"
    [ -z "$base" ] && exit 0

    had="$(git ls-tree -d --name-only "$base" -- "$folder" 2>/dev/null | head -1)"
    [ -z "$had" ] && had="$(git log "$base..HEAD" --diff-filter=A --name-only --pretty=format: -- "$folder" 2>/dev/null | head -1)"
    [ -z "$had" ] && exit 0

    gained="$(git diff --name-only --diff-filter=A "$base" HEAD -- "$archive_dir" 2>/dev/null | head -1)"
    [ -z "$gained" ] \
        && deny "BLOCKED: папку задачи удалили, но в «${archive_dir}» ветка ничего не добавила. Удалить проще, чем разобрать, — и вместе с папкой пропадает разбор просьбы, единственная запись слов владельца. Перенеси то, что объясняет принятые решения, одним файлом с понятным именем и повтори."

    exit 0
fi

# --- открытие заявки на слияние ----------------------------------------------------------
# Команду ищем от начала строки или после разделителя — по той же причине, что и слияние:
# упоминание в кавычках командой не является.
printf '%s' "$cmd" \
    | grep -qE '(^|[;&|(]|&&|\|\|)[[:space:]]*(gh[[:space:]]+pr[[:space:]]+create|glab[[:space:]]+mr[[:space:]]+create|az[[:space:]]+repos[[:space:]]+pr[[:space:]]+create)([[:space:]]|$)' \
    || exit 0

branch="$(git branch --show-current 2>/dev/null)"
[ -z "$branch" ] && exit 0   # открепившийся HEAD — не про этот случай

# Локальная ветка без номера законна, а заявка с неё — уже нет: правка, доезжающая до главной
# ветки, начинается с задачи. Это единственное место, где беззадачная ветка упирается.
rt_task_branch_ok "$branch" \
    || deny "BLOCKED: заявка с ветки «${branch}», за которой не стоит задачи. Правка начинается с задачи, видимой в очереди работ: заведи её — ${task_new} — и перенеси работу в ветку с её номером."

number="$(printf '%s' "$branch" | sed -nE 's/^[A-Za-z]+-([0-9]+).*/\1/p')"

title=''
if command -v perl >/dev/null 2>&1; then
    title="$(printf '%s' "$cmd" | perl -0ne '
        if (/(?:--title|-t)(?:=|\s+)(?:"((?:[^"\\]|\\.)*)"|\x27([^\x27]*)\x27|(\S+))/s) {
            print defined $1 ? $1 : (defined $2 ? $2 : $3);
        }
    ' 2>/dev/null)"
fi

if [ -n "$title" ]; then
    printf '%s' "$title" | grep -qE "$title_re" \
        || fault "заголовок заявки не начинается с номера задачи. В списке заявок тела не видно, а строка связи живёт именно там — без номера в заголовке PR с задачей не сопоставить."
    title_number="$(printf '%s' "$title" | sed -nE 's/^\[[A-Za-z]+-([0-9]+)\].*/\1/p')"
    if [ -n "$number" ] && [ -n "$title_number" ]; then
        [ "$title_number" = "$number" ] \
            || fault "в заголовке заявки номер ${title_number}, у ветки — ${number}. Задача, ветка и PR несут один и тот же номер."
    fi
fi

# Главная ветка влита до открытия PR. PR от разошедшейся ветки показывает ревьюверу свою
# правку вперемешку с чужой, а проверки на нём гоняются от устаревшего основания.
#
# Ярусов два, и порядок между ними такой же, как у проверки задачи. Первый читает локальную
# вершину и работает без сети. Второй спрашивает удалённую ссылку — без него молчание гарда
# значит лишь «твоя ссылка не старше твоей ветки», а читается как «главная ветка влита»: ровно
# так открытый PR и оказался конфликтующим, и узнал об этом владелец.
#
# Сеть здесь допустима по той же причине, по которой её зовёт проверка очереди работ ниже:
# отсутствие ответа пропускается молча, и проверка, падающая в самолёте, не отбивает работу.
# Предел ожидания задаётся переменными самого git — внешний `timeout` есть не на всякой машине.
if git rev-parse --verify --quiet "refs/remotes/origin/${main_branch}" >/dev/null 2>&1 \
    && ! git merge-base --is-ancestor "origin/${main_branch}" HEAD 2>/dev/null; then
    behind="$(git rev-list --count "HEAD..origin/${main_branch}" 2>/dev/null)"
    fault "«${main_branch}» ушла вперёд на ${behind:-несколько} коммитов, а в ветку не влита. PR от разошедшейся ветки показывает ревьюверу правку вперемешку с чужой, а проверки на нём идут от устаревшего основания. Влей и повтори: git fetch origin && git merge origin/${main_branch} — порядок и разбор конфликта в паттерне git-workflow-merge."
fi

# Второй ярус: локальная ссылка сама могла протухнуть. Ответа нет — ярус молчит.
remote_main="$(GIT_HTTP_LOW_SPEED_LIMIT=1000 GIT_HTTP_LOW_SPEED_TIME=5 GIT_TERMINAL_PROMPT=0 \
    git ls-remote origin "refs/heads/${main_branch}" 2>/dev/null | cut -f1)"
local_main="$(git rev-parse --verify --quiet "refs/remotes/origin/${main_branch}" 2>/dev/null)"
if [ -n "$remote_main" ] && [ -n "$local_main" ] && [ "$remote_main" != "$local_main" ]; then
    # Возраст ссылки — то, чего исполнитель не видит вовсе, и именно он отличает «ветка
    # отстала» от «я не знаю, отстала ли». Формат `stat` на BSD и на GNU разный, поэтому
    # спрашиваются оба, а не угадывается система.
    fetch_head="$(git rev-parse --git-dir 2>/dev/null)/FETCH_HEAD"
    fetched_at="$(stat -f %m "$fetch_head" 2>/dev/null || stat -c %Y "$fetch_head" 2>/dev/null)"
    age=''
    if [ -n "$fetched_at" ]; then
        age=" Последний git fetch — $(( ( $(date +%s) - fetched_at ) / 60 )) мин. назад."
    fi
    fault "твоя ссылка origin/${main_branch} отстала от удалённой — ${local_main:0:8} против ${remote_main:0:8}.${age} Гард сравнивает ветку с тем, что лежит в дереве, поэтому молчание первого яруса значит «ссылка не старше ветки», а не «главная ветка влита». Влей и повтори: git fetch origin && git merge origin/${main_branch}."
fi

# Личность вызова. Клиент хостинга держит две записи сразу — залогиненную и ту, чей токен стоит
# в окружении вызова, — и какая из них откроет заявку, из текста команды не видно ничем, кроме
# явной подстановки. Читающие вызовы идут от залогиненной и работают, поэтому пишущий выглядит
# таким же обычным; промах всплывает шагом позже, на назначении ревьювера: автор заявки её
# ревьювером не бывает. Чинится это только переоткрытием — автора у заявки не сменить.
#
# Судится текст команды, а не ответ хостинга: спросить, чьим токеном пойдёт вызов, до его
# исполнения нельзя. Дерево, не назвавшее переменной токена, требования не получает.
if [ -n "$pull_token_var" ] \
    && ! printf '%s' "$cmd" | grep -qE "(^|[;&|(]|&&|\|\||[[:space:]])${pull_token_var}="; then
    fault "заявка открывается без токена машинной записи: в команде нет подстановки «${pull_token_var}». Открытая залогиненной записью, она выйдет от владельца — ревьювером его тогда не назначить, и чинится это только переоткрытием.${pull_token_hint:+ Подставь токен: ${pull_token_hint} …}"
fi

check_task "$number" "заявка с ветки «${branch}»" да

# Всё несошедшееся названо здесь, разом: до этой строки собирались условия, каждое из которых
# прежде отбивало вызов в одиночку.
deny_faults

# Сейчас папка ещё нужна: правки по замечаниям ревью идут в эту же ветку, а без plan.md их не
# пропустит гард хода работы. Поэтому здесь только напоминание. Требование стоит на слиянии —
# там папка уже не нужна, а вред от неё как раз и наступает.
if [ -n "$tasks_dir" ]; then
    lying="$(folder_in_branch "$tasks_dir/$branch")"
    [ -n "$lying" ] \
        && hint "В ветке лежит папка задачи «${lying}». Разбери её до слияния, этим же PR: потом за неё уже никто не возьмётся. На слиянии это будет отказ, а не напоминание."
fi

exit 0
