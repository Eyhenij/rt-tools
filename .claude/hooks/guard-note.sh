#!/usr/bin/env bash
# rt-kit v0.20.0 · hooks/guard-note.sh · e29ef1d67461 · правится надстройкой, не здесь
# Запись отбоя гарда. НЕ гард: объявления `rt-hook:` у него нет, к событиям агента он не
# подключается. Его источают сами гарды — тем же приёмом, каким они источают общий хвост отказа.
#
# Зачем он есть. Отбой пишется в наблюдения пятью строками: подключение записи, проверка наличия
# функции, вызов с именем гарда и признаком сессии. Размноженные по всем гардам, эти пять строк
# расходятся при первой же правке приёма — а до тех пор запись стоит в пятой части гардов, и
# сводка отвечает по ней же. Гард, который отбивать умеет, а записывать нет, в сводке не значится
# ни отбивавшим, ни молчащим: спросить о нём нечего.
#
# ЧТО ЗАПИСЫВАЕТСЯ. Имя гарда и признак сессии — ровно то, что писали гарды поодиночке. Чистит
# значения и решает, писать ли вообще, запись наблюдений; здесь только сборка вызова.
#
# ОТКАЗ В ПОЛЬЗУ РАБОТЫ. Записи может не быть вовсе — файла нет, дерево выключило наблюдения,
# каталог недоступен. Гард, упавший на записи отбоя, останавливал бы работу ради статистики.

# Отбой гарда в наблюдения. Первый параметр — имя гарда, второй — ввод хука или готовый признак
# сессии; без второго запись идёт без признака сессии, и заход в счёт заходов не попадает.
#
#   rt_guard_note docs-guard "$input"
rt_guard_note() {
    local rt_gn_dir rt_gn_sid
    [ -n "$1" ] || return 0

    rt_gn_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
    # shellcheck disable=SC1090
    [ -f "$rt_gn_dir/observe.sh" ] && . "$rt_gn_dir/observe.sh" 2>/dev/null
    command -v rt_note >/dev/null 2>&1 || return 0

    # Ввод хука приходит как есть: признак сессии вынимается здесь, чтобы гард не повторял разбор.
    # Значение без фигурных скобок считается уже готовым признаком.
    rt_gn_sid="$2"
    case "$rt_gn_sid" in
        \{*) rt_gn_sid="$(printf '%s' "$2" | jq -r '.session_id // "nosession"' 2>/dev/null)" ;;
    esac

    if [ -n "$rt_gn_sid" ]; then
        rt_note guard-deny "res=$1" "sid=$rt_gn_sid"
    else
        rt_note guard-deny "res=$1"
    fi

    return 0
}
