/**
 * Метки, которые читают все файлы рёбер семьи админки: вход, общий слой, контракт и пакеты.
 *
 * Лежат отдельно от рёбер, потому что рёбра семьи не умещаются в один файл: раздел людей описан
 * своим файлом, и обоим нужны одни и те же имена. Файл не оканчивается на `.config.mjs`
 * намеренно: проверка раскладки читает файлы рёбер по этому окончанию, а здесь рёбер нет.
 */

/** Состояние входа. Живёт в одном экземпляре: второй ответил бы на вопрос «вошёл ли» иначе. */
export const AUTH_DATA_ACCESS = 'scope:message-bus-admin-auth-data-access';

/**
 * Публикуемые пакеты дерева: киты, основание и утилиты. Стоят в списке у каждой либы админки —
 * из них она и собрана целиком. Метка нужна именно как имя цели: без неё либа с объявленным
 * списком не видит пакет вовсе, потому что первое подходящее правило выигрывает и до общего
 * разрешения дело не доходит.
 */
export const PACKAGE = 'scope:package';

/**
 * Общий слой админки: словарь, обращение к операциям чтения, выборка в адресе, основа
 * списочного стора и общий вид страницы списка. Механика, а не предмет: разделы груза зовут её
 * все три, и разложенная по ним заново она расходилась бы молча.
 */
export const CORE_UTIL = 'scope:message-bus-admin-common-core-util';
export const CORE_API = 'scope:message-bus-admin-common-core-api';
export const CORE_DATA_ACCESS = 'scope:message-bus-admin-common-core-data-access';
export const CORE_UI = 'scope:message-bus-admin-common-core-ui';
export const CORE_FEATURE = 'scope:message-bus-admin-common-core-feature';

/**
 * Форма того, что отдаёт приёмник: страница, выборка и дерево. Её знают обе стороны, и админка
 * читает её у источника, а не заводит свою копию — копия разошлась бы с контрактом молча.
 */
export const CONTRACT = 'scope:message-bus-common';
