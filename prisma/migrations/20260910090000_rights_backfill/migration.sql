-- Перенос прежнего доступа на модель прав.
--
-- Миграция `20260908050000_account_role_and_rights` завела роли, точечные правки и колонку роли у
-- записи — и не положила ни одной строки. У всех записей, заведённых до неё, роль осталась пустой,
-- а пустая роль означает пустой набор прав: человек входит, и ни один раздел ему не открыт.
--
-- До той правки каждая заведённая запись видела все четыре раздела и закрывала любую запись груза.
-- Здесь этот доступ и переносится: заводится роль владельца со всеми правами закрытого набора, и
-- она проставляется записям, у которых роли нет.
--
-- Набор прав повторяет закрытый набор из общей либы (`libs/message-bus-common/src/lib/rights.ts`).
-- Строки списка сверяются с ним тестом: разойдясь, они дали бы роль, которая молчит о праве, — а
-- молчание правом не считается нигде.
--
-- Запись, у которой роль уже стоит, не трогается: её назначили после правки прав, и затирать это
-- миграцией нельзя. Запись, заведённая после правки прав, роли не получала и не должна — доступа,
-- который надо перенести, у неё не было.

INSERT INTO "role" ("id", "key", "name", "rights")
VALUES (
    gen_random_uuid(),
    'owner',
    'Владелец',
    ARRAY[
        'postmortems:read',
        'postmortems:manage',
        'proposals:read',
        'proposals:manage',
        'summaries:read',
        'invites:read',
        'invites:manage',
        'accounts:read',
        'accounts:manage',
        'roles:manage'
    ]
)
ON CONFLICT ("key") DO NOTHING;

UPDATE "account"
SET "roleId" = (SELECT "id" FROM "role" WHERE "key" = 'owner')
WHERE "roleId" IS NULL;
