-- Право чтения чата — роли владельца.
--
-- Набор прав закрыт кодом, и новое право `chat:read` закрывает новый раздел «Чат». Право
-- выдаётся тем же изменением, что завело раздел: иначе владелец после выкатки видит приёмник без
-- него. Что человек увидит внутри раздела, решает не право, а запись оператора чата.
--
-- Идемпотентна: право дописывается роли владельца только там, где его ещё нет.
UPDATE "role"
SET "rights" = array_append("rights", 'chat:read')
WHERE "key" = 'owner'
  AND NOT ('chat:read' = ANY("rights"));
