-- Право чтения использования правил — роли владельца.
--
-- Набор прав закрыт кодом, и новое право `usage:read` закрывает новый раздел «Использование».
-- Право выдаётся тем же изменением, что закрыло операции: иначе владелец после выкатки видит
-- приёмник без нового раздела, а роль разбора груза раздел не читает — это чтение человека.
--
-- Идемпотентна: право дописывается роли владельца только там, где его ещё нет.
UPDATE "role"
SET "rights" = array_append("rights", 'usage:read')
WHERE "key" = 'owner'
  AND NOT ('usage:read' = ANY("rights"));
