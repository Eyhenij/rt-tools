#!/usr/bin/env node
// rt-kit v0.9.1 · checks/check-prose-style.mjs · 0f3e0c3a5f42 · правится надстройкой, не здесь
/**
 * Проверка слога: канцелярит и обороты, которых в этом дереве не пишут.
 *
 * Правило о текстах требует простых слов, а проверки на это не было: формулировочные
 * договорённости закон оставлял автору целиком, и держались они памятью того, кто пишет.
 * Держались плохо — владелец читает написанное и видит машинный слог там, где договорённость
 * требует человеческого.
 *
 * Ловится не стиль вообще, а перечисленные признаки, и каждый назван вместе с заменой: список
 * запретов без замены читается как запрет писать, и автор обходит его, а не правит текст.
 *
 * Чего проверка не видит и видеть не будет: связности, повторов мысли, верности утверждения.
 * Абзац из коротких предложений с чистыми словами проходит её целиком, ничего при этом не
 * значая. Это её граница, а не обещание.
 *
 * Ненулевой код возврата и перечень находок: файл, строка, что нашли, чем заменить.
 *
 * Границы слова пишутся оглядкой на буквы, а не `\b`: он считается по ASCII, кириллица под `\w`
 * не подпадает, и образец с ним молча не срабатывает ни разу.
 */
import { readFileSync } from 'node:fs';

/** Предел длины предложения в словах. Дальше читатель теряет начало. */
const WORDS_LIMIT = 40;

/**
 * Признаки канцелярита. Каждый — образец и то, чем его заменить: без замены находка
 * читается как запрет писать.
 */
const MARKS = [
    [/(?<![а-яёА-ЯЁ])является(?![а-яёА-ЯЁ])/giu, 'сказать глаголом: «это», «работает», «стоит»'],
    [/(?<![а-яёА-ЯЁ])осуществля(ет|ется|ть)(?![а-яёА-ЯЁ])/giu, 'назвать само действие: «делает», «идёт»'],
    [/(?<![а-яёА-ЯЁ])производится(?![а-яёА-ЯЁ])/giu, 'кто производит — тот и подлежащее'],
    [/(?<![а-яёА-ЯЁ])в целях(?![а-яёА-ЯЁ])/giu, '«чтобы»'],
    [/(?<![а-яёА-ЯЁ])с целью(?![а-яёА-ЯЁ])/giu, '«чтобы»'],
    [/(?<![а-яёА-ЯЁ])в случае, если(?![а-яёА-ЯЁ])/giu, '«если»'],
    [/(?<![а-яёА-ЯЁ])при условии, что(?![а-яёА-ЯЁ])/giu, '«если»'],
    [/(?<![а-яёА-ЯЁ])в рамках(?![а-яёА-ЯЁ])/giu, 'назвать отношение прямо: «в», «при», «для»'],
    [/(?<![а-яёА-ЯЁ])на основании(?![а-яёА-ЯЁ])/giu, '«по»'],
    [/(?<![а-яёА-ЯЁ])посредством(?![а-яёА-ЯЁ])/giu, '«через», «командой», «вызовом»'],
    [/(?<![а-яёА-ЯЁ])данн(ый|ая|ое|ые)(?![а-яёА-ЯЁ])/giu, '«этот» или ничего'],
    [/(?<![а-яёА-ЯЁ])соответствующ(ий|ая|ее|ие)(?![а-яёА-ЯЁ])/giu, 'назвать, чему именно соответствует'],
    [/(?<![а-яёА-ЯЁ])необходимо(?![а-яёА-ЯЁ])/giu, '«надо» или повелительное наклонение'],
    [/(?<![а-яёА-ЯЁ])должен быть (выполнен|произведён|осуществлён)(?![а-яёА-ЯЁ])/giu, 'сказать, кто это делает'],
    [/(?<![а-яёА-ЯЁ])имеет место(?![а-яёА-ЯЁ])/giu, '«есть», «случается»'],
    [/(?<![а-яёА-ЯЁ])в дальнейшем(?![а-яёА-ЯЁ])/giu, '«дальше», «потом»'],
    [/(?<![а-яёА-ЯЁ])таким образом(?![а-яёА-ЯЁ])/giu, 'убрать или сказать, что из чего следует'],
    [/(?<![а-яёА-ЯЁ])следует отметить(?![а-яёА-ЯЁ])/giu, 'убрать: если стоит отметить — отмечай'],
    [/(?<![а-яёА-ЯЁ])как уже было сказано(?![а-яёА-ЯЁ])/giu, 'убрать: сказанное дважды не становится вернее'],
];

/** Слова левой колонки словаря: они не пишутся и не произносятся нигде. */
const GLOSSARY_BANS = [
    [/(?<![а-яёА-ЯЁ])таск[аиуе](?![а-яёА-ЯЁ])/giu, 'задача'],
    [/(?<![а-яёА-ЯЁ])тикет[а-яё]*(?![а-яёА-ЯЁ])/giu, 'задача'],
    [/(?<![а-яёА-ЯЁ])пул-реквест[а-яё]*(?![а-яёА-ЯЁ])/giu, 'PR'],
    [/(?<![а-яёА-ЯЁ])джоб[аыуе](?![а-яёА-ЯЁ])/giu, 'шаг конвейера'],
    [/(?<![а-яёА-ЯЁ])пайплайн[а-яё]*(?![а-яёА-ЯЁ])/giu, 'конвейер'],
    [/(?<![а-яёА-ЯЁ])хендофф[а-яё]*(?![а-яёА-ЯЁ])/giu, 'передача'],
    [/(?<![а-яёА-ЯЁ])бэклог[а-яё]*(?![а-яёА-ЯЁ])/giu, 'очередь работ'],
    [/(?<![а-яёА-ЯЁ])скилл[а-яё]*(?![а-яёА-ЯЁ])/giu, 'правило, паттерн или скил без закона'],
];

const CODE_FENCE = /^\s*```/;

/**
 * Заголовки, которые совпадают с образцом канцелярита, но прозой не являются: это имена
 * обязательных разделов спека, и набор разделов требует их дословно.
 *
 * Перечислены поимённо, а не сняты правилом: слово «данные» в предложении канцеляритом быть не
 * перестаёт — «данные требования» ловится по-прежнему. Без этого исключения ни один новый спек
 * не написать вовсе: набор разделов требует заголовок, а проверка слога его отбивает, и оба
 * требования верны каждое по-своему.
 */
const HEADING_EXCEPTIONS = new Set(['Данные']);

/** Заголовок, чьё имя названо исключением: судить в нём нечего — это имя раздела, а не фраза. */
function isExemptHeading(line) {
    const heading = line.match(/^\s*#{1,6}\s+(.+?)\s*$/);

    return heading !== null && HEADING_EXCEPTIONS.has(heading[1]);
}

/** Строки вне блоков кода: в блоках лежат команды и вывод, и слог там не судится. */
function proseLines(text) {
    const out = [];
    let inFence = false;
    text.split('\n').forEach((line, index) => {
        if (CODE_FENCE.test(line)) {
            inFence = !inFence;
            return;
        }
        if (inFence) return;
        if (isExemptHeading(line)) return;
        out.push([index + 1, line]);
    });
    return out;
}

/** Находки одной строки: образец, что нашли, чем заменить. */
function findingsIn(line) {
    const found = [];
    [...MARKS, ...GLOSSARY_BANS].forEach(([re, fix]) => {
        const hit = line.match(re);
        if (hit) found.push([hit[0], fix]);
    });
    return found;
}

/** Слишком длинное предложение: читатель теряет начало раньше, чем автор доходит до конца. */
function longSentences(line) {
    return line
        .split(/(?<=[.!?])\s+/)
        .filter((sentence) => sentence.trim().split(/\s+/).length > WORDS_LIMIT)
        .map((sentence) => [`${sentence.trim().split(/\s+/).length} слов в предложении`, `делить: предел ${WORDS_LIMIT}`]);
}

export function checkProse(text) {
    return proseLines(text).flatMap(([number, line]) =>
        [...findingsIn(line), ...longSentences(line)].map(([what, fix]) => ({ line: number, what, fix }))
    );
}

const files = process.argv.slice(2);
if (files.length > 0) {
    const problems = files.flatMap((file) =>
        checkProse(readFileSync(file, 'utf8')).map((p) => `  ${file}:${p.line} — «${p.what}» → ${p.fix}`)
    );
    if (problems.length > 0) {
        console.error(`check-prose-style: находок ${problems.length}\n`);
        problems.forEach((p) => console.error(p));
        console.error('\nСлог — правило о текстах. Проверка видит перечисленные признаки и только их.');
        process.exit(1);
    }
    console.log(`check-prose-style: проверено файлов ${files.length}, находок нет`);
}
