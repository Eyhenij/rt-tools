/**
 * Параметры съёмки истории: что снимается, чем и в каком окне.
 *
 * Набор снимаемого задан **вычитанием**: снимается всё, кроме помеченного `storySnapshotSkip`.
 * Обратный порядок — «снимается помеченное» — даёт зелёный прогон и ноль проверенных пикселей у
 * каждой матрицы, при которой признак забыли поставить, и отличить это от исправного прогона
 * нечем. Ошибка в перечислении молчит, ошибка в вычитании краснеет.
 *
 * Причина у исключения обязательна: она — единственное, чем «не снимается» отличается от
 * «забыли». Пустая причина роняет прогон.
 *
 * Обвязка витрины: `tsconfig.lib.json` исключает `src/showcase/**`, в пакет не уезжает.
 */

/**
 * Признак корня показа. Кадр берётся по нему, а не по всей странице: порог расхождения считается
 * от площади кадра, и в странице, где сетка занимает малую долю, поехавшая ячейка проходит молча.
 *
 * Стоит на хостах `app-story-grid`, `app-story-row` и `app-story-themes`. В самих декораторах
 * записан литералом: метаданные компонента читаются сборщиком статически, и вычисляемый ключ там
 * не годится.
 */
export const STORY_SNAPSHOT_ROOT_ATTRIBUTE: string = 'data-story-root';

/** Размер базового кадра. История, которой нужен другой, называет его сама. */
export const STORY_SNAPSHOT_VIEWPORT: { readonly width: number; readonly height: number } = { width: 1280, height: 720 };

/** Параметры съёмки одной истории. Лежат в `parameters.snapshot`, читаются обвязкой прогона. */
export interface IStorySnapshotParameters {
    /**
     * Причина, по которой история не снимается. Пустая строка — отказ прогона, а не пропуск:
     * пометка без причины возвращает тот самый молчаливый пропуск, ради которого набор и задан
     * вычитанием.
     */
    readonly skip?: string;

    /**
     * Ширины окна для кадров порога — по одной на каждый порог, который называет сам компонент.
     * Собираются функциями ниже, а не числами на месте: сторона порога выводится из медиазапроса,
     * и «768» против «767» иначе решается молча тем, кто пишет историю.
     */
    readonly widths?: readonly number[];

    /**
     * Кадр целой страницы вместо корня показа. Для истории, у которой показ рисует не сетка.
     *
     * Страницу, не влезающую в базовый кадр, обвязка снимает не съёмкой за пределы окна, а
     * раздвинутым до неё окном: съёмка за пределы окна трогает страницу под затвором, и то, что
     * считается от размеров окна, съезжает прямо в кадре. Отсюда следствие, которое видно в
     * эталоне: у такой истории `100vh` и `100vw` считаются от раздвинутого окна, и показ
     * занимает кадр целиком, без полосы фона по краю.
     */
    readonly fullPage?: boolean;

    /**
     * Узел перекрытия, который история открывает сама и обещает показать в кадре.
     *
     * Названный, он делает две вещи разом: обвязка не уводит указатель перед съёмкой — панель,
     * открытая наведением, гаснет от этого с отсрочкой в сотню миллисекунд, — и отказывает, если
     * к моменту кадра узла на странице нет. Без второй половины кадр с закрытой панелью
     * неотличим от исправной истории, у которой панели и не должно быть.
     */
    readonly overlay?: string;
}

/** Ветка параметров истории, в которой обвязка ищет съёмку. */
export interface IStorySnapshotHost {
    readonly snapshot: IStorySnapshotParameters;
}

/**
 * Снять историю со съёмки, назвав причину.
 *
 * Причина попадает в вывод прогона, поэтому пишется для того, кто читает отказ, а не для автора:
 * «значения по умолчанию уже стоят ячейкой в матрице этого компонента» — годится, «не нужно» —
 * нет.
 */
export function storySnapshotSkip(reason: string): IStorySnapshotHost {
    return { snapshot: { skip: reason } };
}

/**
 * Ширина окна для правила вида `width <= 768px`: само значение порога, потому что равенство
 * правило включает.
 */
export function storyWidthAtMost(threshold: number): number {
    return threshold;
}

/**
 * Ширина окна для правила вида `width >= 1441px`: тоже само значение порога. Отдельная функция
 * рядом с `storyWidthAtMost` не ради вычисления, а ради того, чтобы в истории было видно, какую
 * сторону порога она проверяет: один из порогов кита шире базового кадра, и «узким» такой кадр
 * не является.
 */
export function storyWidthAtLeast(threshold: number): number {
    return threshold;
}

/**
 * Ширина окна для строгого правила вида `width > 1080px`: порог плюс пиксель. Само значение
 * порога сюда не годится — при нём правило ещё не действует, и кадр проверил бы ту сторону, где
 * его нет.
 */
export function storyWidthOver(threshold: number): number {
    return threshold + 1;
}

/**
 * Ширина окна для строгого правила вида `width < 480px`: порог минус пиксель, по той же причине,
 * что и у `storyWidthOver`.
 */
export function storyWidthUnder(threshold: number): number {
    return threshold - 1;
}

/** Пороги ширины для истории компонента, который называет ширину сам. */
export function storySnapshotWidths(...widths: readonly number[]): IStorySnapshotHost {
    return { snapshot: { widths } };
}
