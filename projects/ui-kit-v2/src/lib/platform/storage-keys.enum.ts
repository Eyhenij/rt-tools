/**
 * Ключи браузерного хранилища, которые кит занимает под себя. Единый реестр
 * вместо констант, разбросанных по компонентам: так видно весь занятый
 * неймспейс и не возникает двух ключей на одно и то же. Значения читает и пишет
 * только `StorageService` из `@rt-tools/core`.
 *
 * Неймспейс `rt.` отделяет их от ключей приложения-потребителя.
 */
export enum ERtStorageKeys {
    /** Выбранная тема оформления: переживает перезагрузку и смену пользователя */
    Theme = 'rt.theme',

    /** Префикс, а не полный ключ: итоговый вид — `rt.table.columns.<tableId>`. */
    TableColumnsPrefix = 'rt.table.columns.',
}
