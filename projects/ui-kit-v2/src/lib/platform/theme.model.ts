/**
 * Тема оформления. Выбор и вид — две разные вещи, и кит их не смешивает.
 *
 * Выбор человека хранится, вид применяется к `<html data-theme="...">`.
 * «За машиной» — выбор наравне с двумя другими, а не отсутствие выбора: он
 * разрешается в один из двух видов, и третьего признака на корне не бывает.
 * Хранение — через `StorageService` из `@rt-tools/core` (см. `ThemeService`).
 */
export namespace ITheme {
    /** Вид, в котором страница нарисована. Третьего не бывает. */
    export type Mode = 'light' | 'dark';

    /** Что выбрано: два вида и «идти за настройкой машины». */
    export type Choice = Mode | 'auto';
}
