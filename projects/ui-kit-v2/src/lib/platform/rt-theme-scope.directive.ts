import { Directive, InputSignal, input } from '@angular/core';

import { ITheme } from './theme.model';

/**
 * Местный кусок темы: узел рисует своё поддерево в своей теме, а страница
 * вокруг остаётся как была.
 *
 * Работает в обе стороны — тёмная карточка внутри светлой страницы и светлая
 * внутри тёмной, — и переключает весь набор свойств, а не часть: фон, текст,
 * рамки, тени. Ближний признак выигрывает у дальнего, повторённый внутри
 * такого же ничего не меняет, а снятый возвращает поддерево к теме страницы.
 *
 * Выбора человека и хранилища не трогает вовсе: это слово разметки об одном
 * месте, а не переключение темы.
 *
 * ```html
 * <section [rtTheme]="'dark'">…</section>
 * ```
 *
 * Пустое значение темой не считается и признака не ставит.
 */
@Directive({
    selector: '[rtTheme]',
    host: {
        '[attr.data-theme]': 'rtTheme() || null',
    },
})
export class RtThemeScopeDirective {
    public readonly rtTheme: InputSignal<ITheme.Mode | ''> = input<ITheme.Mode | ''>('');
}
