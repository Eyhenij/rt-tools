import { IRtIcon } from '../icon/rt-icon.model';

/**
 * Контракты полосы массовых действий. Один корневой неймспейс с префиксом `I`.
 *
 * Отличие от договора первого кита одно и оно намеренное: произвольного объекта
 * стилей на действии здесь нет. Вид кнопки называется именем из набора кита —
 * значение цвета в разметку не приходит вовсе.
 */
export namespace IRtActionBar {
    /** Вид действия: тем же именем, каким его зовёт кнопка кита. */
    export type Look = 'plain' | 'danger';

    /**
     * Одно нажатие в полосе. Либо `run` — то, что действие делает, — либо `menu`:
     * вложенный список. Действие с вложенным списком само не срабатывает: оно
     * заголовок группы, и запуск его наравне с раскрытием запустил бы то, чего
     * человек не выбирал.
     */
    export interface Action {
        readonly label: string;
        readonly icon?: IRtIcon.Name;
        readonly look?: IRtActionBar.Look;
        readonly run?: () => void;
        readonly menu?: readonly IRtActionBar.Action[];
    }

    /**
     * Настройка полосы целиком. Счёт приходит парой: сколько выбрано и сколько
     * всего. Полоса ничего из этого не считает — ей дают числа.
     */
    export interface Config {
        readonly selected: number;
        readonly total: number;
        readonly actions: readonly IRtActionBar.Action[];
    }
}

/**
 * Сколько полоса держится в разметке после закрытия — ровно длительность ухода
 * из стилей.
 *
 * Число живёт здесь, а не только в правиле стиля: разметку снимает держатель, и,
 * разойдясь с правилом, он обрывает уход на полпути. Держателю и стилям нужно
 * одно и то же число, поэтому оно объявлено рядом с договором, а не в одном из них.
 */
export const RT_ACTION_BAR_LEAVE_MS: number = 300;
