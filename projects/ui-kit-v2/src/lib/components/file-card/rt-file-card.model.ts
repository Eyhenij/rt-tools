/**
 * Модель `<rt-file-card>`: один корневой неймспейс с префиксом `I`.
 */
export namespace IRtFileCard {
    /**
     * Плотность карточки. Меняет только метрики — отступы, кегли и размеры
     * иконок; состав остаётся прежним, как у `rt-icon-button`. Маппинг на
     * пиксели — в SCSS (`--rt-file-card-*`) и в карте размеров иконок.
     */
    export type Size = 'sm' | 'md' | 'lg';

    /**
     * Нормализованное представление файла для карточки. Источник может быть разным
     * (локальный `File`, сохранённый DTO, вложение сообщения) — caller сводит
     * его к этой форме.
     */
    export interface Model {
        /** Имя файла с расширением — из него выводятся заголовок и иконка типа. */
        name: string;

        /** Размер в байтах. `null` → бейдж размера скрыт (размер неизвестен). */
        sizeBytes: number | null;
    }
}
