/**
 * Модель `<rt-theme-toggle>`: один корневой неймспейс с префиксом `I`.
 */

export namespace IRtThemeToggle {
    /**
     * Внешний вид переключателя:
     *  - `icon` — круглая icon-кнопка с иконкой противоположной темы;
     *  - `switch` — тоггл-рельса с иконками солнца и луны внутри трека.
     */
    export type Appearance = 'icon' | 'switch';
}
