/**
 * Контракты `rt-stat-tile` — KPI-плитка с базой сравнения.
 * Один корневой неймспейс с префиксом `I`, внутри литеральные union'ы,
 * используемые как контракт `input()` сигналов компонента.
 */
export namespace IRtStatTile {
    /** Направление изменения — определяет цвет и иконку строки дельты. */
    export type Direction = 'up' | 'down' | 'flat' | 'unknown';

    /**
     * Изменение к одной базе сравнения.
     *
     * - `percent` — уже посчитанное изменение в процентах; `null` означает
     *   «база нулевая или данных нет», и плитка рисует «—», а не «+100 %».
     * - `label` — подпись базы («к прошлому периоду», «к прошлому году»).
     * - `baseline` — необязательное «было X» той же строкой.
     */
    export interface Delta {
        readonly percent: number | null;
        readonly label: string;
        readonly baseline?: string;
    }
}
