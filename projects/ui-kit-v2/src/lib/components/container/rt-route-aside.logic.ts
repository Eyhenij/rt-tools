/**
 * Абсолютные команды приводятся к сегментам от корня: внутри объекта `outlets`
 * ведущий слэш отдельным сегментом не разбирается.
 *
 * Нужно это затем, что уход панели на связанную запись обязан снять её аутлет
 * той же навигацией. Абсолютные команды меняют только первичную ветку, поэтому
 * панель, открытая в корне приложения, переход переживает: адрес получается с
 * аутлетом, под который в корне маршрута нет, и роутер отклоняет навигацию
 * молча — адрес остаётся прежним, а приложение застревает на панели, которой на
 * экране уже нет.
 */
export function rootSegmentsOf(commands: readonly unknown[]): unknown[] {
    const [head, ...rest]: readonly unknown[] = commands;

    if (typeof head !== 'string' || !head.startsWith('/')) {
        return [...commands];
    }

    return [...head.split('/').filter(Boolean), ...rest];
}
