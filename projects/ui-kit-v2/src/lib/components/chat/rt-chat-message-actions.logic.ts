import { IRtChat } from './rt-chat.model';

/**
 * Есть ли у реплики хотя бы одно доступное действие потребителя.
 *
 * Признак приходит предикатом от экрана, а не подсчётом отрисованных пунктов меню:
 * содержимое спроецированного шаблона известно только после отрисовки, и кнопка
 * успевала бы мигнуть на первом кадре.
 *
 * Предикат не задан — у реплики есть действия: экран, который ничего не гейтит,
 * показывает кнопку меню. Так же это устроено у строки таблицы, и расхождение между
 * двумя точками проекции одного кита читалось бы дефектом.
 */
export function messageHasAvailableActions(message: IRtChat.Message, hasActions: IRtChat.MessageActionsPredicate | null): boolean {
    return hasActions === null ? true : hasActions(message);
}
