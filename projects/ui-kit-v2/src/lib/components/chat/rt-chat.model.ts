import { IQuillDelta } from '../../util';

/**
 * Модель общего чат-компонента `rt-chat`: один корневой неймспейс
 * с префиксом `I`. Доменные стора маппят свою модель сообщения в `Message`, а сам
 * `rt-chat` ничего не знает о доменных сущностях — только рисует тред и композер.
 */
/**
 * Судьба своего сообщения в ленте: пока летит на сервер — часы, после записи —
 * двойной чек, после того как собеседник открыл переписку — тот же чек синим,
 * при обрыве — «!» с повтором. Входящие сообщения статуса не имеют.
 */
export enum ERtChatMessageStatus {
    Sending = 'sending',
    Sent = 'sent',
    Read = 'read',
    Failed = 'failed',
}

export namespace IRtChat {
    /** Алиас enum'а для доменных мапперов, работающих через неймспейс. */
    export type MessageStatus = ERtChatMessageStatus;

    /** Вложение сообщения — домен маппит свой ресурс, скачивание по `public_id`. */
    export interface Attachment {
        id: number;
        /** Обезличенное имя для карточки файла. */
        name: string;
        /** Непрозрачный идентификатор файла — консюмер качает blob по нему. */
        publicId: string;
    }

    /**
     * Одно сообщение треда в уже подготовленной для отображения форме: автор —
     * готовый лейбл (домен решает, как его собрать), `own`/`system` — флаги
     * выравнивания и стиля, дата — ISO-строка (форматируется `DatePipe` внутри).
     */
    export interface Message {
        /** Идентификатор сообщения — ключ `@for track`. */
        id: number | string;
        /** Клиентский временный id оптимистичного сообщения (до ответа сервера). */
        tempId?: string;
        /**
         * Статус своего сообщения. Отсутствует у входящих: чужому сообщению
         * нечего сообщать о доставке.
         */
        status?: MessageStatus;
        /** Готовый лейбл автора (доменный authorLabel). */
        author: string;
        /** Сообщение текущего пользователя — выравнивается вправо, акцентный фон. */
        own: boolean;
        /** Признак системного сообщения (рендерится обычным входящим пузырём). */
        system?: boolean;
        text: string;
        /**
         * Rich-тело (Quill delta) — при наличии рендерится вместо plain `text`
         * через `rt-delta-view`. `null`/отсутствует ⇒ показываем `text`.
         */
        delta?: IQuillDelta | null;
        /** ISO-дата создания. */
        createdAt: string;
        /** URL вложения (если есть) — наличие включает карточку файла. */
        fileUrl?: string | null;
        /** Имя вложения для отображения в карточке. */
        fileName?: string | null;
        /**
         * Вложения сообщения (несколько файлов). Непустой массив имеет приоритет
         * над legacy-парой `fileUrl`/`fileName` (та равна первому вложению).
         */
        attachments?: readonly Attachment[];
        /** Внешняя ссылка-призыв (привязка Telegram) — наличие включает кнопку-ссылку. */
        deepLink?: string | null;
        /** Подпись кнопки-ссылки `deepLink` (домен решает текст по состоянию). */
        deepLinkLabel?: string | null;
        /** Сообщение помечено удалённым — рендерится плейсхолдером вместо содержимого. */
        deleted?: boolean;
        /** Показать действие «удалить» на этом сообщении (домен решает по правам/направлению). */
        canDelete?: boolean;
        /**
         * Текст подтверждения перед удалением. Задан — клик по корзине открывает
         * confirm-попап с этим текстом, удаление уходит только после подтверждения.
         * Пусто/undefined — удаление сразу по клику (домен без confirm-семантики).
         */
        deleteConfirm?: string;
    }

    /** Payload отправки: текст + файлы (пусто/undefined, если вложения выключены). */
    export interface SendPayload {
        text: string;
        files?: File[];
        /**
         * Rich-тело строкой JSON (`JSON.stringify(getContents())`) — взаимоисключимо
         * с непустым `text`. При наличии домен шлёт delta-канал (`message:""`).
         */
        delta?: string | null;
    }
}
