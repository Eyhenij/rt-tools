export namespace IRtProgressBar {
    /** `determinate` — доля из `value`, `indeterminate` — бегущая полоса, когда доля неизвестна. */
    export type Mode = 'determinate' | 'indeterminate';

    /** Цвет заполнения — заливка кнопочной палитры. */
    export type Color = 'primary' | 'secondary' | 'info' | 'success' | 'warning' | 'danger';
}
