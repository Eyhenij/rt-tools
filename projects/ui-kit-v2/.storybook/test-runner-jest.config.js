import { getJestConfig } from '@storybook/test-runner';

/**
 * Настройки сборщика тестов для съёмки витрины второго кита.
 *
 * Прогон снимков ищет файл с этим именем в каталоге витрины и, найдя, отдаёт его сборщику вместо
 * своего умолчания. Файл лежит здесь, а не в корне дерева, намеренно: корневой прочитал бы и
 * прогон первого кита, а тот по решению эпика «Один кит» не правится вовсе — включая условия, при
 * которых сняты его эталоны.
 *
 * Заводится он ради двух строк ниже. До них кадр зависел от машины: пояс брался у неё, язык —
 * у браузера. Перевод на летнее время двигал время в переписке на час, чужая настройка браузера
 * переворачивала дату в родных полях, и набор снимков краснел пятнадцатью кадрами, ни один из
 * которых не говорил о вёрстке.
 *
 * Договорённость, которую этот файл исполняет, — `docs/specs/ui-kit-v2/`.
 */
const base = getJestConfig();

/**
 * Настроек две, и одной не хватает — это замерено, а не выведено.
 *
 * `locale` контекста меняет `navigator.language` и заголовок запроса, но формат родного
 * `<input type="date">` не трогает: его рисует сам браузер по языку своего запуска. Замер на
 * одной истории выбора даты: без настроек `03/15/2026` и `09:30 AM`, с одним `locale` — то же
 * самое, с языком запуска — `15.03.2026` и `09:30`.
 *
 * Пояс, наоборот, слушается контекста: сеанс отладочного протокола его тоже задаёт, а язык —
 * нет. Поэтому обе двери открыты сразу, каждая для своего.
 */
const SNAPSHOT_LOCALE = 'ru-RU';

/**
 * Пояс съёмки. `UTC` взят потому, что он один и тот же на любой машине и не переводится на летнее
 * время: именно перевод и развёл кадры переписки с эталонами на час, а чужая машина — на пять.
 */
const SNAPSHOT_TIMEZONE = 'UTC';

export default {
    ...base,
    testEnvironmentOptions: {
        ...base.testEnvironmentOptions,
        'jest-playwright': {
            ...base.testEnvironmentOptions?.['jest-playwright'],
            launchOptions: { args: [`--lang=${SNAPSHOT_LOCALE}`] },
            contextOptions: { locale: SNAPSHOT_LOCALE, timezoneId: SNAPSHOT_TIMEZONE },
        },
    },
};
