import { getJestConfig } from '@storybook/test-runner';

/**
 * Настройки сборщика тестов для съёмки витрины первого кита.
 *
 * Набор снимков ищет файл с этим именем в каталоге витрины и, найдя, отдаёт его сборщику вместо
 * своего умолчания. Файл лежит здесь, а не в корне дерева: корневой прочитал бы и соседнюю
 * витрину, а у неё свои условия съёмки и свои эталоны.
 *
 * Завести его эпик «Один кит» прежде запрещал вовсе — первый кит не правился, витрина в том числе.
 * Запрет снят словом владельца 17 сентября 2026 года: «делать чтобы избежать постоянного
 * рассинхрона». Разрешение дано на оснастку съёмки, а не на кит: ни один компонент первого кита
 * этой работой не меняется.
 */
const base = getJestConfig();

/**
 * Язык съёмки.
 *
 * `locale` контекста меняет `navigator.language` и заголовок запроса, но формат родного
 * `<input type="date">` рисует сам браузер по языку своего запуска — его называет подъём браузера
 * в образе, сюда доводы запуска не доходят. Обе двери поэтому открыты сразу, каждая для своего.
 */
const SNAPSHOT_LOCALE = 'ru-RU';

/**
 * Пояс съёмки. `UTC` взят потому, что он один и тот же на любой машине и не переводится на летнее
 * время: у соседней витрины именно перевод развёл кадры с эталонами на час, а чужая машина — на
 * пять.
 */
const SNAPSHOT_TIMEZONE = 'UTC';

/**
 * Адрес браузера, поднятого в образе. Его называет `tools/shot-browser.mjs` — он же образ и
 * поднимает; проверка кадров витрины зовёт съёмку через него.
 *
 * Растр знаков считает та машина, что рисует, и у двух машин он разный при одном и том же коде:
 * доля расхождения 0,01 по всем буквам сразу. Пока кадры снимала машина, эталон не мог совпасть с
 * обеими сторонами — снятый у разработчика ронял конвейер, снятый под конвейер ронял проверку
 * перед отправкой, и каждая пересъёмка меняла одну сторону расхождения на другую.
 */
const SHOT_BROWSER = process.env.RT_SHOT_BROWSER ?? '';

if (!SHOT_BROWSER) {
    throw new Error(
        'Кадры витрины снимает только браузер из образа: снятые браузером машины, они не ' +
            'совпадают ни с одной другой машиной. Команда — `node tools/visual-gate.mjs ui-kit`, ' +
            'она поднимает образ сама.'
    );
}

export default {
    ...base,
    testEnvironmentOptions: {
        ...base.testEnvironmentOptions,
        'jest-playwright': {
            ...base.testEnvironmentOptions?.['jest-playwright'],
            connectOptions: { wsEndpoint: SHOT_BROWSER },
            contextOptions: { locale: SNAPSHOT_LOCALE, timezoneId: SNAPSHOT_TIMEZONE },
        },
    },
};
