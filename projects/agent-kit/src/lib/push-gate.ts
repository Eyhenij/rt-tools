/**
 * Набор проверок перед пушем — итоговый и снятое из умолчания.
 *
 * Набор собирается из двух файлов: умолчания пакета и надстройки профиля дерева. Результат
 * сборки не показывался нигде — чтобы его прочитать, надо было звать функцию профиля руками из
 * оболочки. Из этой невидимости выросли три разных промаха: дерево дописало в надстройку команду,
 * уже стоявшую в умолчании, и гоняло проверку дважды за пуш; другое дерево выкусило из умолчания
 * сплошную проверку одной строкой `rt_push_checks_default "$@" | grep -v …` — строка выглядела
 * настройкой, а была снятием охраны; а расхождение набора с конвейером узнавалось из красного
 * конвейера после заявки.
 *
 * Набор ЗОВЁТСЯ, а не пересказывается чтением: он ветвится по содержимому дерева — есть ли
 * настройка раскладки, есть ли конфиг линтера стилей, какие проверки разложены, — и разобранный
 * по тексту функции разойдётся с настоящим молча.
 *
 * ОТКАЗ В ПОЛЬЗУ ЧИТАТЕЛЯ: нет профиля, нет функции, вызов упал или завис — раздела нет, а
 * причина названа строкой. Разбор состояния ничего не пишет, и своим отказом чинить тут нечего.
 */
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { join } from 'node:path';

/** Имя функции профиля, собирающей набор, и имя её умолчания. */
const PUSH_CHECKS: string = 'rt_push_checks';
const PUSH_CHECKS_DEFAULT: string = `${PUSH_CHECKS}_default`;

/** Сколько ждать сборки набора. Сама она ничего не гоняет — печатает строки. */
const TIMEOUT_MS: number = 10_000;

/**
 * Строки, которые вернула названная функция профиля. Профиль собирается из тех же файлов и в том
 * же порядке, что читает сам гард: сперва разложенное умолчание пакета, поверх — надстройка
 * дерева. Судить по одной надстройке значило бы получить пустой набор у всякого дерева, которое
 * умолчаний не переписывало.
 */
function callProfile(root: string, defaults: string, fn: string): readonly string[] | null {
    const sources: readonly string[] = [join(root, defaults, 'project.sh'), join(root, '.claude/rt-kit', 'project.sh')].filter(
        (one: string): boolean => existsSync(one)
    );
    if (!sources.length) {
        return null;
    }

    // База пустая: с ней умолчание печатает полный набор, а не набор по вкладу ветки. Разбор
    // состояния читают, чтобы увидеть набор целиком, а не тот, что выпал бы на сегодняшнюю ветку.
    const script: string =
        sources.map((one: string): string => `. ${JSON.stringify(one)} 2>/dev/null`).join('; ') +
        `; command -v ${fn} >/dev/null 2>&1 || exit 3; ${fn} ''`;

    try {
        // Полный путь к оболочке, а не имя: имя разрешается через `PATH`, а он в чужой среде
        // бывает записываемым — тогда «bash» указывает не туда. Ищется он тем же способом, каким
        // ищут его хуки: в двух местах, где оболочка лежит на всякой машине.
        const shell: string = ['/bin/bash', '/usr/bin/bash'].find((one: string): boolean => existsSync(one)) ?? '/bin/bash';
        const out: string = execFileSync(shell, ['-c', script], {
            cwd: root,
            encoding: 'utf8',
            timeout: TIMEOUT_MS,
            stdio: ['ignore', 'pipe', 'ignore'],
        });

        return out
            .split('\n')
            .map((line: string): string => line.trim())
            .filter((line: string): boolean => line.length > 0);
    } catch {
        return null;
    }
}

/**
 * Итоговый набор перед пушем и то, что печатало умолчание, а в итог не попало.
 *
 * Разница считается по вызовам, а не по признаку переопределения: дерево, переписавшее функцию
 * целиком и вернувшее тот же набор, из умолчания не убрало ничего, а дерево, дописавшее фильтр,
 * убрало — и по одному факту переопределения эти два случая неразличимы.
 *
 * Названа разница ровно тем, что она есть: строкой умолчания, которой в итоге нет. Снятием
 * охраны она НЕ называется — дерево могло заменить команду своим вариантом, зовущим ту же
 * проверку другим прогонщиком, и такая замена выглядит отсюда точно так же. Что из двух
 * случилось, видно только в надстройке, и читает её человек.
 */
export function pushGateLines(root: string, defaults: string): string[] {
    const final: readonly string[] | null = callProfile(root, defaults, PUSH_CHECKS);
    if (final === null) {
        return ['набор перед пушем: собрать не удалось — нет профиля дерева либо функции rt_push_checks'];
    }

    const base: readonly string[] | null = callProfile(root, defaults, PUSH_CHECKS_DEFAULT);
    const cut: readonly string[] = base === null ? [] : base.filter((one: string): boolean => !final.includes(one));

    return [
        `набор перед пушем: ${final.length}`,
        ...final.map((one: string): string => `  ${one}`),
        ...(cut.length
            ? [
                  `умолчание печатало, а в наборе нет: ${cut.length}`,
                  ...cut.map((one: string): string => `  ${one}`),
                  '  это либо снятие охраны, либо замена своим вариантом той же проверки — различает их надстройка профиля',
              ]
            : []),
    ];
}
