#!/usr/bin/env bash
# Запрос из ввода гарда хранилища: что именно поедет к серверу и через что.
#
# Строки `# rt-hook:` здесь нет намеренно: событие и образец вызова объявляет сам гард, а
# помощник рядом хуком не регистрируется и в одиночку ничего не решает.
#
# Отсюда выходят четыре значения: `sql` — текст запроса или команда целиком, `conn` —
# идентификатор подключения редактора, `context` — чем это доставляется, и `cmd` — исходная
# командная строка, нужная разбору адреса миграции в исходном регистре.

# Три вида ввода: запрос через подключение редактора, команда оболочки и та же команда,
# завёрнутая в универсальный исполнитель. Инструмент, не названный здесь, гарда не касается.
sql_read_request() {
    sql=""
    context=""
    conn=""
    case "$tool" in
        mcp__webstorm__execute_sql_query)
            sql="$(printf '%s' "$input" | jq -r '.tool_input.queryText // empty' 2>/dev/null)"
            conn="$(printf '%s' "$input" | jq -r '.tool_input.connectionId // empty' 2>/dev/null)"
            context="запрос через подключение редактора"
            ;;
        # Терминал IDE исполняет ту же командную строку и кладёт её в то же поле, что и Bash:
        # без этой ветки весь гард обходился сменой инструмента.
        Bash | mcp__webstorm__execute_terminal_command | mcp__webstorm__execute_tool)
            cmd="$(printf '%s' "$input" | jq -r '.tool_input.command // empty' 2>/dev/null)"
            [ -z "$cmd" ] && exit 0

            # Универсальный исполнитель зовёт ЛЮБОЙ инструмент редактора по имени, в том числе
            # `execute_sql_query`, — и тогда в строке нет ни одного имени клиента, по которому
            # гард себя включает. Сам инструмент закрыт в permissions.deny, но полагаться только
            # на настройку нельзя: её снимут, а гард останется.
            if [ "$tool" = "mcp__webstorm__execute_tool" ] && command -v perl >/dev/null 2>&1; then
                case "$cmd" in
                    *execute_sql_query*)
                        inner_sql="$(printf '%s' "$cmd" | perl -0ne '
                            if (/--queryText(?:=|\s+)(?:"((?:[^"\\]|\\.)*)"|\x27([^\x27]*)\x27|(.+))/s) {
                                print defined $1 ? $1 : (defined $2 ? $2 : $3);
                            }
                        ' 2>/dev/null)"
                        inner_conn="$(printf '%s' "$cmd" | perl -0ne '
                            if (/--connectionId(?:=|\s+)(?:"([^"]*)"|\x27([^\x27]*)\x27|(\S+))/) {
                                print defined $1 ? $1 : (defined $2 ? $2 : $3);
                            }
                        ' 2>/dev/null)"
                        ;;
                esac
                # Терминал, завёрнутый в тот же исполнитель: разбираем настоящую команду.
                if [ -z "$inner_sql" ]; then
                    inner_cmd="$(printf '%s' "$cmd" | perl -0ne '
                        if (/--command(?:=|\s+)(?:"((?:[^"\\]|\\.)*)"|\x27([^\x27]*)\x27|(.+))/s) {
                            print defined $1 ? $1 : (defined $2 ? $2 : $3);
                        }
                    ' 2>/dev/null)"
                    [ -n "$inner_cmd" ] && cmd="$inner_cmd"
                fi
            fi

            # Завёрнутый запрос разбирается как запрос из редактора, а не как команда оболочки:
            # имени клиента в нём нет, зато есть подключение и текст SQL.
            if [ -n "$inner_sql" ]; then
                sql="$inner_sql"
                conn="$inner_conn"
                context="запрос через подключение редактора (обёртка исполнителя)"
            else

            # Команда, которая ничего никуда не доставляет, разбору не подлежит — даже если имя
            # клиента стоит в её аргументах. `grep -rn "prisma db push" docs/` читает файлы, а не
            # базу; раньше он получал deny, и обойти это можно было только испортив сам шаблон
            # поиска. Тот же приём уже применён в dev-server-guard: решает ГОЛОВА команды, а не
            # упоминание имени где-то внутри.
            # Интересуют команды, которые доносят SQL до сервера. Клиент ищется КАК СЛОВО в любом
            # месте команды, а не только в начале: удаление на бою выглядит как
            # `ssh root@host "docker compose exec postgres psql -c '…'"` — при проверке одного
            # лишь начала строки оно проходило мимо гарда целиком.
            #
            # Порядок здесь принципиален. Раньше выше стояла отсечка «команда начинается с git/gh»,
            # снимавшая ложные срабатывания на тексте коммита, — и она же открывала обход: в
            # `git log && psql … -c "DELETE …"` первое звено уносило с собой весь остальной SQL.
            # Теперь сперва ищется клиент, и только его отсутствие завершает проверку.
            printf '%s\n' "$cmd" | grep -qE \
                '(^|[^[:alnum:]_.-])(psql|pg_restore|pg_dump|prisma)([^[:alnum:]_.-]|$)' \
                || exit 0

            # Ложные срабатывания на описаниях снимаются иначе — вырезанием текста сообщений
            # (`-m '…'`, `-am "…"`, `--message="…"`, `-F file`), а не отказом от проверки всей
            # команды. В самом сообщении SQL не исполняется, но слова «delete» и «drop» в нём
            # обычны: `git commit -am "chore(api): update prisma schema"` разбирался как
            # UPDATE без WHERE, потому что шаблон требовал `-m` вплотную к дефису.
            if command -v perl >/dev/null 2>&1; then
                # `file` в альтернации быть не должно: под него попадал `--file=cleanup.sql`
                # у psql, и признак «SQL приехал файлом» умирал раньше, чем его проверяли.
                # Здесь только флаги, которые несут ТЕКСТ сообщения.
                cmd="$(printf '%s' "$cmd" | perl -0pe '
                    s/(^|[^[:alnum:]])--?[a-zA-Z]*(m|message|body|title|body-file|F)(=|\s+)("([^"\\]|\\.)*"|\x27[^\x27]*\x27|[^\s;&|]+)/$1/gs
                ' 2>/dev/null || printf '%s' "$cmd")"
                # После вырезания сообщения клиента может уже не остаться — тогда это была
                # git-команда, лишь упоминавшая psql в тексте.
                printf '%s\n' "$cmd" | grep -qE \
                    '(^|[^[:alnum:]_.-])(psql|pg_restore|pg_dump|prisma)([^[:alnum:]_.-]|$)' \
                    || exit 0
            else
                # Без perl вырезать текст сообщения нечем, и разбирать его как SQL нельзя:
                # штатный коммит упирался бы в отказ. Доставки SQL в git-команде не бывает,
                # поэтому здесь дешевле пропустить, чем ломать работу.
                case "$cmd" in
                    git\ *|*/git\ *|gh\ *|*/gh\ *) exit 0 ;;
                esac
            fi

            sql="$cmd"
            context="команда psql/prisma"
            fi
            ;;
        *) exit 0 ;;
    esac
}
