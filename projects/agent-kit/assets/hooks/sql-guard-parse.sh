#!/usr/bin/env bash
# Разбор команды для гарда хранилища: приведение к одному виду, нарезка на сегменты и ответ
# на вопрос, доставляет ли сегмент SQL до сервера.
#
# Строки `# rt-hook:` здесь нет намеренно: событие и образец вызова объявляет сам гард, а
# помощник рядом хуком не регистрируется и в одиночку ничего не решает.

# Дальше разбираем без учёта регистра и переводов строк: `delete\n  from bookings`
# — тот же запрос, что и в одну строку.
#
# Перевод строки при этом превращается в `;`, а не в пробел: в командной строке он РАЗДЕЛЯЕТ
# вызовы ровно как `;`, и склейка его в пробел стирала границу между ними. Многострочная
# команда становилась одним сегментом, доказательство чтения из первой строки покрывало
# неразобранный вызов из второй, и запись на боевую базу проходила молча — тот же обход,
# что чинили для `&&`, только набранный с новой строки.
normalize() {
    perl -0ne '
        # Продолжение длинной команды обратным слешем — это одна строка, а не две: без
        # склейки адрес из первой уезжал в соседний сегмент, где клиента уже нет.
        s/\\\n/ /g;
        # Перевод строки заменяется на `;` ТОЛЬКО вне кавычек. Внутри `-c "…"` он часть
        # запроса: многострочный SELECT резался на сегменты, и штатное чтение боевой базы
        # переставало быть доказанным.
        my ($out, $quote, $esc) = ("", "", 0);
        for my $ch (split //, $_) {
            if ($esc) { $out .= $ch; $esc = 0; next; }
            if ($ch eq "\\") { $out .= $ch; $esc = 1; next; }
            if ($quote ne "") {
                $out .= ($ch eq "\n" ? " " : $ch);
                $quote = "" if $ch eq $quote;
            } elsif ($ch eq q{"} || $ch eq q{'"'"'}) {
                $quote = $ch; $out .= $ch;
            } elsif ($ch eq "\n" || $ch eq ";") {
                $out .= "\x01";              # граница независимых команд
            } elsif ($ch eq "|") {
                $out .= "\x02";              # граница звена конвейера
            } elsif ($ch eq "&") {
                $out .= "\x01";
            } else {
                $out .= $ch;
            }
        }
        # Соседние маркеры схлопываются: `&&` и `||` дают по два подряд.
        $out =~ s/\x01+/\x01/g;
        $out =~ s/\x02\x01/\x01/g;
        $out =~ s/\x01\x02/\x01/g;
        # Незакрытая кавычка означает, что автомат разъехался: апостроф в комментарии
        # (`# don'"'"'t forget`) оставлял состояние «внутри строки» до конца ввода, и все
        # последующие переводы строк переставали разделять вызовы — сегментация выключалась
        # одним символом. В таком случае честнее ничего не печатать: вызывающий разделит
        # строки грубым способом, и лишнее дробление сыграет в пользу строгости.
        print $out if $quote eq "";
    ' 2>/dev/null
}

# Грубое разделение — запасной путь: все переводы строк становятся разделителями. Оно строже
# точного (может разрезать многострочный запрос), поэтому годится и как фолбэк без perl,
# и как ответ на неразобранную команду.
sql_flatten() {
    flat_rough="$(printf '%s' "$sql" | perl -0pe 's/\\\n/ /g' 2>/dev/null | tr '\n;&' '\001\001\001' | tr '|' '\002' | tr '\t' ' ' | tr '[:upper:]' '[:lower:]')"
    [ -z "$flat_rough" ] && flat_rough="$(printf '%s' "$sql" | tr '\n;&' '\001\001\001' | tr '|' '\002' | tr '\t' ' ' | tr '[:upper:]' '[:lower:]')"

    if command -v perl >/dev/null 2>&1; then
        flat="$(printf '%s' "$sql" | normalize | tr '\t' ' ' | tr '[:upper:]' '[:lower:]')"
        [ -z "$flat" ] && flat="$flat_rough"
    else
        flat="$flat_rough"
    fi
}

# Разбор идёт по сегментам, а не по всей строке: `ls -l /opt && … psql -c "\copy …"` целиком
# выглядел как чтение, потому что `-l` от `ls` засчитывался за `psql -l`.
#
# Нарезка живёт в ЕДИНСТВЕННОМ месте. Пока наборов разделителей было два — один в раннем слое,
# другой здесь, — расхождение само по себе оказалось дырой: одиночный `|` считался границей
# тут и не считался там, и доставка файла конвейером в клиент проходила как чтение.
# Команда — то, что стоит между `;`, `&&`, `||` и переводами строк. Конвейер границей НЕ
# является: `cat fix.sql | psql …` — не две независимые команды, а одна доставка SQL, где
# левое звено питает правое. Пока `|` резал команды, глагол из `echo "drop table …"` терялся
# вместе с отброшенным звеном, и запись проходила молча.
split_segments() {
    # Перевод строки в конце обязателен: без него `read` не отдаёт последнюю строку в тело
    # цикла, и команда из одного сегмента молча выпадала из разбора целиком.
    printf '%s\n' "$1" | tr '\001' '\n'
}

# Звенья конвейера внутри одной команды.
split_pipeline() {
    printf '%s' "$1" | tr '\002' '\n'
}

# Команда считается вызовом клиента, только если клиент стоит ГОЛОВОЙ хотя бы одного звена.
# Имя в аргументе (`grep -rn "prisma db push" docs/`) вызовом не является.
calls_client() {
    _found=""
    _links="$(printf '%s' "$1" | tr '\002' '\n')"
    while IFS= read -r link; do
        [ -z "$link" ] && continue
        # Голова звена: пропускаем присваивания окружения и обёртки вроде sudo/time/xargs.
        head="$(printf '%s' "$link" | sed -E 's/^[[:space:]]*//; s/^([A-Za-z_][A-Za-z0-9_]*=[^[:space:]]*[[:space:]]+)*//; s/^(sudo|time|env|nice|xargs)[[:space:]]+//')"
        case "$head" in
            psql*|pg_restore*|pg_dump*|pg_dumpall*|prisma*|*/psql*|*/pg_restore*|*/pg_dump*)
                _found="yes"; break ;;
        esac
        # Транспорт до машины: сам вызов стоит внутри строки, которую он исполняет.
        case "$head" in
            ssh\ *|scp\ *|docker\ *|*/ssh\ *|*/docker\ *)
                printf '%s' "$link" | grep -qE '(^|[^[:alnum:]_.-])(psql|pg_restore|pg_dump|prisma)([^[:alnum:]_.-]|$)' \
                    && { _found="yes"; break; } ;;
        esac
        # Раннер пакетов перед клиентом: `npx prisma migrate deploy`.
        case "$head" in
            npx\ *|pnpm\ *|yarn\ *|bun\ *|npm\ *)
                printf '%s' "$head" | grep -qE '^(npx|pnpm|yarn|bun|npm)([[:space:]]+(exec|run|dlx))?[[:space:]]+(psql|pg_restore|pg_dump|prisma)([[:space:]]|$)' \
                    && { _found="yes"; break; } ;;
        esac
    done <<CALLS_EOF
$_links
CALLS_EOF
    [ -n "$_found" ]
}

# Голова сегмента — читающий инструмент: имя клиента стоит в его аргументе, то есть это поиск
# или просмотр файла, а не доставка SQL. `grep -rn "prisma db push" docs/` читает документацию.
# Решает именно ГОЛОВА: тот же приём применён в dev-server-guard якорем BOUND.
is_reader() {
    printf '%s' "$1" | grep -qE '^[[:space:]]*([A-Za-z_][A-Za-z0-9_]*=[^[:space:]]*[[:space:]]+)*((sudo|time|env|nice|xargs)[[:space:]]+)*([^[:space:]]*/)?(grep|rg|ag|ack|find|awk|sed|cat|less|more|head|tail|wc|echo|printf|jq|diff|comm|sort|uniq|column)([[:space:]]|$)'
}

# Сегменты с настоящим вызовом клиента: читающие головы отсеиваются здесь же, а не отдельным
# слоем с собственным выходом.
client_segments() {
    split_segments "$flat" | while IFS= read -r seg; do
        [ -z "$seg" ] && continue
        calls_client "$seg" || continue
        # Маркер звена больше не нужен: дальше команда разбирается как одна строка.
        printf '%s\n' "$(printf '%s' "$seg" | tr '\002' ' ')"
    done
}

# Адресат берётся ТОЛЬКО из сегментов вызова клиента и только из аргументов, а не из данных.
# Домен сайта живёт в самих строках — в почте владельца, в canonical и og:url объекта, — а
# рядом в цепочке его дёргают по HTTP. Пока признак искался по всей команде, `curl
# https://<домен приложения>/... && psql -p 5432 -c "update …"` отклонялся как запись в
# боевую базу, и опт-аута у этой ветки нет по замыслу: команда становилась неисполнимой.
# Текст запроса вырезается ДО нарезки на сегменты. Внутри `-c "…"` свободно живут `;` и `||`
# — по ним сегменты и режутся, поэтому кусок запроса с доменом в данных становился отдельным
# сегментом, и почта на домене приложения снова читалась как адрес боевой базы.
sql_addr_flatten() {
    addr_flat="$flat"
    if command -v perl >/dev/null 2>&1; then
        addr_flat="$(printf '%s' "$flat" | perl -0pe '
            s/(^|[^[:alnum:]])--?(c|command|querytext)(=|\s+)("([^"\\]|\\.)*"|\x27[^\x27]*\x27)/$1/gs
        ' 2>/dev/null || printf '%s' "$flat")"
    fi
}

addr_segments() {
    split_segments "$addr_flat" | while IFS= read -r seg; do
        [ -z "$seg" ] && continue
        flat_seg="$(printf '%s' "$seg" | tr '\002' ' ')"
        # Адрес берётся из команд с вызовом клиента и из транспорта до машины: `ssh root@…`
        # называет боевой хост, а сам вызов стоит дальше по цепочке.
        if calls_client "$seg"; then
            printf '%s\n' "$flat_seg"
        elif printf '%s' "$flat_seg" | grep -qE '(^|[^[:alnum:]_.-])(ssh|scp|docker)([^[:alnum:]_.-]|$)|(pghost|pgport|pgdatabase|pguser|database_url|postgres_url)='; then
            is_reader "$flat_seg" && continue
            printf '%s\n' "$flat_seg"
        fi
    done
}

# Сегменты вызова клиента для дальнейшего разбора. У запроса из редактора сегментов нет вовсе
# — там весь текст и есть запрос.
sql_collect_segments() {
    segments="$(client_segments)"
    if [ -z "$segments" ]; then
        if [ -n "$conn" ] || [ "$context" != "команда psql/prisma" ]; then
            segments="$flat"
        else
            # Команда, где имя клиента встретилось только в аргументах читающих инструментов,
            # ничего никуда не доставляет. Выход здесь безопасен: он стоит ПОСЛЕ разбора, а не
            # вместо него, и срабатывает лишь когда настоящего вызова в команде нет.
            exit 0
        fi
    fi
}
