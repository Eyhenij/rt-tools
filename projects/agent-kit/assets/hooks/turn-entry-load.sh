#!/usr/bin/env bash
# rt-hook: SessionStart startup|resume|compact|clear
# Требует: hooks/handoff-write.sh
# SessionStart: передача прошлого захода и карта хода уезжают в контекст на каждом запуске.
#
# Передачу пишет хук перед сжатием — и на этом её путь кончался: читать её не умел никто, и
# в новый заход её клал человек. Написанная и не прочитанная, она равна ненаписанной.
#
# Второе, чего заход после сжатия не знает, — как здесь ведут работу. Перечень состояний с
# обязательными действиями лежит в правиле, а правило после сжатия не загружено: заход первым
# движением идёт читать его целиком, то есть тратит на восстановление порядка ту часть окна,
# ради которой сжатие и случилось. Карта отвечает на этот вопрос до того, как он задан.
#
# Подаётся это на всех четырёх запусках, а не только после сжатия: заход после обрыва и заход
# после очистки начинают с того же пустого места, и разница между ними исполнителю не видна.
#
# FAIL-OPEN: не git-репозиторий, нет ветки, нет каталога передач, нет карты, нечитаемый файл —
# хук выходит нулём и молчит о той части, которой нет. Запуск он не отбивает никогда: сессия
# важнее контекста.

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/utf8.sh" 2>/dev/null || true

ROOT="${CLAUDE_PROJECT_DIR:-.}"
cd "$ROOT" 2>/dev/null || exit 0
git rev-parse --is-inside-work-tree >/dev/null 2>&1 || exit 0

branch="$(git branch --show-current 2>/dev/null)"

# Профиль дерева: сперва умолчание пакета, поверх него — надстройка проекта, если она есть.
rt_hooks_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
for profile in "$rt_hooks_dir/../rt-kit/defaults/project.sh" "$rt_hooks_dir/../defaults/project.sh" \
    "$ROOT/.claude/rt-kit/defaults/project.sh" "$ROOT/.claude/rt-kit/project.sh"; do
    # shellcheck disable=SC1090
    [ -f "$profile" ] && . "$profile" 2>/dev/null
done

handoff_dir="${RT_HANDOFF_DIR:-.claude/handoff}"
map="$rt_hooks_dir/../rt-kit/defaults/turn-map.md"
[ -f "$map" ] || map="$ROOT/.claude/rt-kit/defaults/turn-map.md"

# Передача берётся по имени текущей ветки. Чужая, поданная как своя, описывает работу, которой
# в этом дереве нет, — поэтому и раздел, и файл ищутся по ветке, а не выбираются из каталога.
#
# Мест два, и порядок между ними один. Передача ветки с папкой задачи лежит разделом её хода
# работы: он коммитится и едет в ветку, поэтому переживает переход на другую машину. Файл вне
# дерева — запасной путь: у работы без папки задачи разделу лечь некуда. Найдя раздел, файл не
# читают: это одна и та же передача, и вторая копия старше первой.
tasks_dir="${RT_TASKS_DIR:-docs/tasks}"
progress=''
[ -n "$branch" ] && progress="$ROOT/$tasks_dir/$branch/progress.md"

section=''
if [ -n "$progress" ] && [ -r "$progress" ]; then
    # Сравнение байтами: под локалью с национальными настройками `awk` этой системы считает
    # разные кириллические заголовки равными, и вход читал бы разделом передачи первый попавшийся.
    section="$(LC_ALL=C awk '
        $0 == "## Передача захода" { skip = 1; next }
        skip && /^## / { skip = 0 }
        skip { print }
    ' "$progress" 2>/dev/null)"
fi

handoff=''
[ -n "$branch" ] && handoff="$ROOT/$handoff_dir/$branch.md"

if [ -n "$section" ]; then
    printf 'ПЕРЕДАЧА ПРОШЛОГО ЗАХОДА — раздел «Передача захода» в `%s/%s/progress.md`, ниже целиком.\n\n' "$tasks_dir" "$branch"
    printf 'Она написана прошлым заходом и описывает минуту, когда её собрали. Всё, что в ней\n'
    printf 'стоит о дереве, проверяется деревом: команда этого хода главнее записанной вчера.\n\n'
    printf '%s\n\n' "$section"
elif [ -n "$handoff" ] && [ -r "$handoff" ]; then
    printf 'ПЕРЕДАЧА ПРОШЛОГО ЗАХОДА — `%s/%s.md`, ниже целиком.\n\n' "$handoff_dir" "$branch"
    printf 'Она написана прошлым заходом и описывает минуту, когда её собрали. Всё, что в ней\n'
    printf 'стоит о дереве, проверяется деревом: команда этого хода главнее записанной вчера.\n\n'
    cat "$handoff" 2>/dev/null
    printf '\n\n'
fi

if [ -r "$map" ]; then
    printf 'КАРТА ХОДА — состояния работы и то, чем ход кончается. Ниже целиком.\n\n'
    printf 'Это выжимка правила ведения работы, а не оно само: правило объясняет, карта\n'
    printf 'называет. Своё состояние заход читает в разделе «Где стоим» хода работы.\n\n'
    cat "$map" 2>/dev/null
    printf '\n'
fi

exit 0
