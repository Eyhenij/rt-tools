#!/usr/bin/env bash
# Образцы стража выходов хода. НЕ гард: объявления `rt-hook:` у него нет, к событиям агента он
# не подключается. Его источает страж выходов хода — тем же приёмом, каким гарды источают общее
# чтение ввода и хвост отказа. Вынесен отдельно, когда страж перерос предел длины файла: образцы
# и доводы при них читаются порознь от ярусов, которые их применяют.
#
# Каждый образец — переменная оболочки; страж передаёт их разбору записи хода доводами.

# Команда, меняющая дерево или его состояние. Чтение и поиск сюда не входят намеренно: ими и
# заполняется ход, который встал.
#
# Перенаправления вывода здесь нет, и снято оно по разбору: страж отбил два хода из семи,
# простоявших без работы, а пять засчитал работой ровно по нему. Тело будущей заявки писалось во
# временный каталог захода — вне рабочего дерева, — а одно из ожиданий несло только отвод потока
# ошибок в устройство пустоты. Ни то ни другое дерева не меняет, а образцу они были неотличимы
# от записи в рабочий файл: он видел саму стрелку и не спрашивал, куда она ведёт. Признаком
# остаются правка файла инструментом правки и перечисленные здесь команды.
work_re='git (add|commit|push|checkout|merge|rm)|npm run|pnpm (run|exec)|nx (build|test|run)|gh (pr|issue|api|run)|task:(new|move)|mkdir|cp |mv |rm |sed -i|tee '

# Разведка. Те же слова, что и в образце работы, но подкоманда читающая: переключение ветки,
# подтягивание, просмотр истории, чтение заявок и прогонов. Образец работы называет их работой,
# потому что знает только первое слово — `git` и `gh` стоят в нём целиком, — и ход, в котором
# исполнитель перешёл на главную ветку, прочитал историю и написал владельцу отчёт, выходил
# отсюда нулём. Разбор — запись «2026-08-25-read-only-turn-counted-as-work» в приёме.
#
# Разведка выглядит работой лучше всего остального: в ней команды, числа и точные ответы. Тем
# она и опасна — ход, набитый ею, читается как полный и владельцем, и самим заходом.
read_re='^[[:space:]]*(([^[:space:]]*/)?git[[:space:]]+(show|log|ls-tree|ls-files|ls-remote|diff|status|branch|tag|rev-parse|remote|describe|blame|fetch|pull|(checkout|switch)(?!([[:space:]]+-[A-Za-z-]+)*[[:space:]]+-[bc][[:space:]]))|([^[:space:]]*/)?gh[[:space:]]+(pr|issue|run|repo)[[:space:]]+(list|view|status|checks|diff|download|logs))([[:space:]]|$)'

# Части составной команды судятся по одной: ход собирает чтение и работу в одну строку через
# `&&`, и суждение целиком отпускало бы разведку по первой же меняющей части.
part_re='&&|\|\||;|\n'

# Ожидание чужого шага. Прогон, разбор владельцем и слияние идут без исполнителя и от взгляда
# быстрее не становятся — правило прямо говорит, что состоянием работы это не бывает. Судится
# только ПОСЛЕДНЕЕ действие хода: ожидание в середине законно, а запуск работы в фоне работой
# остаётся. Разбор — запись «2026-08-25-turn-ended-on-waiting» в приёме.
#
# Прежний признак спрашивал одно: была ли за ход работа. Ход, где разобран конфликт, сделаны
# коммит и пуш, а последним действием стал цикл до готовности прогона, проходил его целиком —
# работа была, и много. Именно эта полнота и обманывает: пустоты за таким ходом не видно.
wait_re='gh[[:space:]]+(run[[:space:]]+watch|pr[[:space:]]+checks[^|]*--watch)|until[[:space:]].*sleep|while[[:space:]].*sleep|^[[:space:]]*sleep[[:space:]]'

# Отдача работы и начало следующей. Правило зовёт законным концом хода отданную работу — но с
# условием: следующая начата, и по ней сделано ДЕЙСТВИЕ, а не сказано.
handover_re='gh[[:space:]]+pr[[:space:]]+create'
started_re='task:new|task:move|board\.mjs[[:space:]]+move|git[[:space:]]+checkout([[:space:]]+-[A-Za-z-]+)*[[:space:]]+-b|git[[:space:]]+switch([[:space:]]+-[A-Za-z-]+)*[[:space:]]+-c'
