#!/usr/bin/env bash
# rt-hook: PreToolUse AskUserQuestion
# Требует: hooks/grill-gate.sh
# Половина гарда разговора, стоящая на инструменте вопроса: меню судится до отправки.
#
# Своим ресурсом, а не строкой в шапке соседа, потому что инструмент вопроса — единственный
# способ спросить владельца, и у дерева на нём уже может стоять свой гард со своей причиной
# отказа. Второй отказ на том же инструменте делает вопрос недоступным вовсе, и дерево
# отказывается от гарда целиком вместо того, чтобы взять его половину. Разведённые по двум
# ресурсам, половины отменяются порознь: строка отказа снимает одну и оставляет другую.
#
# Судит вызов то же тело, что и завершение хода: требование одно, и расходиться двум его
# редакциям нельзя. Здесь только объявление события и передача ввода.
#
# ОТКАЗ В ПОЛЬЗУ РАБОТЫ: нет соседнего файла — ход РАЗРЕШАЕТСЯ. Половина гарда, потерявшая
# тело, не имеет права заклинить разговор.

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/utf8.sh" 2>/dev/null || true
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/hook-input.sh" 2>/dev/null || true

rt_hooks_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
[ -f "$rt_hooks_dir/grill-gate.sh" ] || exit 0

rt_hook_read
printf '%s' "$RT_HOOK_INPUT" | "$rt_hooks_dir/grill-gate.sh"
