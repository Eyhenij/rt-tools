#!/usr/bin/env bash
# Гард пишущих запросов к хранилищу. PreToolUse.
#
# Правка данных — единственное действие, которое нельзя откатить правкой кода. Удаление по
# маске однажды уносит вместе с пробными записями настоящие: маска совпадает шире, чем ожидал
# автор запроса, и узнаётся это уже по восстановлению из копии.
#
# Отсюда правило: строки адресуются по первичному ключу. Перечисление идентификаторов
# затрагивает ровно столько строк, сколько их перечислено, и промах виден до выполнения;
# отбор по подстроке не виден никогда.
#
# Три уровня:
#   отказ    — снос, очистка, правка схемы, удаление и обновление без условия или с условием
#              не по идентификатору;
#   вопрос   — остальная запись: адресная правка и вставка, решение за владельцем;
#   пропуск  — чтение.
#
# Боевое хранилище отдельно: его адреса перечисляет профиль проекта ({{projectProfile}},
# переменная RT_PROD_DSN) — там любая запись отказывается без опт-аута. Бой правится миграцией
# через выкатку, а не запросом из редактора.
#
# Опт-аут для остальных случаев: маркер `destructive-ok` в тексте запроса вместе с объяснением,
# почему адресация по идентификатору не подходит, понижает отказ до вопроса. Последнее слово
# остаётся за владельцем — гард лишь не пропускает такое молча.
#
# ОТКАЗ В ПОЛЬЗУ РАБОТЫ: нет разборщика, битый ввод, чужой инструмент — пропуск.

input="$(cat 2>/dev/null)"
[ -z "$input" ] && exit 0
command -v jq >/dev/null 2>&1 || exit 0

tool="$(printf '%s' "$input" | jq -r '.tool_name // empty' 2>/dev/null)"

sql=""
case "$tool" in
    mcp__webstorm__execute_sql_query)
        sql="$(printf '%s' "$input" | jq -r '.tool_input.queryText // empty' 2>/dev/null)"
        ;;
    Bash | mcp__webstorm__execute_terminal_command | mcp__webstorm__execute_tool)
        cmd="$(printf '%s' "$input" | jq -r '.tool_input.command // empty' 2>/dev/null)"
        [ -z "$cmd" ] && exit 0

        # Клиент ищется КАК СЛОВО в любом месте команды, а не только в начале: удаление на бою
        # выглядит как заход по сети с вложенной командой клиента, и проверка одного лишь
        # начала строки проходит мимо него целиком.
        #
        # Порядок принципиален. Отсечка «команда начинается с гита», снимающая ложные
        # срабатывания на тексте коммита, открывает обход: в составной команде первое звено
        # уносит с собой весь остальной запрос. Поэтому сперва ищется клиент.
        printf '%s\n' "$cmd" | grep -qE '(^|[^[:alnum:]_.-])(psql|pg_restore|pg_dump|prisma)([^[:alnum:]_.-]|$)' || exit 0

        # Ложные срабатывания на описаниях снимаются вырезанием текстов сообщений, а не отказом
        # от проверки всей команды: в самом сообщении запрос не исполняется, но слова «удалить»
        # и «обновить» в нём обычны.
        if command -v perl >/dev/null 2>&1; then
            # Флага файла в списке быть не должно: под него попадает файл запроса у клиента, и
            # признак «запрос приехал файлом» умирает раньше, чем его проверят.
            cmd="$(printf '%s' "$cmd" | perl -0pe '
                s/(^|[^[:alnum:]])--?[a-zA-Z]*(m|message|body|title|body-file|F)(=|\s+)("([^"\\]|\\.)*"|\x27[^\x27]*\x27|[^\s;&|]+)/$1/gs
            ' 2>/dev/null || printf '%s' "$cmd")"
            printf '%s\n' "$cmd" | grep -qE '(^|[^[:alnum:]_.-])(psql|pg_restore|pg_dump|prisma)([^[:alnum:]_.-]|$)' || exit 0
        else
            # Без разборщика вырезать текст сообщения нечем, и разбирать его как запрос нельзя:
            # штатный коммит упирался бы в отказ. Доставки запроса внутри команды истории не
            # бывает, поэтому здесь дешевле пропустить, чем ломать работу.
            case "$cmd" in
                git\ *|*/git\ *|gh\ *|*/gh\ *) exit 0 ;;
            esac
        fi

        sql="$cmd"
        ;;
    *) exit 0 ;;
esac

[ -z "$sql" ] && exit 0

# Дальше разбираем без учёта регистра: запрос, разбитый на строки, — тот же запрос.
flat="$(printf '%s' "$sql" | tr '\n' ' ' | tr '[:upper:]' '[:lower:]')"

deny() {
    echo "$1 Адресуй строки по первичному ключу: перечисление идентификаторов затрагивает ровно столько строк, сколько их названо, и промах виден до выполнения. Если адресация по идентификатору здесь не подходит, поставь маркер destructive-ok в текст запроса с объяснением — решение тогда примет владелец." >&2
    exit 2
}

ask() {
    jq -n --arg r "$1" '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"ask",permissionDecisionReason:$r}}' 2>/dev/null
    exit 0
}

# Бой: адреса знает профиль. Там любая запись отказывается, и опт-аут не действует.
profile="${CLAUDE_PROJECT_DIR:-.}/{{projectProfile}}"
if [ -f "$profile" ]; then
    # shellcheck disable=SC1090
    . "$profile" 2>/dev/null
    if [ -n "${RT_PROD_DSN:-}" ] && printf '%s' "$flat" | grep -qF "$RT_PROD_DSN"; then
        case "$flat" in
            *insert\ *|*update\ *|*delete\ *|*drop\ *|*truncate\ *|*alter\ *)
                echo "Запись в боевое хранилище запрещена совсем: схема меняется миграцией через выкатку, данные — через интерфейс." >&2
                exit 2 ;;
        esac
    fi
fi

opt_out=0
case "$flat" in *destructive-ok*) opt_out=1 ;; esac

case "$flat" in
    *drop\ *|*truncate\ *|*alter\ table*)
        [ "$opt_out" = 1 ] && ask "Схемная команда с маркером destructive-ok. Решение за тобой."
        deny "Снос, очистка или правка схемы запросом." ;;
esac

case "$flat" in
    *delete\ from*|*update\ *set\ *)
        # Условие по идентификатору — единственная форма, где число задетых строк известно
        # заранее. Отбор по подстроке им не является, даже когда сегодня совпадает точно.
        if printf '%s' "$flat" | grep -qE 'where[^;]*\b(id|uuid)\b[[:space:]]*(=|in[[:space:]]*\()'; then
            ask "Адресная правка данных. Решение за тобой."
        fi
        [ "$opt_out" = 1 ] && ask "Правка без адресации по идентификатору, с маркером destructive-ok. Решение за тобой."
        deny "Удаление или обновление без условия по идентификатору." ;;
esac

case "$flat" in
    *insert\ into*) ask "Вставка данных. Решение за тобой." ;;
esac

exit 0
