#!/usr/bin/env bash
# SessionStart: словарь проекта уезжает в контекст целиком, на каждом запуске сессии.
#
# Памятью это не держится: словарь читают перед тем, как написать текст, а разговор с
# владельцем идёт без чтения — и слово из левой колонки «Так не пишем» всплывает в ответе,
# хотя в файлах его уже нет. Здесь словарь приходит до первой реплики и действует и на
# тексты, и на ответы.
#
# FAIL-OPEN: нет файла или нет `jq` — выходим молча. Сессия важнее словаря.

GLOSSARY="${CLAUDE_PROJECT_DIR:-.}/docs/GLOSSARY.md"
[ -f "$GLOSSARY" ] || exit 0
command -v jq >/dev/null 2>&1 || exit 0

{
    printf 'СЛОВАРЬ ПРОЕКТА — `docs/GLOSSARY.md`, ниже целиком.\n\n'
    printf 'Слово отсюда употребляется в том значении, что здесь: и в файлах, и в ответах владельцу.\n'
    printf 'Раздел «Так не пишем» действует так же — левая колонка не пишется и не произносится нигде.\n'
    printf 'Слова, которого здесь нет, у читателя нет тоже: оно либо заводится здесь же той же правкой,\n'
    printf 'либо заменяется тем, что уже есть.\n\n'
    cat "$GLOSSARY"
} | jq -Rs '{hookSpecificOutput:{hookEventName:"SessionStart",additionalContext:.}}'
