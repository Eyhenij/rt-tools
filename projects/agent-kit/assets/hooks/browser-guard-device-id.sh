#!/usr/bin/env bash
# rt-hook: PreToolUse mcp__claude-in-chrome__select_browser
# rt-hook: PostToolUse mcp__claude-in-chrome__select_browser
# Требует: hooks/deny-tail.sh
# Гард выбора браузера. Стоит на обоих событиях выбора — до вызова и после него.
#
# ДО ВЫЗОВА отклоняет любой профиль, кроме закреплённого: чужой стоит лишнего круга и приводит в
# браузер, где сессий этого проекта нет вовсе.
#
# ПОСЛЕ ВЫЗОВА ставит метку сессии — и только тогда, когда ответ говорит о состоявшемся
# подключении. Гард свежести читает ВОЗРАСТ этой метки, и она делает законной всю дальнейшую
# работу с браузером.
#
# Почему метка переехала на второе событие. Она стояла на совпадении признака, то есть на
# ПОПЫТКЕ выбора. Закреплённый профиль отключён, вызов выбора отказывает — а метка уже лежит, и
# гард свежести пропускает следом состав вкладок, переход и снимок экрана: они уходят в тот
# браузер, который расширение считает активным, и какой это браузер, не знает никто. Заметил это
# владелец, а не гард. Метка до вызова обещает «профиль закреплённый», а знает только «профиль
# запрашивали».
#
# ОТКАЗ В ПОЛЬЗУ РАБОТЫ: помощник не назвал профиль — пропуск. Ответ, о котором нельзя сказать,
# что подключение состоялось, метки не оставляет: работу это не заклинивает — следующий вызов
# отобьёт гард свежести и потребует выбрать заново.

# Своё имя в наблюдениях: отбой пишет общий хвост отказа, а не сам гард.
RT_GUARD_NAME=browser-guard-device-id

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/utf8.sh" 2>/dev/null || true
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/hook-input.sh" 2>/dev/null || true

rt_hook_read
input="$RT_HOOK_INPUT"

# Признак сессии помощнику передаётся: без него слово о ненастроенном дереве метится днём и
# приходит один раз в сутки, а не один раз за заход.
sid="$(printf '%s' "$input" | jq -r '.session_id // "nosession"' 2>/dev/null)"

device_id="$("${CLAUDE_PROJECT_DIR:-.}/.claude/hooks/browser-device-id.sh" "$sid")"
[ -z "$device_id" ] && exit 0

requested="$(printf '%s' "$input" | jq -r '.tool_input.deviceId // empty' 2>/dev/null)"
event="$(printf '%s' "$input" | jq -r '.hook_event_name // empty' 2>/dev/null)"

if [ "$event" = "PostToolUse" ]; then
    # Ответ вызова целиком строкой: он приходит объектом, строкой или списком блоков, и разбирать
    # его форму пришлось бы под каждого помощника. Судится текст — в нём видны и признак профиля,
    # и слово об отказе.
    answer="$(printf '%s' "$input" | jq -r '.tool_response // empty | if type == "string" then . else tojson end' 2>/dev/null)"

    # Отказ выбора: подключения не случилось, и метка не ставится. Слова отказа названы обоими
    # языками — помощник отвечает на своём, а дерево читает вывод на русском.
    case "$answer" in
        *'"error"'* | *'"isError":true'* | *"failed"* | *"not found"* | *"not connected"* | *"не найден"* | *"отключ"*)
            exit 0
            ;;
    esac

    # Пустой ответ подключением не считается: сказать по нему нечего, а метка утверждала бы, что
    # профиль подключён.
    [ -z "$answer" ] && exit 0

    marker_dir="${TMPDIR:-/tmp}/claude-browser-guard"
    mkdir -p "$marker_dir" 2>/dev/null && : >"$marker_dir/${sid}" 2>/dev/null
    exit 0
fi

# До вызова судится только признак профиля: метки здесь больше нет.
[ "$requested" = "$device_id" ] && exit 0

# Общий хвост отказа: два законных хода и законная форма обхода, если она у отказа есть. Файл
# может быть не разложен — тогда хвоста нет, а причина отказа остаётся прежней.
# shellcheck disable=SC1090
[ -f "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/deny-tail.sh" ] \
    && . "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/deny-tail.sh" 2>/dev/null
command -v rt_deny_tail >/dev/null 2>&1 || rt_deny_tail() { :; }

echo "Профиль «${requested}» не тот, что закреплён за проектом. Бери ${device_id} — единственный профиль, где сделан вход. $(rt_deny_tail)" >&2
exit 2
