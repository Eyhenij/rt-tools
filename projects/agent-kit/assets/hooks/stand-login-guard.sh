#!/usr/bin/env bash
# rt-hook: Stop
# Требует: hooks/deny-tail.sh
# Гард входа на стенд: ход, в котором у владельца просят войти или ввести пароль, не
# заканчивается. Stop.
#
# Зачем именно так. Стенд, вход и данные для проверки готовит агент. Требование это держалось
# памятью исполнителя и не удержало ничего: за один заход просьба «войди сам» и «введи пароль»
# прозвучала четырежды подряд, каждый раз с новым препятствием перед ней — отбитое
# классификатором поле, чужое расширение в браузере, отключившийся профиль. Препятствие
# настоящее, и потому просьба выглядит законной; работой агента она от этого быть не перестаёт.
#
# Ловится на завершении хода, а не на вызове: просьба высказывается текстом реплики, а не
# вызовом инструмента, и до конца хода её не видно ничем.
#
# ГРАНИЦА НАЗВАНА ВСЛУХ. Судится набор образцов: глагол просьбы рядом со словом о пароле, входе
# или форме. Просьба, сказанная словами вне набора, и просьба, поданная меню вариантов, гарду не
# видны. Набор открыт и пополняется правкой — полнота его открытый вопрос, а не обещание.
#
# Что законно и не отбивается: просьба об обычном режиме работы вместо автоматического. Ввод
# делает агент, а у владельца просят режим — это разные просьбы, и гард их различает.
#
# ОТКАЗ В ПОЛЬЗУ РАБОТЫ: при любой ошибке, отсутствии записи хода и повторном заходе ход
# РАЗРЕШАЕТСЯ. Сломанный гард не имеет права заклинить разговор.

# Своё имя в наблюдениях: отбой пишет общий хвост отказа, а не сам гард.
RT_GUARD_NAME=stand-login-guard

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/utf8.sh" 2>/dev/null || true
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/hook-input.sh" 2>/dev/null || true

rt_hook_read
input="$RT_HOOK_INPUT"
[ -z "$input" ] && exit 0

command -v jq >/dev/null 2>&1 || exit 0

# Повторный заход по тому же ходу не судится: гард сказал своё один раз и отпускает.
active="$(printf '%s' "$input" | jq -r '.stop_hook_active // false' 2>/dev/null)"
[ "$active" = "true" ] && exit 0

transcript="$(printf '%s' "$input" | jq -r '.transcript_path // empty' 2>/dev/null)"
[ -z "$transcript" ] && exit 0
[ -f "$transcript" ] || exit 0

# Образцы просьбы. Первая половина — просьба сделать ввод за агента, вторая — просьба войти
# самому. Слово о режиме работы в набор не входит намеренно: его просить законно.
asked_re='(введи|введите|набери|наберите|вбей|вбейте|заполни|заполните|подставь|вставь)[^.!?\n]{0,40}(пароль|учётн|учетн|логин|креды|форму входа)'
asked_re="$asked_re"'|(войди|войдите|залогинься|залогиньтесь|авторизуйся|авторизуйтесь)[^.!?\n]{0,40}(сам|сами|рукой|руками|за меня|вместо меня|пожалуйста)?'
asked_re="$asked_re"'|(нужно|надо|прошу)[^.!?\n]{0,20}(чтобы ты|чтобы вы)?[^.!?\n]{0,20}(ввёл|ввел|ввели|вошёл|вошел|вошли)[^.!?\n]{0,30}(пароль|вход|систему)'

# Ход — это всё, что записано после последнего настоящего ввода владельца. Ответ инструмента
# приходит той же ролью, поэтому строки с `tool_result` вводом не считаются.
#
# Хвост в 400 строк: запись хода растёт всю сессию, а судится только последний ход.
verdict="$(tail -n 400 "$transcript" 2>/dev/null | jq -s -r --arg re "$asked_re" '
    def is_input:
        .type == "user"
        and ((.isCompactSummary // false) | not)
        and (((.message.content // []) | if type == "array"
                then ([.[] | select(.type == "tool_result")] | length)
                else 0 end) == 0);

    (map(is_input) | rindex(true)) as $i
    | (if $i == null then . else .[$i + 1:] end) as $turn
    | [$turn[] | select(.type == "assistant") | (.message.content // [])[] | select(.type == "text") | .text] as $texts
    # Признак нечувствителен к регистру флагом, а не приведением: приведение знает только
    # латиницу, и «Введи пароль» с большой буквы проходило бы мимо набора молча.
    | if (($texts | join("\n")) | test($re; "i")) then "asked" else "pass" end
' 2>/dev/null)"

[ "$verdict" = "asked" ] || exit 0

reason="BLOCKED by stand-login-guard: у владельца просят войти или ввести пароль. Стенд, вход и данные для проверки готовит агент: препятствие перед просьбой — отбитое поле, чужое расширение в браузере, отключившийся профиль — остаётся препятствием агента.

Пути, которыми оно снимается своими силами:

    подстановка значения инструментом формы по ссылке на элемент
    выключение мешающего расширения в профиле браузера
    подъём стенда на другом адресе
    пара засева местной базы вместо боевой учётной записи

У владельца просят режим работы, а не ввод: обычный режим вместо автоматического, вход в нём — руками агента, и возврат в автоматический тем же ходом.

Гард судит один ход: следующий заход не отбивается."

# Общий хвост отказа: два законных хода. Файл может быть не разложен — тогда хвоста нет,
# а причина отказа остаётся прежней.
# shellcheck disable=SC1090
[ -f "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/deny-tail.sh" ] \
    && . "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/deny-tail.sh" 2>/dev/null
command -v rt_deny_tail >/dev/null 2>&1 || rt_deny_tail() { :; }
deny_tail_text="$(rt_deny_tail "")"
[ -n "$deny_tail_text" ] && reason="${reason}

${deny_tail_text}"

jq -n --arg r "$reason" '{decision:"block",reason:$r}' 2>/dev/null \
    || printf '{"decision":"block","reason":"stand-login-guard: вход на стенд делает агент, а не владелец."}\n'

exit 0
