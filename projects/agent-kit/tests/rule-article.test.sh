#!/usr/bin/env bash
# Сценарии разбора признака применимости у статьи правила.
#
# Судится механика: как признак читается, как образец сверяется с путём правки и что печатается,
# когда не подошло ничего. Правил дерева набор не знает — правило-проба пишется здесь же.
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

echo "признак статьи правила"

. "$HOOKS/rule-article.sh"

RULE="$(mktemp)"
cleanup() { rm -f "$RULE"; }
trap cleanup EXIT

cat > "$RULE" <<'MD'
# Правило-проба

## Как закон применяется здесь

- **Оформление берётся ступенью, а не числом.** Написанное на месте число живёт мимо шкалы и
  расходится с ней молча.
  <!-- rt-when: *.scss *.css -->
- **Статья без признака остаётся законной.** По пути правки её не выбирает никто.
- **Производное значение считается сигналом.** Геттер пересчитывается на каждом чтении.
  <!-- rt-when: *.ts -->

## Ловушки

- Пункт этого раздела статьёй не является.
MD

# Первое, ради чего работа затеяна: под правку приходит одна статья, а не правило целиком.
out="$(rt_rule_articles "$RULE" "projects/kit/src/button.scss")"
case "$out" in
    *'Оформление берётся ступенью'*) report 'SC-AK-488 — под правку стилей приходит своя статья' 'есть' 'есть' ;;
    *) report 'SC-AK-488 — под правку стилей приходит своя статья' 'нет' 'есть' ;;
esac

case "$out" in
    *'Производное значение'*) report 'SC-AK-489 — чужая статья в отказ не попадает' 'попала' 'не попала' ;;
    *) report 'SC-AK-489 — чужая статья в отказ не попадает' 'не попала' 'не попала' ;;
esac

case "$out" in
    *'rt-when'*) report 'SC-AK-490 — сам признак в печатаемую статью не входит' 'входит' 'не входит' ;;
    *) report 'SC-AK-490 — сам признак в печатаемую статью не входит' 'не входит' 'не входит' ;;
esac

out="$(rt_rule_articles "$RULE" "projects/kit/src/button.ts")"
case "$out" in
    *'Производное значение'*) report 'SC-AK-491 — другой род правки берёт другую статью' 'есть' 'есть' ;;
    *) report 'SC-AK-491 — другой род правки берёт другую статью' 'нет' 'есть' ;;
esac

# ОТКАЗ В ПОЛЬЗУ РАБОТЫ: не подошло ничего — печатается пусто, и зовущий остаётся при прежнем
# отказе. Статья без признака и правило без признаков вовсе законны оба.
out="$(rt_rule_articles "$RULE" "docs/readme.md")"
[ -z "$out" ] && report 'SC-AK-492 — не подошло ничего: печатается пусто' 'пусто' 'пусто' \
    || report 'SC-AK-492 — не подошло ничего: печатается пусто' 'не пусто' 'пусто'

PLAIN="$(mktemp)"
printf '# Правило\n\n## Как закон применяется здесь\n\n- **Статья без признака.** Текст.\n' > "$PLAIN"
out="$(rt_rule_articles "$PLAIN" "projects/kit/src/button.scss")"
[ -z "$out" ] && report 'SC-AK-493 — правило без единого признака отбивает прежним текстом' 'пусто' 'пусто' \
    || report 'SC-AK-493 — правило без единого признака отбивает прежним текстом' 'не пусто' 'пусто'
rm -f "$PLAIN"

# Образец без каталога сверяется и с именем файла: статья говорит «про такие файлы», а правка
# приходит полным путём.
NAMED="$(mktemp)"
printf '# Правило\n\n## Как закон применяется здесь\n\n- **Статья про состав.** Текст.\n  <!-- rt-when: package.json -->\n' > "$NAMED"
out="$(rt_rule_articles "$NAMED" "apps/admin/package.json")"
case "$out" in
    *'Статья про состав'*) report 'SC-AK-494 — образец без каталога сверяется с именем файла' 'есть' 'есть' ;;
    *) report 'SC-AK-494 — образец без каталога сверяется с именем файла' 'нет' 'есть' ;;
esac
rm -f "$NAMED"

# Раскрытие имён при разборе образцов выключено: иначе `*.scss` развернулось бы в имена файлов
# рабочего каталога, и статья выбиралась бы по тому, откуда позвали.
WORK="$(mktemp -d)"
: > "$WORK/other.scss"
out="$(cd "$WORK" && rt_rule_articles "$RULE" "projects/kit/src/button.scss")"
case "$out" in
    *'Оформление берётся ступенью'*) report 'SC-AK-495 — рабочий каталог на выбор статьи не влияет' 'есть' 'есть' ;;
    *) report 'SC-AK-495 — рабочий каталог на выбор статьи не влияет' 'нет' 'есть' ;;
esac
rm -rf "$WORK"

# Файла правила нет вовсе, путь правки пуст — оба случая проходят молча.
out="$(rt_rule_articles "$RULE/нет-такого" "projects/kit/src/button.scss")"; code=$?
[ "$code" -eq 0 ] && [ -z "$out" ] && report 'SC-AK-496 — правила нет: молчание, а не отказ' 'пусто' 'пусто' \
    || report 'SC-AK-496 — правила нет: молчание, а не отказ' "код:$code" 'пусто'

out="$(rt_rule_articles "$RULE" '')"; code=$?
[ "$code" -eq 0 ] && [ -z "$out" ] && report 'SC-AK-497 — пути правки нет: молчание, а не отказ' 'пусто' 'пусто' \
    || report 'SC-AK-497 — пути правки нет: молчание, а не отказ' "код:$code" 'пусто'

suite_result "признак статьи правила"
