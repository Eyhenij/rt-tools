#!/usr/bin/env bash
# Сценарий: источник пакета не несёт шапку установки файлов из пакета.
#
# Шапку ставят копиям, которые раскладываются в дерево. У источника она ничего не значит, зато
# проверка источника правил читает её и отказывает в правке файла — указывая в ответе на тот же
# самый путь. Файл после этого не правится вовсе, и увидеть это можно только наткнувшись.
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

echo "источники пакета: шапки установки нет"

# Сколько файлов каталога несут шапку во второй строке. Читаются все роды ресурсов, не одни
# проверки: шапку ставит раскладка любому файлу, который она кладёт в дерево.
headers_in() {
    local root="$1" count=0 line
    while IFS= read -r file; do
        line="$(sed -n '2p' "$file")"
        case "$line" in
            *'rt-kit v'*) count=$((count + 1)) ;;
        esac
    done < <(find "$root" -type f \( -name '*.mjs' -o -name '*.sh' \) | sort)
    printf '%s' "$count"
}

# --- SC-AK-1158 — источник пакета не несёт шапку установки ---------------------------------
SRC_ROOT="$(cd "$CHECKS/.." && pwd)"
report "SC-AK-1158 — источников с шапкой нет" "$(headers_in "$SRC_ROOT")" 0

# Обратная сторона того же: подложенная шапка находится. Без этой пробы зелёный ответ выше
# одинаково значил бы «шапок нет» и «искали не то».
PLANT="$(mktemp -d)"
printf '%s\n' '#!/usr/bin/env node' '// rt-kit v0.29.0 · checks/probe.mjs · 0123456789ab · правится надстройкой, не здесь' \
    > "$PLANT/probe.mjs"
report "SC-AK-1158 — подложенная шапка находится" "$(headers_in "$PLANT")" 1
rm -rf "$PLANT"

suite_result "источники пакета: шапки установки нет"
