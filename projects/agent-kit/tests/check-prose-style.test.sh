#!/usr/bin/env bash
# Сценарии проверки слога: что она ловит, чего не трогает и что называет заменой.
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

echo "проверка слога"

WORK="$(mktemp -d)"
cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT

CHECK_FILE="${HOOKS%/hooks}/checks/check-prose-style.mjs"

run_on() {
    printf '%s\n' "$2" > "$WORK/proba.md"
    node "$CHECK_FILE" "$WORK/proba.md" 2>&1
}

finds() {
    local label="$1" text="$2" pattern="$3" got
    if run_on "$label" "$text" | grep -qiE "$pattern"; then got="есть"; else got="нет"; fi
    report "$label" "$got" "есть"
}

clean() {
    local label="$1" text="$2" got
    if run_on "$label" "$text" | grep -q "находок нет"; then got="чисто"; else got="находка"; fi
    report "$label" "$got" "чисто"
}

# --- канцелярит -------------------------------------------------------------------------
finds "SC-AK-327 — «является» ловится и названа замена" \
    'Проверка является инструментом.' 'является.*глаголом'
finds "SC-AK-328 — «в целях» ловится" 'В целях ускорения сборки.' 'в целях.*чтобы'
finds "SC-AK-329 — «данный» ловится" 'Данный файл правится.' 'Данный.*этот'

# --- слова, которых в этом дереве не пишут ------------------------------------------------
# Границы слова считаются по буквам, а не `\b`: он ASCII-only, и кириллица под `\w` не подпадает —
# образец с ним не срабатывает ни разу и молчит об этом.
finds "SC-AK-330 — слово из левой колонки словаря ловится" 'Эта таска в бэклоге.' 'таска.*задача'
finds "SC-AK-331 — и его словоформа тоже" 'Эта таска в бэклоге.' 'бэклоге.*очередь работ'

# --- длина предложения ---------------------------------------------------------------------
LONG="$(python3 -c "print('слово ' * 45 + '.')")"
finds "SC-AK-332 — слишком длинное предложение ловится" "$LONG" 'слов в предложении'

# --- чего проверка не трогает --------------------------------------------------------------
clean "SC-AK-333 — чистый текст проходит" 'Гард отбивает правку. Отказ называет следующий шаг.'
clean "SC-AK-334 — блок кода не судится" '```
Данный файл является примером в целях проверки.
```'
# Слово внутри другого слова находкой не считается: иначе проверка ловила бы половину дерева.
clean "SC-AK-335 — слово внутри другого слова не ловится" 'Заявление подано.'

suite_result "проверка слога"
