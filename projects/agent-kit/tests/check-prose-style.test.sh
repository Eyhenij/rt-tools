#!/usr/bin/env bash
# Сценарии проверки слога: что она ловит, чего не трогает и что называет заменой.
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

echo "проверка слога"

WORK="$(mktemp -d)"
cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT

CHECK_FILE="${HOOKS%/hooks}/checks/check-prose-style.mjs"

run_on() {
    printf '%s\n' "$2" > "$WORK/proba.md"
    node "$CHECK_FILE" "$WORK/proba.md" 2>&1
}

finds() {
    local label="$1" text="$2" pattern="$3" got
    if run_on "$label" "$text" | grep -qiE "$pattern"; then got="есть"; else got="нет"; fi
    report "$label" "$got" "есть"
}

clean() {
    local label="$1" text="$2" got
    if run_on "$label" "$text" | grep -q "no findings"; then got="чисто"; else got="находка"; fi
    report "$label" "$got" "чисто"
}

# --- канцелярит -------------------------------------------------------------------------
finds "SC-AK-327 — «является» ловится и названа замена" \
    'Проверка является инструментом.' 'является.*глаголом'
finds "SC-AK-328 — «в целях» ловится" 'В целях ускорения сборки.' 'в целях.*чтобы'
finds "SC-AK-329 — «данный» ловится" 'Данный файл правится.' 'Данный.*этот'

# --- SC-AK-903 — английский канцелярит ------------------------------------------------------
# Слой правил пишется по-английски, и русский набор на нём молчал: образец с кириллической
# границей не совпадает ни с одним латинским словом. Оба набора судят каждую строку.
finds "SC-AK-903 — «in order to» ловится и названа замена" \
    'The check runs in order to find the word.' 'in order to.*to'
finds "SC-AK-903 — «utilize» ловится в любой форме" 'The hook utilizes the list.' 'utilizes.*use'
finds "SC-AK-903 — «is able to» ловится" 'The guard is able to refuse.' 'is able to.*can'
clean "SC-AK-903 — чистый английский текст проходит" 'The guard refuses the edit. The refusal names the next step.'
clean "SC-AK-903 — латинское слово внутри другого слова не ловится" 'Priority is set by the owner.'
finds "SC-AK-903 — русский набор при этом остался" 'Проверка является инструментом.' 'является'

# --- слова, которых в этом дереве не пишут ------------------------------------------------
# Границы слова считаются по буквам, а не `\b`: он ASCII-only, и кириллица под `\w` не подпадает —
# образец с ним не срабатывает ни разу и молчит об этом.
finds "SC-AK-330 — слово из левой колонки словаря ловится" 'Эта таска в бэклоге.' 'таска.*задача'
finds "SC-AK-331 — и его словоформа тоже" 'Эта таска в бэклоге.' 'бэклоге.*очередь работ'

# --- длина предложения ---------------------------------------------------------------------
LONG="$(python3 -c "print('слово ' * 45 + '.')")"
finds "SC-AK-332 — слишком длинное предложение ловится" "$LONG" 'words in a sentence'

# --- чего проверка не трогает --------------------------------------------------------------
clean "SC-AK-333 — чистый текст проходит" 'Гард отбивает правку. Отказ называет следующий шаг.'
clean "SC-AK-334 — блок кода не судится" '```
Данный файл является примером в целях проверки.
```'
# Слово внутри другого слова находкой не считается: иначе проверка ловила бы половину дерева.
clean "SC-AK-335 — слово внутри другого слова не ловится" 'Заявление подано.'

# Имя обязательного раздела спека совпадает с образцом канцелярита, но прозой не является:
# набор разделов требует его дословно, и без исключения нового спека не написать вовсе.
clean "SC-AK-393 — заголовок обязательного раздела спека не судится" '## Данные'
finds "SC-AK-394 — то же слово в предложении ловится по-прежнему" \
    'Данные требования приняты.' 'Данные.*эти'

# SC-AK-859. «Данные» бывает и существительным, и заменить его нечем: данные стенда — это данные.
# Проверяется оно поэтому по тому, что стоит следом: местоимением читается перед словом, которое
# само и определяет.
clean "SC-AK-859 — существительное «данные» не считается находкой" 'Спека необратимо меняет данные стенда.'
clean "SC-AK-859 — и во втором падеже тоже" 'Тесты правят данные живой базы.'
finds "SC-AK-859 — местоимение перед своим словом распознаётся" \
    'Данные условия выполнены.' 'Данные.*эти'

# SC-AK-865. Цитата закона не судится: слова, которые проверка отбивает, стоят в самих законах
# десятками, и правка цитаты меняет чужой текст. Признак узкий — блок вводится адресом закона,
# иначе цитата стала бы местом, куда прячут своё письмо.
clean "SC-AK-865 — цитата закона не судится" 'Статья `docs/constitution/work-conduct.md` говорит:

> Отбитая правка является поводом остановиться.'
finds "SC-AK-865 — своя строка рядом с цитатой судится по-прежнему" \
    'Статья `docs/constitution/work-conduct.md` говорит:

> Отбитая правка является поводом остановиться.

Своё письмо является продолжением.' 'является'
clean "SC-AK-865 — блок цитаты без адреса закона своё письмо не прячет" '> Обычная цитата.'
finds "SC-AK-865 — своё письмо в цитате без адреса закона ловится" \
    '> Правка является поводом.' 'является'

# --- SC-AK-868 — слова дерева сверх пакетных ------------------------------------------------
#
# Левую колонку словаря дерево дописывает надстройкой, и не судило её ничто: набор образцов был
# зашит в код проверки. Дерево заводило свою проверку рядом — второй набор на одно требование,
# и разойтись они могли молча. Настройка читается от корня дерева, поэтому фикстуре нужен свой
# корень с копией проверок.

TREE="$(mktemp -d)"
mkdir -p "$TREE/tools" "$TREE/.claude/rt-kit"
cp "$CHECKS/check-prose-style.mjs" "$CHECKS/rt-kit-checks.config.mjs" "$TREE/tools/"

tree_says() {
    printf '%s\n' "$2" > "$TREE/proba.md"
    (cd "$TREE" && node tools/check-prose-style.mjs proba.md 2>&1)
}

tree_bans() {
    printf '%s\n' "$1" > "$TREE/.claude/rt-kit/checks.json"
}

tree_bans '{ "prose": { "glossaryBans": [{ "pattern": "деплой[а-яё]*", "fix": "выкатка" }] } }'
if tree_says label 'Деплой прошёл ночью.' | grep -qiE 'Деплой.*выкатка'; then got="есть"; else got="нет"; fi
report "SC-AK-868 — слово дерева ловится наравне с пакетными" "$got" "есть"

if tree_says label 'Эта таска в бэклоге.' | grep -qiE 'таска.*задача'; then got="есть"; else got="нет"; fi
report "SC-AK-868 — пакетные слова при этом остались" "$got" "есть"

tree_bans '{ "prose": { "glossaryBans": [{ "pattern": "[", "fix": "ничего" }] } }'
if tree_says label 'Эта таска в бэклоге.' | grep -qiE 'таска.*задача'; then got="есть"; else got="нет"; fi
report "SC-AK-868 — негодный образец проверку не роняет" "$got" "есть"

rm -rf "$TREE"

suite_result "проверка слога"
