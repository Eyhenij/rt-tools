#!/usr/bin/env bash
# Сценарии текстов пакета: правило переносится между репозиториями, адресность — нет.
#
# Правило, назвавшее домен, порт или файл конкретного дерева, в чужом дереве читается как
# описание чужой работы: пути там другие, а домена может не быть вовсе. Для адресности заведены
# два места — компаньон `implementation.md` рядом с правилом и дырки со значениями, — и этот
# набор стережёт границу между ними.
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

echo "тексты"

TEXTS="$ASSETS/rules $ASSETS/patterns"

# Семьи и общие домены — соглашение мастерской, верное в любом её дереве: они объявлены законом
# об импортах, а не выбраны одним репозиторием. Всё, что глубже, — имя, которого в соседнем
# дереве может не быть.
COMMON_SEGMENTS='common|util|proto|platform|i18n|core'

# --- домены конкретного дерева ------------------------------------------------------------
#
# Ограда блока кода запретов не снимает: узел графа и строка команды — тот же текст ресурса, и
# путь чужого дерева в них остаётся путём чужого дерева. Поэтому перечень ищется по файлу
# целиком, а не по одной прозе.
#
# Безымянный образец — `libs/<домен>`, `<Feature>Component` — под перечень не подпадает: имя в
# угловых скобках не адресует ничего, и перечень признаков закрытый.
domains_in() {
    grep -rhoE "libs/(site|admin|api)/[a-z][a-z0-9-]*" "$@" 2>/dev/null \
        | grep -vE "libs/(site|admin|api)/($COMMON_SEGMENTS)\$" | sort -u
}

found_domains="$(domains_in $TEXTS)"
if [ -z "$found_domains" ]; then
    report "в текстах нет доменов конкретного дерева" PASS PASS
else
    report "в текстах нет доменов конкретного дерева" "$(printf '%s' "$found_domains" | tr '\n' ' ')" PASS
fi

# --- порты ----------------------------------------------------------------------------------
# Порт стенда у каждого дерева свой, и записанный числом он врёт молча: команда выполняется и
# отвечает не тем стендом. Для него заведена дырка — раскладка требует значения.
#
# Порт, который поднимает та же команда, что и обращается к нему, — не адресность: одноразовая
# база в контейнере живёт ровно столько, сколько идёт проверка, и её номер ничего не адресует.
# Такие порты объявлены рядом публикацией `-p <порт>:` и из счёта уходят.
published="$(grep -rhoE '\-p[[:space:]]+[0-9]{4,5}:[0-9]{2,5}' $TEXTS 2>/dev/null | grep -oE '[0-9]{4,5}' | sort -u)"
found_ports="$(grep -rhoE "localhost:[0-9]{4,5}|iTCP:[0-9]{4,5}|PORT=[0-9]{4,5}" $TEXTS 2>/dev/null \
    | grep -oE '[0-9]{4,5}' | sort -u)"
for port in $published; do
    found_ports="$(printf '%s\n' "$found_ports" | grep -vx "$port")"
done
found_ports="$(printf '%s' "$found_ports" | grep -E '[0-9]' | sort -u)"
if [ -z "$found_ports" ]; then
    report "в текстах нет записанных числом портов" PASS PASS
else
    report "в текстах нет записанных числом портов" "$(printf '%s' "$found_ports" | tr '\n' ' ')" PASS
fi

# --- раздел «Где это лежит» ------------------------------------------------------------------
# Пути живут в компаньоне: правило переносится, раскладка — нет. Правило, у которого в этом
# разделе стоит таблица путей, дублирует то, что проект обязан написать у себя, — и расходится
# с ним при первой же правке дерева.
with_paths=0
for rule in "$ASSETS"/rules/*.md; do
    section="$(awk '/^## Где это лежит$/{take=1; next} /^## /{take=0} take' "$rule")"
    # Ссылка на сам компаньон путём не считается: она и есть указание, куда пути переехали.
    printf '%s' "$section" | grep -vF 'implementation.md' | grep -qE '`[a-zA-Z0-9_./-]+\.(ts|mjs|json|scss|html|md|sh)`' && {
        report "без таблицы путей: ${rule##*/}" FAIL PASS
        with_paths=$((with_paths + 1))
    }
done
[ "$with_paths" -eq 0 ] && report "ни одно правило не везёт чужих путей" PASS PASS

# --- дырки объявлены ---------------------------------------------------------------------------
# Дырка, оставшаяся в тексте, — обещание значения: раскладка откажет, пока дерево его не назовёт.
# Проверяется, что имена дырок читаются целиком, а не обрываются на первом же символе разметки.
#
# Дырок может не быть, и это законное состояние набора, а не провал: порты стендов перенесены
# из паттернов в профиль дерева, и после этого проверять целостность имени не на чем.
# Требование «хоть одна дырка» держало бы в текстах чужое значение ради самой проверки.
holes="$(grep -rhoE '\{\{[a-zA-Z][a-zA-Z0-9.-]*\}\}' $TEXTS 2>/dev/null | sort -u | tr -d '{}' | tr '\n' ' ')"
if [ -n "$(printf '%s' "$holes" | tr -d '[:space:]')" ]; then
    report "дырки в текстах читаются" "$(printf '%s' "$holes" | grep -cE '[a-zA-Z]')" 1
else
    report "дырок в текстах не осталось — читать нечего" PASS PASS
fi

# --- SC-AK-67 — счёт шагов работы сплошной ----------------------------------------------------
# Номер шага называют вслух, и два разных первых шага мешают разговору. Целого при этом не
# видит ни один паттерн, поэтому список шагов лежит в правиле, а паттерны только носят номера.
steps="$(grep -rhoE '^#{2,3} [0-9]+\. ' "$ASSETS"/patterns/task-flow-*.md | grep -oE '[0-9]+' | sort -n)"
report "SC-AK-67 — номер шага не повторяется" "$(printf '%s\n' "$steps" | uniq -d | grep -c '[0-9]')" 0

listed="$(awk '/^## Шаги работы$/{take=1; next} /^## /{take=0} take' "$ASSETS/rules/task-flow.md" \
    | grep -cE '^\| [0-9]+ +\|')"
report "SC-AK-67 — шаги перечислены в правиле" "$listed" "$(printf '%s\n' "$steps" | grep -c '[0-9]')"

# --- SC-AK-68 — правилу об оформлении документов есть куда вписать скилы дерева ----------------
# Одноимённый раздел надстройки замещает пакетный целиком, поэтому дерево, дописывающее своё в
# чужой раздел, теряет его пакетные пункты вместе со своей припиской.
report "SC-AK-68 — раздел под скилы дерева заведён" "$(grep -c '^## Скилы дерева$' "$ASSETS/rules/doc-style.md")" 1

# --- SC-AK-94 — ресурс не утверждает про дерево того, чего не знает ---------------------------
# Гард, названный безусловно, приходит в контекст каждой сессии и врёт про дерево, где его не
# разложили, — тем увереннее, что печатает это сам инструмент. Ловится по глаголам утверждения
# рядом со словом «гард» в печатаемых строках хуков: у хука надстройки нет, и поправить такую
# строку дерево не может ничем.
claims="$(grep -rhnE "printf '[^']*(отбивает|стоит|разложен) гард" "$ASSETS"/hooks/*.sh 2>/dev/null \
    | grep -vE 'если|нет:|`[a-z-]+`' | sort -u)"
if [ -z "$claims" ]; then
    report "SC-AK-94 — о соседнем гарде сказано условно" PASS PASS
else
    report "SC-AK-94 — о соседнем гарде сказано условно" "$(printf '%s' "$claims" | tr '\n' ' ')" PASS
fi

# --- SC-AK-215, SC-AK-228 — блок кода и безымянный образец --------------------------------------
#
# Набор, зелёный на своём же корпусе, зелен и тогда, когда ищет не там. Поэтому адрес дерева
# подставляется в копию — сперва внутрь блока кода, потом безымянным образцом.
probe="$(mktemp -d)"
printf '# Проба\n\n```bash\nnx test libs/site/booking\n```\n' > "$probe/rule.md"
report "SC-AK-215 — адрес дерева внутри блока кода найден" \
    "$(domains_in "$probe" | grep -c 'libs/site/booking')" 1

printf '# Проба\n\n```bash\nnx test libs/site/<домен>\n```\n' > "$probe/rule.md"
report "SC-AK-228 — безымянный образец адресом не считается" \
    "$(domains_in "$probe" | grep -c '[a-z]')" 0

rm -rf "$probe"

suite_result "тексты"
