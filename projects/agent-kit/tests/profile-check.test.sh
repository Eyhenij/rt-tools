#!/usr/bin/env bash
# Сценарии слова о нехватке функции профиля.
#
# Проверяется ровно то, ради чего помощник заведён: гард без своей функции больше не выходит
# молча. Молчание означало разом «нечего проверять», «проверять нечем» и «всё в порядке», и
# отличить их было нечем — гард лежал в дереве, стоял в настройке и читался как работающий.
#
# Второе свойство важно не меньше первого: сказав о нехватке, гард всё равно пропускает
# действие. Он сообщает о своей неполноте, а не судит правку — судить её ему нечем.
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

echo "нехватка профиля"

TMP="$(mktemp -d)"
cleanup() { rm -rf "$TMP"; }
trap cleanup EXIT
export TMPDIR="$TMP"

# shellcheck disable=SC1091
. "$HOOKS/profile-check.sh"

# Что сказал помощник и с каким исходом. Вывод идёт в поток ошибок: это сообщение о состоянии
# дерева, а не ответ гарда агенту.
said() {
    rt_needs "$1" проба "$2" 2>"$TMP/said"
    printf '%s' "$(cat "$TMP/said")"
}

rt_defined_probe() { return 0; }

# SC-AK-88. Функции нет — хук называет её имя и файл, в котором её определяют.
out="$(said rt_absent_probe s1)"
case "$out" in
    *rt_absent_probe*project.sh*) report "SC-AK-88 — назвал функцию и файл" да да ;;
    *) report "SC-AK-88 — назвал функцию и файл" "$out" да ;;
esac

# SC-AK-90. Сказав о нехватке, помощник отвечает отказом — но отказ этот про себя, а не про
# правку: гард по нему уходит с нулём и действие пропускает.
if rt_needs rt_absent_probe проба s1 2>/dev/null; then
    report "SC-AK-90 — нехватка действие не отбивает" да нет
else
    report "SC-AK-90 — нехватка действие не отбивает" нет нет
fi

# SC-AK-89. Второй раз за ту же сессию — молча: та же строка на каждый вызов повторялась бы
# десятки раз за заход и перестала бы читаться.
out="$(said rt_absent_probe s1)"
report "SC-AK-89 — второй раз за сессию молчит" "$out" ''

# Новая сессия — сказано снова: отметка живёт заход, а не жизнь машины.
out="$(said rt_absent_probe s2)"
case "$out" in
    *rt_absent_probe*) report "новая сессия слышит то же" да да ;;
    *) report "новая сессия слышит то же" "$out" да ;;
esac

# Функция есть — помощник молчит и отвечает успехом: говорить не о чем.
out="$(said rt_defined_probe s3)"
report "определённая функция молчит" "$out" ''
if rt_needs rt_defined_probe проба s3 2>/dev/null; then
    report "определённая функция — успех" да да
else
    report "определённая функция — успех" нет да
fi

suite_result "нехватка профиля"
