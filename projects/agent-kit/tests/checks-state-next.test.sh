#!/usr/bin/env bash
# Сценарии проверки строк следующего движения: раздел без строки, списанный у соседа хвост,
# зачин без движения, молчание трёх текстов о границе состояния и место проверки в наборе
# гейта пуша.
#
# Дерево здесь своё и синтетическое: проверка ищет правило, паттерны, карту и закон от корня, и
# набор, запущенный в дереве-потребителе, судил бы это дерево, а не механику ресурса.
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

echo "проверки: следующее движение"

NEXT_TREE="$(mktemp -d)"
mkdir -p "$NEXT_TREE/tools" "$NEXT_TREE/.claude/skills" "$NEXT_TREE/.claude/rt-kit/defaults" "$NEXT_TREE/docs/constitution"
cp "$CHECKS/check-state-next.mjs" "$NEXT_TREE/tools/"
next_cleanup() { rm -rf "$NEXT_TREE"; }
trap next_cleanup EXIT

next_code() {
    (cd "$NEXT_TREE" && node tools/check-state-next.mjs >/dev/null 2>&1)
    printf '%s' "$?"
}
next_says() {
    (cd "$NEXT_TREE" && node tools/check-state-next.mjs 2>&1) | grep -cE "$1"
}

# Правило: таблица состояний в четыре столбца и утверждение о границе состояния.
write_rule() {
    mkdir -p "$NEXT_TREE/.claude/skills/task-flow"
    cat > "$NEXT_TREE/.claude/skills/task-flow/SKILL.md" <<'EOF'
# Ведение работы

| Состояние | Вход в него | Обязательное действие | Ведёт паттерн |
| --------- | ----------- | --------------------- | ------------- |
| `первое`  | просьба     | разведка              | `сцена`       |
| `второе`  | разведка    | замысел               | `сцена`       |

Переход из состояния в состояние ходом не кончается: обязательное действие сделано, и
следующее делается тем же ходом.
EOF
}

# Паттерн: два раздела состояния, у каждого своя строка следующего движения.
write_pattern() {
    mkdir -p "$NEXT_TREE/.claude/skills/сцена"
    cat > "$NEXT_TREE/.claude/skills/сцена/SKILL.md" <<'EOF'
# Сцена

## Состояние `первое`: разведка идёт до первого вопроса

Приёмы разведки.

**Следующее движение:** находки ложатся в разбор, и тем же ходом уходит первый вопрос.

## Состояние `второе`: замысел пишется этапами

Приёмы замысла.

**Следующее движение:** замысел коммитится, и тем же ходом начинается первый этап.
EOF
}

write_map() {
    printf '# Карта хода\n\nПереход из состояния в состояние — тем более.\n' \
        > "$NEXT_TREE/.claude/rt-kit/defaults/turn-map.md"
}

write_law() {
    printf '# Закон о ведении работы\n\nПереход из состояния в состояние исполнителя не останавливает.\n' \
        > "$NEXT_TREE/docs/constitution/work-conduct.md"
}

write_rule
write_pattern
write_map
write_law

# SC-AK-447 — у каждого раздела состояния есть строка следующего движения
report "SC-AK-447 — полное дерево проходит" "$(next_code)" 0
report "SC-AK-447 — вывод называет число разделов" "$(next_says 'разделов состояния 2')" 1

# SC-AK-449 — строка находится по зачину, а не по дословному совпадению: хвосты у разделов
# разные, и оба раздела при этом считаются описанными.
report "SC-AK-449 — разные хвосты после общего зачина сходятся" "$(next_code)" 0

# SC-AK-448 — раздел без строки отбивается с именем состояния и паттерна
sed -i.bak 's/^\*\*Следующее движение:\*\* находки ложатся.*/Находки ложатся в разбор./' \
    "$NEXT_TREE/.claude/skills/сцена/SKILL.md"
report "SC-AK-448 — раздел без строки отбит" "$(next_code)" 1
report "SC-AK-448 — отказ называет состояние и паттерн" "$(next_says '`первое` в паттерне `сцена`')" 1
report "SC-AK-448 — отказ называет заголовок раздела" "$(next_says 'разведка идёт до первого вопроса')" 1
write_pattern

# SC-AK-450 — списанная у соседа строка отбивается
sed -i.bak 's/^\*\*Следующее движение:\*\* замысел коммитится.*/**Следующее движение:** находки ложатся в разбор, и тем же ходом уходит первый вопрос./' \
    "$NEXT_TREE/.claude/skills/сцена/SKILL.md"
report "SC-AK-450 — списанный хвост отбит" "$(next_code)" 1
report "SC-AK-450 — отказ называет оба раздела" "$(next_says 'слово в слово то же, что у `первое`')" 1
write_pattern

# SC-AK-451 — зачин без движения за ним отбивается
sed -i.bak 's/^\*\*Следующее движение:\*\* замысел коммитится.*/**Следующее движение:** дальше./' \
    "$NEXT_TREE/.claude/skills/сцена/SKILL.md"
report "SC-AK-451 — зачин без движения отбит" "$(next_code)" 1
report "SC-AK-451 — отказ говорит, чего не хватает" "$(next_says 'зачин есть, а движение за ним не названо')" 1
write_pattern

# SC-AK-453 — правило без утверждения о границе отбивается той же проверкой
sed -i.bak 's/^Переход из состояния в состояние ходом.*/Переход между состояниями ходом не кончается./' \
    "$NEXT_TREE/.claude/skills/task-flow/SKILL.md"
report "SC-AK-453 — правило без статьи отбито" "$(next_code)" 1
report "SC-AK-453 — отказ называет правило, а не разделы" "$(next_says 'правило ведения работы о границе состояния молчит')" 1
write_rule

# SC-AK-454 — карта хода говорит о переходе то же, что и правило
printf '# Карта хода\n\nСпособов четыре.\n' > "$NEXT_TREE/.claude/rt-kit/defaults/turn-map.md"
report "SC-AK-454 — карта без строки о границе отбита" "$(next_code)" 1
report "SC-AK-454 — отказ называет карту" "$(next_says 'карта хода о границе состояния молчит')" 1
write_map

# SC-AK-455 — закон о ведении работы называет границу состояния статьёй
printf '# Закон о ведении работы\n\nСтатей тут нет.\n' > "$NEXT_TREE/docs/constitution/work-conduct.md"
report "SC-AK-455 — закон без статьи отбит" "$(next_code)" 1
report "SC-AK-455 — отказ называет закон" "$(next_says 'закон о ведении работы о границе состояния молчит')" 1
write_law

# Карты и закона в дереве может не быть вовсе — тогда сверять их нечем, и проверка молчит.
rm "$NEXT_TREE/.claude/rt-kit/defaults/turn-map.md" "$NEXT_TREE/docs/constitution/work-conduct.md"
report "следующее движение: дерево без карты и закона проходит" "$(next_code)" 0
write_map
write_law

# SC-AK-457 — сломанный перечень состояний отказом считается
printf '# Ведение работы\n\nПереход из состояния в состояние ходом не кончается.\n' \
    > "$NEXT_TREE/.claude/skills/task-flow/SKILL.md"
report "SC-AK-457 — перечень без таблицы отбит" "$(next_code)" 1
report "SC-AK-457 — отказ говорит, что перечень сломан" "$(next_says 'не нашлось таблицы состояний')" 1
write_rule

# SC-AK-456 — дерево без правила ведения работы проверку проходит
rm -r "$NEXT_TREE/.claude/skills/task-flow"
report "SC-AK-456 — дерева без правила проверка не судит" "$(next_code)" 0
report "SC-AK-456 — молчание объяснено" "$(next_says 'сверять нечего')" 1
write_rule

# Ведущий паттерн, которого в дереве нет, здесь не судится: его называет сверка состояний, и
# два отказа об одном промахе читаются как две претензии.
rm -r "$NEXT_TREE/.claude/skills/сцена"
report "следующее движение: неразложенный паттерн не судится" "$(next_code)" 1
report "следующее движение: отказ про разделы, а не про паттерн" "$(next_says 'ни одного раздела состояния не нашлось')" 1
write_pattern

# SC-AK-458 — проверка стоит своей строкой в наборе гейта пуша
GATE_TREE="$(fixture_tree)"
mkdir -p "$GATE_TREE/tools"
printf '' > "$GATE_TREE/tools/check-state-next.mjs"
gate_line="$(
    CLAUDE_PROJECT_DIR="$GATE_TREE" bash -c ". '$DEFAULTS/project.sh'; rt_push_checks_default ''" \
        | grep -c 'node tools/check-state-next.mjs'
)"
report "SC-AK-458 — гейт пуша зовёт проверку" "$gate_line" 1
rm -rf "$GATE_TREE"

# SC-AK-452 — правило, карта и закон пакета говорят о границе одними словами: признак, который
# проверка ищет, живёт в самих ресурсах, и разойдясь с ними, она перестаёт что-либо значить.
report "SC-AK-452 — правило пакета говорит о границе" \
    "$(grep -c 'Переход из состояния в состояние' "$ASSETS/rules/task-flow.md")" 1
report "SC-AK-454 — карта пакета говорит о границе" \
    "$(grep -c 'Переход из состояния в состояние' "$ASSETS/defaults/turn-map.md")" 1
report "SC-AK-455 — закон пакета говорит о границе" \
    "$(grep -c 'Переход из состояния в состояние' "$ASSETS/laws/work-conduct.md")" 1

suite_result "проверки: следующее движение"
