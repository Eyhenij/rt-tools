#!/usr/bin/env bash
# Что проверка заголовка коммита говорит о языке описания.
#
# Проверка стоит в дереве, а не в пакете: набор родов правки и список областей — имена этого
# репозитория, и переносить их некуда. Судится она заголовками, а не живым коммитом: у коммита
# заголовок один, а случаев несколько, и хук гита позвать их по очереди не даёт.
#
# Печатает строку на случай: ожидание против полученного. Ненулевой код — хоть один разошёлся.
set -u

root="$(cd "$(dirname "$0")/../../.." && pwd)"
ok=0
bad=0

# Что проверка отвечает на такой заголовок: «прошёл» или «отбит».
verdict_for() {
    if printf '%s\n' "$1" | (cd "$root" && npx --no -- commitlint) > /dev/null 2>&1; then
        printf 'прошёл'
    else
        printf 'отбит'
    fi
}

# Случай: заголовок, ожидание, чем случай важен.
probe() {
    header="$1"
    want="$2"
    about="$3"
    got="$(verdict_for "$header")"

    if [ "$got" = "$want" ]; then
        ok=$((ok + 1))
        printf '  ok   %s — %s\n' "$want" "$about"
    else
        bad=$((bad + 1))
        printf '  ПЛОХО ждали «%s», получили «%s» — %s\n    заголовок: %s\n' "$want" "$got" "$about" "$header"
    fi
}

printf 'Язык описания коммита\n'

probe 'chore(rt:agent-kit): bump version to 0.13.0 [ci skip]' 'отбит' \
    'английское описание — тот самый коммит выпуска, с которого работа началась'
probe 'chore(rt:agent-kit): версия пакета поднята до 0.13.0 [ci skip]' 'прошёл' \
    'русское описание со служебной пометкой пропуска конвейера'
probe 'fix(rt:ui-kit): кнопка держит высоту при длинной подписи' 'прошёл' \
    'обычная запись о правке'
probe 'docs(rt:agent-kit): правило поставки говорит про язык описания' 'прошёл' \
    'запись о тексте'
probe 'feat(rt:message-bus): приёмник отдаёт cargo-pull одним вызовом' 'прошёл' \
    'русское описание с латинским именем команды — латиница сама по себе не отбивается'
probe 'refactor(rt:store): move state to signals' 'отбит' \
    'английское описание без единой русской буквы'

printf '\nсошлось: %d, разошлось: %d\n' "$ok" "$bad"
[ "$bad" -eq 0 ]
