#!/usr/bin/env bash
# Сценарии помощника, который называет закреплённый профиль браузера.
#
# Проверяется механика: откуда берётся значение и что происходит, когда его нет нигде. Второе
# важнее первого — молчание ненастроенного дерева читалось как «всё в порядке», и пять гардов
# пропускали всё подряд шесть суток. Пропуск при этом остаётся: помощник говорит о своей
# неполноте, а не судит работу.
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

echo "профиль браузера"

TMP="$(mktemp -d)"
cleanup() { rm -rf "$TMP"; }
trap cleanup EXIT
export TMPDIR="$TMP"

tree="$(mktemp -d)"
mkdir -p "$tree/.claude/rt-kit"
export CLAUDE_PROJECT_DIR="$tree"

# Что напечатано в поток вывода, и отдельно — что сказано в поток ошибок.
said() {
    RT_BROWSER_DEVICE_ID="${RT_BROWSER_DEVICE_ID:-}" bash "$HOOKS/browser-device-id.sh" "$@" 2>"$TMP/said"
}
heard() { printf '%s' "$(cat "$TMP/said")"; }

# SC-AK-717. Значение из переменной окружения перебивает всё остальное.
out="$(RT_BROWSER_DEVICE_ID=из-переменной said s1)"
report "SC-AK-717 — значение берётся из переменной" "$out" "из-переменной"

# SC-AK-718. Переменной нет — значение читается из файла рядом с конфигом раскладки, без
# окружающих пробелов.
printf '  из-файла \n' > "$tree/.claude/rt-kit/browser-device-id"
out="$(said s1)"
report "SC-AK-718 — значение берётся из файла" "$out" "из-файла"

rm -f "$tree/.claude/rt-kit/browser-device-id"

# SC-AK-719. Значения нет нигде — помощник говорит об этом в поток ошибок и всё равно уходит
# нулём: запрета он не предлагает, а гарды по нему пропускают.
out="$(said s1)"
code=$?
report "SC-AK-719 — без значения ничего не напечатано" "$out" ''
report "SC-AK-719 — без значения выход нулевой" "$code" 0
case "$(heard)" in
    *RT_BROWSER_DEVICE_ID*browser-device-id*) report "SC-AK-719 — сказано, чего не хватает" да да ;;
    *) report "SC-AK-719 — сказано, чего не хватает" "$(heard)" да ;;
esac

# SC-AK-720. Второй вызов с тем же признаком молчит: строка на каждый вызов утонула бы в выводе
# и перестала читаться.
said s1 >/dev/null
report "SC-AK-720 — второй раз за заход молчит" "$(heard)" ''

# Признак другой — сказано снова: метка живёт заход, а не жизнь машины.
said s2 >/dev/null
case "$(heard)" in
    *RT_BROWSER_DEVICE_ID*) report "новый заход слышит то же" да да ;;
    *) report "новый заход слышит то же" "$(heard)" да ;;
esac

rm -rf "$tree"
suite_result "профиль браузера"
