import { defineConfig, devices } from '@playwright/test';

import { ADMIN_ORIGIN, ADMIN_PAGE_ORIGIN } from './stand/stand.mjs';

/**
 * Адрес браузера, поднятого в образе. Его называет `tools/shot-browser.mjs` — он же образ и
 * поднимает; цель `e2e` зовёт набор только через него.
 *
 * Растр знаков считает та машина, что рисует, и у двух машин он разный при одном и том же коде.
 * Образ один на любой из них, и эталон, снятый им, годится всюду.
 */
const SHOT_BROWSER: string = process.env['RT_SHOT_BROWSER'] ?? '';

if (!SHOT_BROWSER) {
    throw new Error(
        'Набор идёт только браузером из образа: кадры, снятые браузером машины, не совпадают ни с ' +
            'одной другой машиной. Команда — `pnpm exec nx run message-bus-admin-e2e:e2e`, она ' +
            'поднимает образ сама.'
    );
}

/**
 * Стенд остаётся на машине: он поднимает прод-сборки и базу, и вторая их сборка внутри образа
 * стоила бы дороже переноса. Из образа машина зовётся своим именем — `localhost` там свой.
 *
 * Имя берётся у стенда, а не пишется здесь: тем же именем засев называет адреса страниц площадок
 * виджета, и написанное дважды оно разошлось бы молча — виджет получил бы отказ по списку адресов.
 */
const PAGE_ORIGIN: string = ADMIN_PAGE_ORIGIN;

/**
 * Сквозной набор админки.
 *
 * Стенд поднимается одной командой и целиком: прод-сборки приёмника и админки, база стенда, её
 * схема и засев. Прогонщик ждёт адреса админки — к этой минуте всё остальное уже стоит.
 *
 * Браузер один — chromium: на машине владельца поставлен только он, и прогон в остальных падает
 * состоянием машины, а не дефектом правки. Узкий экран проверяется тем же браузером в размере
 * телефона: карточка вместо строки — обещание раскладки, а не отдельного браузера.
 *
 * Повторов у упавшего теста нет намеренно. Стенд свой, данные засеяны заново, и упавший тест
 * здесь означает расхождение с обещанием, а не занятую машину; повтор прятал бы ровно то, ради
 * чего набор и заведён.
 *
 * Пояс и язык страницы названы явно: время показывается в поясе того, кто смотрит. Язык самого
 * браузера — там же, где браузер запускается: `tools/shot-browser.mjs`. Набор, взявший любое из
 * трёх у машины, проверял бы настройку машины, а не экран.
 */
export default defineConfig({
    testDir: './src',
    fullyParallel: false,
    forbidOnly: Boolean(process.env['CI']),
    retries: 0,
    workers: 1,
    reporter: [['list']],
    timeout: 60_000,
    /**
     * Эталоны экранов лежат одним каталогом при наборе, а не рядом с каждой спекой: их читают
     * списком — «какие экраны закрыты кадром», — а не по одному вместе с кодом теста. Имя
     * прогона в пути обязательно: широкий и узкий кадры одного экрана — два разных эталона.
     *
     * Имени платформы в пути нет намеренно: кадры снимает браузер образа, и платформа у них
     * поэтому одна — его. Прежде здесь стояло, что раннер конвейера и есть машина разработчика;
     * это неправда, и она стоила полдня.
     */
    snapshotPathTemplate: '{testDir}/../__snapshots__/{projectName}/{arg}{ext}',
    expect: {
        timeout: 10_000,
        /**
         * Порог сравнения держится у нуля: `threshold` судит цвет пикселя, `maxDiffPixelRatio` —
         * долю разошедшейся площади. Съеденный отступ занимает сотые доли кадра, и порог
         * пощедрее пропускал бы его молча — ровно то, ради чего кадры и заводятся.
         */
        toHaveScreenshot: { threshold: 0, maxDiffPixelRatio: 0 },
    },
    use: {
        baseURL: PAGE_ORIGIN,
        /*
         * Доводы браузеру — профиль цвета, растр без ускорителя, отрисовка кадра целиком и язык —
         * стоят там, где браузер запускается, в `tools/shot-browser.mjs`: соединение их не
         * передаёт, браузер к этой минуте уже поднят той стороной.
         */
        connectOptions: { wsEndpoint: SHOT_BROWSER },
        trace: 'retain-on-failure',
        screenshot: 'only-on-failure',
        locale: 'ru-RU',
        timezoneId: 'Europe/Minsk',
    },
    projects: [
        {
            name: 'chromium',
            use: { ...devices['Desktop Chrome'], viewport: { width: 1440, height: 900 } },
            testIgnore: ['**/*.narrow.spec.ts'],
        },
        {
            name: 'narrow',
            use: { ...devices['Pixel 7'] },
            testMatch: ['**/*.narrow.spec.ts'],
        },
    ],
    webServer: {
        command: 'node apps/message-bus-admin-e2e/stand/up.mjs',
        url: ADMIN_ORIGIN,
        cwd: '../..',
        // Стенд поднимается на каждом прогоне, и переиспользования нет ни на одной машине.
        // Пока оно было включено вне конвейера, поднятый стенд прошлой ветки прогонщик брал как
        // есть — а вместе с подъёмом не шли ни сборка, ни засев: спеки бежали по данным и
        // сборке той ветки и падали так же, как падают на дефекте правки. Цена отказа —
        // пятнадцать секунд сборки, названные ниже; цена промаха — прогон, которому нельзя
        // верить, и признака у него нет.
        reuseExistingServer: false,
        // Пять минут с запасом: сборки обоих приложений идут пятнадцать секунд даже с пропущенным
        // кэшем, вместе с китом, а схема, засев и подъём двух служб — секунды. Предел поднимали до
        // десяти минут, когда стенд не отвечал вовсе; причина лежала в хранилище, и ожидание её не
        // касалось. Предел, растянутый под неизвестную причину, превращает отказ стенда в
        // десятиминутное молчание — а молчание читается как медленная сборка.
        timeout: 300_000,
        stdout: 'pipe',
        stderr: 'pipe',
    },
});
