import { expect, Locator, Page } from '@playwright/test';

/**
 * Эталонный кадр экрана.
 *
 * Ожидания вставшего кадра здесь нет намеренно, и это не пропуск. `toHaveScreenshot` ждёт его
 * сам, и ждёт ровно тем приёмом, который в обвязках витрин написан руками: глушит движение,
 * прячет каретку, дожидается `document.fonts.ready` и снимает кадр за кадром, пока два подряд
 * не совпадут пиксель в пиксель. Свой такой же цикл рядом был бы вторым ответом на один вопрос
 * — и разошёлся бы с первым молча.
 *
 * Витрины ждут руками потому, что их прогонщик снимков такого цикла не делает вовсе: там кадр
 * снимается один раз и сразу сверяется. Разница в прогонщике, а не в том, что экран приложения
 * устойчивее истории.
 *
 * Что остаётся набору — назвать недетерминированное. Маска закрашивает узел до сравнения, и
 * закрывается ею то, что плывёт от прогона к прогону по существу, а не то, что не успело
 * встать.
 */

/** Что закрывается маской на этом кадре. Пустой список — на кадре плывущего нет. */
export interface IScreenShotOptions {
    readonly mask?: readonly Locator[];
}

/**
 * Снять кадр целой страницы и сверить с эталоном.
 *
 * Кадр берётся целой страницей, а не окном: панель, вылезшая за нижний край, в оконном кадре
 * просто обрезается — и пропажа её половины читается как «ничего не изменилось».
 */
export async function expectScreen(page: Page, name: string, options: IScreenShotOptions = {}): Promise<void> {
    await expect(page).toHaveScreenshot(`${name}.png`, {
        fullPage: true,
        mask: options.mask ? [...options.mask] : undefined,
    });
}
