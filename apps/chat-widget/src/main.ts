/**
 * Точка входа виджета: скрипт объявляет элемент страницы и на этом кончается.
 *
 * Сам он ничего не рисует и никуда не встаёт: где стоять виджету, решает страница потребителя —
 * она ставит тег. Второе объявление того же имени браузер отвергает ошибкой, поэтому имя
 * проверяется до объявления: два скрипта на одной странице — это не отказ страницы, а один
 * лишний скрипт.
 */
import { ChatWidgetElement, WIDGET_TAG } from './lib/chat-widget.element';

if (!customElements.get(WIDGET_TAG)) {
    customElements.define(WIDGET_TAG, ChatWidgetElement);
}
