/**
 * Номер обращения: то, чем человек называет свой отказ, а приёмник находит его в журнале.
 *
 * Заводится на отказ, а не на запрос: контекста запроса у приёмника нет вовсе, а строк об одном
 * обращении ровно одна — та, которую пишет разбор отказов. Дорасти до номера на запрос ему не
 * во что, пока о запросе не пишет никто другой.
 *
 * Ставится он только там, где причина человеку не видна, — в ответах `500` и `503`. У отказа по
 * вводу и правам причина названа самим отказом, и номер к ней ничего не прибавляет, зато уводит
 * читающего в журнал за тем, что уже написано на экране.
 */
import { randomBytes } from 'node:crypto';

/**
 * Длина номера: четыре байта — восемь шестнадцатеричных знаков.
 *
 * Столько человек перепишет с экрана без ошибки, а на отбор в журнале этого хватает: строк с
 * номером у приёмника единицы, и совпадение двух номеров разводится временем строки.
 */
const INCIDENT_BYTES: number = 4;

/** Новый номер обращения. */
export function incidentNumber(): string {
    return randomBytes(INCIDENT_BYTES).toString('hex');
}
