/**
 * Предел веса груза.
 *
 * Объявлен настройкой: без предела запрос произвольного размера кладёт службу на самом малом
 * узле. Читается в одном месте, потому что читателей двое — подъём службы, который ставит предел
 * разбору тела, и разбор отказов, который называет предел дереву. Разойдись они, приёмник
 * отбивал бы по одному числу, а называл бы другое.
 *
 * В сводку старта предел попадает именем и значением: значение здесь и есть состояние
 * возможности, а секретом оно не бывает — приёмник называет его дереву в самом отказе.
 */

/** Предел, когда настройка его не назвала. */
const DEFAULT_CARGO_LIMIT: string = '2mb';

export function cargoLimit(): string {
    return process.env['CARGO_LIMIT'] ?? DEFAULT_CARGO_LIMIT;
}
