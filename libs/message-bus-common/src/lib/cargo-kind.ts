/**
 * Род груза: разбор происшествия или предложение.
 *
 * Место объявления одно на обе стороны. Дерево называет род в пакете правки состояния, админка —
 * в запросе встретившихся версий, и слова там одни и те же: из двух копий набора компилируется
 * одна, а расходятся они молча — запрос ушёл бы словом, которого приёмник не знает, и отбился бы
 * отказом там, где человек выбрал раздел.
 *
 * Третьего рода в наборе нет: состояния и версии выпуска у записи месяца не бывает вовсе.
 */

/** Род записи груза. */
export enum ECargoKind {
    /** Разбор происшествия: ключ — имя файла на дереве. */
    Postmortem = 'postmortem',
    /** Предложение: ключ — признак его текста. */
    Proposal = 'proposal',
}

/** Имя параметра рода груза. Названо здесь, чтобы разбор и текст отказа не расходились строкой. */
const KIND_PARAM: string = 'kind';

/** Набор целиком: по нему судится пришедшее слово и по нему же собирается текст отказа. */
const CARGO_KINDS: readonly ECargoKind[] = Object.values(ECargoKind);

/**
 * Род груза из значения, пришедшего строкой. Пусто — слова вне набора либо не строки.
 *
 * Зовут её обе стороны: приёмник — разбирая строку пакета правки и параметр запроса, админка —
 * называя род своего раздела.
 */
export function cargoKindOf(raw: unknown): ECargoKind | null {
    if (typeof raw !== 'string') {
        return null;
    }

    return CARGO_KINDS.find((kind: ECargoKind): boolean => kind === raw.trim()) ?? null;
}

/**
 * Что в параметре рода груза не разобрано. Пусто — параметр можно читать.
 *
 * Род обязателен и умолчания не имеет: версии двух родов приезжают разными наборами, и
 * подставленный молча род показал бы в отборе одного раздела версии другого.
 */
export function cargoKindFault(query: Record<string, unknown>): string | null {
    return cargoKindOf(query[KIND_PARAM]) === null ? `параметр ${KIND_PARAM} ожидается одним из: ${CARGO_KINDS.join(', ')}` : null;
}
