/**
 * Месяц записи. Ключ пары «дерево — месяц», по которой запись находится или заводится.
 *
 * Считается по часам приёмника во всемирном времени: деревья стоят в разных поясах, и граница
 * месяца, взятая у отправителя, кладёт две записи на один месяц. Местное время узла переезд узла
 * не переживает — приёмник арендован в одном поясе, а читают его в другом.
 *
 * Время приходит доводом, а не берётся из часов внутри: иначе граница месяца не проверяется
 * ничем, кроме ожидания первого числа.
 */

/** Месяц в форме `2026-08`. */
export function monthOf(at: Date): string {
    return at.toISOString().slice(0, 7);
}
