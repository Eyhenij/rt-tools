/**
 * Приглашение так, как его читает админка.
 *
 * Место объявления одно на обе стороны: приём отдаёт эту форму, админка её читает, и своей
 * копии не заводит — из двух копий компилируется одна, а расходятся они молча.
 *
 * Кода приглашения нет ни в строке списка, ни в хранилище: там лежит только его хеш. Один раз
 * код виден в ответе на выдачу — форма этого ответа объявлена здесь же, и второго места, где
 * его показывают, нет.
 */

/**
 * Поля, по которым приглашения упорядочиваются. Первое — порядок по умолчанию.
 *
 * Место объявления одно на обе стороны, как и у самой строки: приём отбивает поле не из набора
 * отказом, а экран не должен просить того, на что получит отказ. Две копии этого набора
 * разошлись бы на первой же новой колонке.
 *
 * Состояния в наборе нет: оно не колонка хранилища, а счёт на момент запроса — просроченность
 * наступает сама собой, между двумя запросами, и упорядочить по ней хранилищу нечем.
 */
export const TREE_INVITE_SORTABLE: readonly string[] = ['issuedAt', 'expiresAt', 'name'];

/** Состояние приглашения: то, чем оно показывается в списке. */
export enum ETreeInviteView {
    /** Приглашением ещё не воспользовались, и срок не вышел. */
    Waiting = 'waiting',
    /** По приглашению выдан токен: дерево заведено. */
    Redeemed = 'redeemed',
    /** Срок вышел, а приглашением так и не воспользовались. */
    Expired = 'expired',
    /** Владелец снял приглашение до того, как им воспользовались. */
    Revoked = 'revoked',
}

/** Строка списка приглашений. Времена приезжают строкой по всемирному времени приёма. */
export interface ITreeInviteView {
    /** Имя будущего дерева: его назвал владелец при выдаче. */
    readonly name: string;
    readonly state: ETreeInviteView;
    readonly issuedAt: string;
    readonly expiresAt: string;
    /** Признак дерева, заведённого этим приглашением; пусто — приглашение не погашено. */
    readonly treeSlug: string | null;
}

/**
 * Ответ на выдачу приглашения — единственное место, где код виден человеку.
 *
 * Отдаётся один раз, тем же запросом, которым приглашение заведено: в хранилище уходит хеш, и
 * повторить показ неоткуда. Ни в список, ни в журнал этот код не попадает.
 */
export interface ITreeInviteIssued {
    /** Имя будущего дерева, как его назвал владелец. */
    readonly name: string;
    /** Сам код. Показывается один раз и больше нигде не хранится. */
    readonly code: string;
    readonly issuedAt: string;
    readonly expiresAt: string;
}
