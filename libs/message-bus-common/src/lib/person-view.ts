/**
 * Человек приёмника так, как его читает админка.
 *
 * Место объявления одно на обе стороны: приём отдаёт эту форму, админка её читает, и своей копии
 * не заводит — из двух копий компилируется одна, а расходятся они молча.
 *
 * Ни пароля, ни его хеша здесь нет и не будет: список говорит, кто дотягивается до груза, а не
 * чем этот человек входит.
 */

/**
 * Поля, по которым люди упорядочиваются. Первое — порядок по умолчанию.
 *
 * Место объявления одно на обе стороны, как и у самой строки: приём отбивает поле не из набора
 * отказом, а экран не должен просить того, на что получит отказ.
 *
 * Первым стоит последний вход: умолчание направления одно на все разделы — свежие сверху, — и по
 * имени оно дало бы список от «я» к «а». Роли в наборе нет: она приезжает вложенной записью, и
 * порядок по ней означал бы порядок по чужой таблице.
 */
export const PERSON_SORTABLE: readonly string[] = ['lastLoginAt', 'name', 'disabledAt'];

/** Строка списка людей. Времена приезжают строкой по всемирному времени приёма. */
export interface IPersonView {
    readonly name: string;
    /** Имя роли, как его видит человек. Пусто — роли нет; словами это называет экран, а не приём. */
    readonly role: string | null;
    /** Пусто — запись действует. Отключённая входа не заводит, а её прежние входы оборваны. */
    readonly disabledAt: string | null;
    /** Время последнего входа. Пусто — этой записью ещё не входили ни разу. */
    readonly lastLoginAt: string | null;
}
