/**
 * Дерево, названное человеку.
 *
 * Признак дерева — хеш адреса репозитория, и по нему человек своё дерево не узнаёт: в отборе и в
 * строке списка стоит имя, а сужается список признаком. Оба поля поэтому едут вместе — имя без
 * признака нечем отобрать, признак без имени нечем показать.
 *
 * Лежит в общей либе, а не в домене деревьев: это шапка строки у всех трёх списков груза, и
 * копия её у каждого разошлась бы с остальными. Домен деревьев при этом остаётся владельцем
 * самих записей — здесь только то, чем дерево названо в ответе.
 */

/** Дерево в отборе и в строке списка. */
export interface ITreeChoice {
    /** Признак: им груз называет отправителя, и им же сужается список. */
    readonly slug: string;
    /** Читаемое имя: его назвал владелец при заведении дерева. */
    readonly name: string;
}
