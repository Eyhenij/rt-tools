/**
 * Что приёмник добавляет к форме груза от себя.
 *
 * Саму форму — поля сводки, предложений и разборов — объявляет отправляющая сторона, и берётся
 * она оттуда напрямую: `@rt-tools/agent-kit/cargo`. Направление именно такое, потому что пакет
 * уходит в реестр: импорт внутренней либы уехал бы в описания его типов и сломал бы установку.
 * Реэкспортировать её отсюда нельзя тоже — потребитель импортирует символ у источника.
 *
 * Здесь остаётся то, что форме груза не принадлежит: как приёмник отвечает.
 */

/**
 * То, что операция приёма делает с ответом: ставит код — `201` у заведённой записи месяца и
 * `200` у обновлённой.
 *
 * Объявлено здесь, а не взято из типов каркаса отдачи: код ответа — часть контракта приёма, по
 * нему дерево видит, первый ли это прогон месяца. Своего типа каркас отдачи не несёт, а лежащие
 * в дереве описывают его прошлую редакцию — операции приёма ломались бы на чужом обновлении.
 *
 * В форме груза его нет: отправляющая сторона ответ читает, а не собирает.
 */
export interface IIntakeResponse {
    status(code: number): unknown;
}
