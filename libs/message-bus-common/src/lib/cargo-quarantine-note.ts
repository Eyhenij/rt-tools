import { ECargoState } from './cargo-state';

/**
 * Решение о причине карантина: годится ли она при названном переходе.
 *
 * Стоит рядом с решением о переходе и отдельно от операции правки по той же причине, что и текст
 * починки: условие внутри операции проверяется только запросом, а здесь судится договорённость
 * домена — «чем запись спорна» отвечает на карантин и ни на что другое. Хранилища решению не
 * нужно: оно смотрит на саму строку и зовётся до похода в базу.
 *
 * Своим файлом, а не веткой в решении о тексте починки: значения два, у каждого своё состояние и
 * своя причина отказа, и общая ветка отвечала бы двумя наборами причин на один вопрос.
 */

/** Почему строка не годится из-за причины карантина. Пусто означает, что с причиной всё в порядке. */
export enum ECargoQuarantineNoteFault {
    /** Запись кладут в карантин, а чем она спорна — не сказано. */
    Missing = 'quarantine-note-missing',
    /** Причина приехала с переходом, который к карантину не относится. */
    Unexpected = 'quarantine-note-unexpected',
}

/**
 * Судить причину карантина при переходе.
 *
 * Причина обязательна ровно при одном переходе и запрещена при остальных. Обязательна потому, что
 * состояние без ответа на «чем спорна» разбирают заново каждый раз — ровно то, от чего карантин и
 * заводится. Запрещена потому, что лежащая у записи вне карантина она читается как причина
 * карантина, которого не было.
 *
 * Пустая строка сюда не доходит: разбор тела приводит строку из пробелов к пустоте, иначе
 * требование обходилось бы одним пробелом.
 */
export function cargoQuarantineNoteFault(state: ECargoState, quarantineNote: string | null): ECargoQuarantineNoteFault | null {
    if (state === ECargoState.Quarantined) {
        return quarantineNote === null ? ECargoQuarantineNoteFault.Missing : null;
    }

    return quarantineNote === null ? null : ECargoQuarantineNoteFault.Unexpected;
}
