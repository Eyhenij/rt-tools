import { ECargoState } from './cargo-state';

/**
 * Решение о тексте починки: годится ли он при названном переходе.
 *
 * Стоит рядом с решением о переходе и отдельно от операции правки по той же причине: условие,
 * написанное внутри операции, проверяется только запросом, а здесь судится договорённость
 * домена — «чем исправлено» отвечает на починку и ни на что другое. Хранилища решению не нужно:
 * оно смотрит на саму строку, поэтому и зовётся до похода в базу.
 */

/** Почему строка не годится из-за текста починки. Пусто означает, что с текстом всё в порядке. */
export enum ECargoFixNoteFault {
    /** Запись переводят в «починено и не выпущено», а чем она починена — не сказано. */
    Missing = 'fix-note-missing',
    /** Текст приехал с переходом, который к починке не относится. */
    Unexpected = 'fix-note-unexpected',
}

/**
 * Судить текст починки при переходе.
 *
 * Текст обязателен ровно при одном переходе и запрещён при остальных. Обязателен потому, что
 * состояние «починено и не выпущено» без него отвечает на «сделано ли» и молчит о «чем» — ради
 * этого ответа работа и заведена. Запрещён потому, что при выпуске или возврате в работу он
 * относился бы неизвестно к чему: читающий не отличил бы починку от выпуска.
 *
 * Пустой текст сюда не доходит: разбор пакета приводит строку из пробелов к пустоте, иначе
 * требование обходилось бы одним пробелом.
 */
export function cargoFixNoteFault(state: ECargoState, fixNote: string | null): ECargoFixNoteFault | null {
    if (state === ECargoState.Fixed) {
        return fixNote === null ? ECargoFixNoteFault.Missing : null;
    }

    return fixNote === null ? null : ECargoFixNoteFault.Unexpected;
}
