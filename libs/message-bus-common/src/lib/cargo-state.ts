/**
 * Состояние записи груза: на каком шаге стоит разбор происшествия или предложение.
 *
 * Место объявления одно на обе стороны: приёмник отдаёт эти слова чтением, админка их читает и
 * своей копии не заводит — из двух копий компилируется одна, а расходятся они молча.
 *
 * Тот же набор объявлен перечислением хранилища, и слова в нём те же: колонка держит набор, а
 * значение вне него хранилище не принимает вовсе. Сходство двух объявлений проверяется спекой —
 * разъехавшись, они дали бы состояние, которого экран не знает, и показали бы его машинной
 * строкой.
 *
 * Готовое и выпущенное разведены не для порядка: между починкой и выпуском стоит редакция
 * пакета, и потребитель получает фикс только после раскладки у себя.
 */

/** Состояние записи груза: то, чем она показывается в списке. */
export enum ECargoState {
    /** Запись приехала, и с ней ещё ничего не делали. */
    New = 'new',
    /** Запись взята в разбор. */
    InWork = 'in_work',
    /** Недочёт починен, но выпуска с починкой ещё не было. */
    Fixed = 'fixed',
    /** Починка уехала выпуском. */
    Released = 'released',
}

/** Набор целиком: по нему и сверяется пришедшее значение. */
const CARGO_STATES: readonly ECargoState[] = Object.values(ECargoState);

/**
 * Состояние из значения, пришедшего строкой.
 *
 * Зовут её обе стороны: приёмник — переводя колонку хранилища, где набор объявлен своим
 * перечислением, админка — разбирая ответ чтения. Значение вне набора читается как «новое», а не
 * роняет список: пустого состояния у записи не бывает, и показать нечитаемое было бы хуже, чем
 * показать её неразобранной.
 */
export function cargoStateOf(raw: string): ECargoState {
    const found: ECargoState | undefined = CARGO_STATES.find((state: ECargoState): boolean => state === raw);

    return found ?? ECargoState.New;
}
