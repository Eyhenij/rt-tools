import { ECargoState } from './cargo-state';

/**
 * Решение о версии выпуска: годится ли она при названном переходе.
 *
 * Стоит рядом с решением о приёме починки и по той же причине: условие, написанное внутри
 * операции, проверяется только запросом, а здесь судится договорённость домена — «в какой
 * версии» отвечает на выпуск и ни на что другое. Хранилища решению не нужно: оно смотрит на
 * саму строку, поэтому и зовётся до похода в базу.
 */

/**
 * Предел длины версии выпуска.
 *
 * Свой, а не общий с весом запроса: текст починки — это текст, и его держит предел веса, а
 * версия — метка. Присланный вместо неё кусок журнала изменений надо отбить до того, как он
 * ляжет в колонку, по которой потом будут искать.
 */
export const CARGO_RELEASE_VERSION_LIMIT: number = 100;

/** Почему строка не годится из-за версии выпуска. Пусто означает, что с версией всё в порядке. */
export enum ECargoReleaseVersionFault {
    /** Запись переводят в «выпущено», а в какой версии искать фикс — не сказано. */
    Missing = 'release-version-missing',
    /** Версия приехала с переходом, который к выпуску не относится. */
    Unexpected = 'release-version-unexpected',
}

/**
 * Судить версию выпуска при переходе.
 *
 * Версия обязательна ровно при одном переходе и запрещена при остальных. Обязательна потому, что
 * состояние «выпущено» без неё отвечает на «уехало ли» и молчит о том, куда именно, — ради этого
 * ответа работа и заведена. Запрещена потому, что при починке или возврате в работу она
 * относилась бы неизвестно к чему: читающий не отличил бы выпуск от починки.
 *
 * Пустая версия сюда не доходит: разбор пакета приводит строку из пробелов к пустоте, иначе
 * требование обходилось бы одним пробелом.
 */
export function cargoReleaseVersionFault(state: ECargoState, releaseVersion: string | null): ECargoReleaseVersionFault | null {
    if (state === ECargoState.Released) {
        return releaseVersion === null ? ECargoReleaseVersionFault.Missing : null;
    }

    return releaseVersion === null ? null : ECargoReleaseVersionFault.Unexpected;
}
