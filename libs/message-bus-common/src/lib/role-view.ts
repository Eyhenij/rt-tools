/**
 * Роль и доступ человека так, как их читает админка.
 *
 * Место объявления одно на обе стороны, как и у строки человека: приём отдаёт эти формы, админка
 * их читает и своей копии не заводит — из двух копий компилируется одна, а расходятся они молча.
 *
 * Права здесь строками закрытого набора: имя права называют обе стороны, и сам набор лежит рядом.
 */
import { IPermissionEdit, TRight } from './rights';

/**
 * Поля, по которым роли упорядочиваются. Поле одно: имя роли и есть то, чем её отличают, а
 * порядок по числу людей или по составу прав ничего не говорит человеку, который ищет роль.
 */
export const ROLE_SORTABLE: readonly string[] = ['name'];

/** Роль: ключ, имя, права и сколько людей её держат. */
export interface IRoleView {
    /** Ключ роли: им на роль ссылаются адрес панели, хранилище и засев. Человеку не показывается. */
    readonly key: string;
    /** Имя, как его видит человек в списке ролей. */
    readonly name: string;
    /** Права роли. Право, которого здесь нет, роль не даёт. */
    readonly rights: readonly TRight[];
    /** Сколько записей держат роль. Роль, которую держат, не удаляется. */
    readonly people: number;
}

/**
 * Доступ человека: его роль, точечные правки поверх неё и то, что из них выходит.
 *
 * Выходящий набор едет вместе с исходными: панель показывает и то, и другое, а сложение на второй
 * стороне разошлось бы с приёмом молча.
 */
export interface IPersonAccessView {
    readonly name: string;
    /** Ключ роли. Пусто — роли нет, и без правок прав нет ни одного. */
    readonly role: string | null;
    /** Точечные правки: по одной на право, которого они касаются. */
    readonly edits: readonly IPermissionEdit[];
    /** Права, которые выходят из роли и правок вместе. */
    readonly rights: readonly TRight[];
}

/** Что панель шлёт приёмнику: роль и правки целиком. Выходящий набор считает приём. */
export interface IPersonAccessInput {
    readonly role: string | null;
    readonly edits: readonly IPermissionEdit[];
}

/** Что панель роли шлёт приёмнику: имя и права целиком. */
export interface IRoleInput {
    readonly name: string;
    readonly rights: readonly TRight[];
}
