import { ECargoState } from './cargo-state';

/**
 * Порядок переходов состояния груза: что дереву разрешено сделать со своей записью.
 *
 * Решение вынесено сюда из операции правки нарочно. Условие внутри операции проверяется только
 * запросом, а порядок переходов — договорённость домена: его надо звать вызовом, чтобы каждый
 * исход был назван спекой и чтобы приём починки и версия выпуска судили переход тем же
 * решением, а не своей копией условия.
 *
 * Прежнее состояние берётся из хранилища, а не из тела запроса: между чтением дерева и его
 * правкой стоит сеть, и присланное прежнее состояние успевает устареть.
 */

/** Шаги вперёд по порядку: каждое состояние ходит на соседнее справа, и только на него. */
const CARGO_STATE_ORDER: readonly ECargoState[] = [ECargoState.New, ECargoState.InWork, ECargoState.Fixed, ECargoState.Released];

/** Чем кончилась строка правки состояния. */
export enum ECargoStateMove {
    /** Переход разрешён: запись переводится. */
    Allowed = 'allowed',
    /** Запись уже стоит в этом состоянии: переходом это не считается и строку не отбивает. */
    Same = 'same',
    /** Переход запрещён порядком: строка отбивается с причиной. */
    Denied = 'denied',
}

/**
 * Решение о переходе: можно ли перевести запись из одного состояния в другое.
 *
 * Разрешены ровно две дороги. Шаг вперёд идёт на соседнее состояние: «готово», пропущенное по
 * дороге к «выпущено», означало бы выпуск того, о чём никто не сказал, что оно починено. Назад
 * ходит один возврат — из «в работе» в «новое»: он означает, что работу отменили, а остальные
 * шаги назад переписывали бы прошлое.
 *
 * Правка в то же состояние отдельным исходом стоит потому, что она не промах: рабочий порядок
 * повторяют, и вторая та же отметка — обычное дело. Ответ считает такие записи своим числом, а
 * в отбитые они не идут.
 */
export function cargoStateMove(from: ECargoState, to: ECargoState): ECargoStateMove {
    if (from === to) {
        return ECargoStateMove.Same;
    }

    if (from === ECargoState.InWork && to === ECargoState.New) {
        return ECargoStateMove.Allowed;
    }

    // Карантин стоит в стороне от порядка шагов: в него запись уходит только из «нового», и
    // возвращается только туда же. Вперёд из него дороги нет — она означала бы починку того, о чём
    // решили, что чинить нечего; а из «в работе» в карантин ходить незачем: для брошенной работы
    // уже есть возврат в «новое».
    if (from === ECargoState.Quarantined) {
        return to === ECargoState.New ? ECargoStateMove.Allowed : ECargoStateMove.Denied;
    }

    if (to === ECargoState.Quarantined) {
        return from === ECargoState.New ? ECargoStateMove.Allowed : ECargoStateMove.Denied;
    }

    const next: ECargoState | undefined = CARGO_STATE_ORDER[CARGO_STATE_ORDER.indexOf(from) + 1];

    return to === next ? ECargoStateMove.Allowed : ECargoStateMove.Denied;
}

/** Шаги, которыми запись закрывают: их ставит тот, кто починил и опубликовал. */
const CARGO_CLOSE_STATES: readonly ECargoState[] = [ECargoState.Fixed, ECargoState.Released];

/**
 * Решение о закрытии: можно ли издателю редакции перевести чужую запись в названное состояние.
 *
 * Порядок здесь свой, и это не послабление, а другое право. Дерево ведёт свою запись по шагам и
 * отвечает за каждый; издатель видит её один раз — когда правка вошла в редакцию, — и шага «в
 * работе» у него не было вовсе: работу брал не он. Поэтому «новое» закрывается сразу починенным,
 * а «в работе» и «новое» издателю не ставятся ни из какого состояния: они говорят о работе,
 * которую ведёт дерево, и поставить их значило бы распорядиться чужой очередью.
 *
 * Назад закрытие не ходит: выпущенное не возвращается в починенное ни у кого — иначе издатель
 * отменял бы то, о чём уже сказал потребителю.
 */
export function cargoCloseMove(from: ECargoState, to: ECargoState): ECargoStateMove {
    if (!CARGO_CLOSE_STATES.includes(to)) {
        return ECargoStateMove.Denied;
    }

    if (from === to) {
        return ECargoStateMove.Same;
    }

    // Запись в карантине издателю не закрывается: карантина нет в порядке шагов вовсе, и место
    // прежнего состояния вышло бы отрицательным — то есть меньше любого, и закрытие прошло бы.
    // Спорную запись достаёт из карантина дерево, а не тот, кто выпустил редакцию.
    if (from === ECargoState.Quarantined) {
        return ECargoStateMove.Denied;
    }

    return CARGO_STATE_ORDER.indexOf(to) > CARGO_STATE_ORDER.indexOf(from) ? ECargoStateMove.Allowed : ECargoStateMove.Denied;
}

/** Строка правки: чью запись и в какое состояние её переводят. */
export interface ICargoStateAsk {
    /** Ключ записи: имя файла у разбора происшествия, признак текста у предложения. */
    readonly key: string;
    /** Состояние, в которое дерево просит перевести запись. */
    readonly state: ECargoState;
    /**
     * Чем недочёт исправлен. Приезжает только с переходом в «починено и не выпущено» — при
     * остальных здесь пусто, и лежащий у записи текст правка не трогает.
     */
    readonly fixNote: string | null;
    /**
     * В какой версии искать фикс. Приезжает только с переходом в «выпущено» — при остальных
     * здесь пусто, и лежащая у записи версия правку не трогает.
     */
    readonly releaseVersion: string | null;
    /**
     * Чем запись спорна. Приезжает только с переходом в карантин — при остальных здесь пусто, и
     * лежащая у записи причина правку не трогает.
     */
    readonly quarantineNote: string | null;
}

/**
 * Ложится ли строка в хранилище.
 *
 * Разрешённый переход ложится всегда. Правка в то же состояние переходом не считается — и всё
 * же ложится, когда несёт приложенное значение: второй приезд затирает прежнее, а без этого
 * исправить в нём опечатку было бы нечем — запись уже стоит в нужном состоянии, и второго
 * перехода туда не бывает. Отбитая строка не ложится никогда: запись, у которой лёг текст или
 * версия без перехода, читалась бы починенной либо выпущенной.
 *
 * Стоит рядом с решением о переходе, а не при одном из приложенных значений: их два, у каждого
 * своё решение о годности, а вопрос «пишем ли строку» на оба один.
 */
export function cargoStateWrites(
    move: ECargoStateMove | null,
    fixNote: string | null,
    releaseVersion: string | null,
    quarantineNote: string | null = null
): boolean {
    const attached: boolean = fixNote !== null || releaseVersion !== null || quarantineNote !== null;

    return move === ECargoStateMove.Allowed || (move === ECargoStateMove.Same && attached);
}

/** Что ложится в запись: состояние и те приложенные значения, которые строка принесла. */
export interface ICargoStateData {
    readonly state: ECargoState;
    readonly fixNote?: string;
    readonly releaseVersion?: string;
    readonly quarantineNote?: string;
}

/**
 * Правка одной записи, собранная из строки.
 *
 * Пустое приложенное значение в правку не идёт вовсе, а не ложится пустотой: строка приезжает и
 * без него, и лежащее у записи оно не трогает — текст починки переживает выпуск, а версия
 * выпуска переживает повторную отметку.
 *
 * Собирается это здесь, а не в каждом домене своим условием: таблицы у них разные, а правило,
 * по которому значение попадает в запись, одно, и разойтись двум копиям нечем помешать.
 */
export function cargoStateData(ask: ICargoStateAsk): ICargoStateData {
    return {
        state: ask.state,
        ...(ask.fixNote === null ? {} : { fixNote: ask.fixNote }),
        ...(ask.releaseVersion === null ? {} : { releaseVersion: ask.releaseVersion }),
        ...(ask.quarantineNote === null ? {} : { quarantineNote: ask.quarantineNote }),
    };
}

/** Что ложится в закрываемую запись: то же, что у правки деревом, и признак закрывшего. */
export interface ICargoCloseData extends ICargoStateData {
    /** Закрыл издатель. Ложится при каждом закрытии, а не только при первом: снимать признак нечем. */
    readonly closedByPublisher: true;
}

/**
 * Правка одной записи при закрытии.
 *
 * Собирается здесь, а не в каждом домене своим условием: признак закрывшего один на оба рода
 * записей, и вторая его копия разошлась бы с первой молча — увидеть расхождение можно было бы
 * только на записи, которую уже закрыли.
 */
export function cargoCloseData(ask: ICargoStateAsk): ICargoCloseData {
    return { ...cargoStateData(ask), closedByPublisher: true };
}

/**
 * Чем кончилась одна строка правки.
 *
 * Пустой переход означает, что записи с таким ключом у дерева нет. Четвёртым значением набора он
 * не заводится нарочно: переход судится между двумя состояниями, а у ненайденной записи второго
 * состояния нет вовсе — и набор, куда его дописали, пришлось бы разбирать в каждом месте, где
 * решают о переходе.
 */
export interface ICargoStateOutcome {
    /** Ключ записи, каким его прислало дерево. */
    readonly key: string;
    /** Решение о переходе либо пусто, когда записи у дерева нет. */
    readonly move: ECargoStateMove | null;
}

/** Чем кончилась одна строка закрытия: то же решение и признак дерева, чью запись закрывали. */
export interface ICargoCloseOutcome extends ICargoStateOutcome {
    /**
     * Признак дерева записи либо пусто, когда записи с таким признаком нет вовсе.
     *
     * Нужен журналу: закрытие правит чужие записи, и строка о нём без дерева не говорит, кому
     * это видно, — а видно оно как раз соседу, который о закрытии не просил.
     */
    readonly tree: string | null;
}
