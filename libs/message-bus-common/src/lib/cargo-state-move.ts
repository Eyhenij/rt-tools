import { ECargoState } from './cargo-state';

/**
 * Порядок переходов состояния груза: что дереву разрешено сделать со своей записью.
 *
 * Решение вынесено сюда из операции правки нарочно. Условие внутри операции проверяется только
 * запросом, а порядок переходов — договорённость домена: его надо звать вызовом, чтобы каждый
 * исход был назван спекой и чтобы приём починки и версия выпуска судили переход тем же
 * решением, а не своей копией условия.
 *
 * Прежнее состояние берётся из хранилища, а не из тела запроса: между чтением дерева и его
 * правкой стоит сеть, и присланное прежнее состояние успевает устареть.
 */

/** Шаги вперёд по порядку: каждое состояние ходит на соседнее справа, и только на него. */
const CARGO_STATE_ORDER: readonly ECargoState[] = [ECargoState.New, ECargoState.InWork, ECargoState.Fixed, ECargoState.Released];

/** Чем кончилась строка правки состояния. */
export enum ECargoStateMove {
    /** Переход разрешён: запись переводится. */
    Allowed = 'allowed',
    /** Запись уже стоит в этом состоянии: переходом это не считается и строку не отбивает. */
    Same = 'same',
    /** Переход запрещён порядком: строка отбивается с причиной. */
    Denied = 'denied',
}

/**
 * Решение о переходе: можно ли перевести запись из одного состояния в другое.
 *
 * Разрешены ровно две дороги. Шаг вперёд идёт на соседнее состояние: «готово», пропущенное по
 * дороге к «выпущено», означало бы выпуск того, о чём никто не сказал, что оно починено. Назад
 * ходит один возврат — из «в работе» в «новое»: он означает, что работу отменили, а остальные
 * шаги назад переписывали бы прошлое.
 *
 * Правка в то же состояние отдельным исходом стоит потому, что она не промах: рабочий порядок
 * повторяют, и вторая та же отметка — обычное дело. Ответ считает такие записи своим числом, а
 * в отбитые они не идут.
 */
export function cargoStateMove(from: ECargoState, to: ECargoState): ECargoStateMove {
    if (from === to) {
        return ECargoStateMove.Same;
    }

    if (from === ECargoState.InWork && to === ECargoState.New) {
        return ECargoStateMove.Allowed;
    }

    const next: ECargoState | undefined = CARGO_STATE_ORDER[CARGO_STATE_ORDER.indexOf(from) + 1];

    return to === next ? ECargoStateMove.Allowed : ECargoStateMove.Denied;
}

/** Строка правки: чью запись и в какое состояние её переводят. */
export interface ICargoStateAsk {
    /** Ключ записи: имя файла у разбора происшествия, признак текста у предложения. */
    readonly key: string;
    /** Состояние, в которое дерево просит перевести запись. */
    readonly state: ECargoState;
}

/**
 * Чем кончилась одна строка правки.
 *
 * Пустой переход означает, что записи с таким ключом у дерева нет. Четвёртым значением набора он
 * не заводится нарочно: переход судится между двумя состояниями, а у ненайденной записи второго
 * состояния нет вовсе — и набор, куда его дописали, пришлось бы разбирать в каждом месте, где
 * решают о переходе.
 */
export interface ICargoStateOutcome {
    /** Ключ записи, каким его прислало дерево. */
    readonly key: string;
    /** Решение о переходе либо пусто, когда записи у дерева нет. */
    readonly move: ECargoStateMove | null;
}
