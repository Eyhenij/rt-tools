/**
 * Запись месяца, каким её читает админка.
 *
 * Две стороны и два уровня — тем же устройством, что у двух других разделов. Сторона контракта
 * несёт время строкой: через передачу его иначе не пронести. Сторона экрана — временем: пояс
 * смотрящего считается от него.
 *
 * Уровня два: список несёт счёт заходов и время прогона, а сводки целиком не несёт — она лежит
 * телом произвольной формы, и страница, тянущая тела всех своих строк, росла бы весом без
 * предела.
 *
 * Сводка на стороне экрана — уже текст, а не тело: показывается она текстом, и разбирать тело в
 * разметку значило бы исполнять в браузере вошедшего то, что прислало дерево.
 *
 * Поле контракта `schema` до экрана не доезжает: оно называет форму груза, которой дерево
 * прислало запись, и человеку в разделе не говорит ничего. Стороне контракта оно при этом
 * объявлено — она повторяет то, что приезжает.
 */
import { ITreeChoice } from '@rt/message-bus-common';

export namespace IMonthRecord {
    /** Строка списка: то, что видно в таблице. */
    export namespace Short {
        /** Сторона контракта. */
        export interface Api {
            readonly id: string;
            readonly tree: ITreeChoice;
            readonly month: string;
            readonly sessions: number | null;
            readonly schema: string;
            readonly ranAt: string;
        }

        /** Сторона экрана. */
        export interface State {
            readonly id: string;
            readonly tree: ITreeChoice;
            /** Календарный месяц вида `2026-08`: запись одна на пару «дерево — месяц». */
            readonly month: string;
            /** Заходов за месяц. Ноль — сводки в этом месяце ещё не было: запись завёл другой род груза. */
            readonly sessions: number;
            /** Время последнего прогона отправки, приехавшего в эту запись. */
            readonly ranAt: Date;
        }
    }

    /** Запись целиком: то, что показывает панель подробностей. */
    export interface Api extends Short.Api {
        readonly summary: unknown;
    }

    export interface State extends Short.State {
        /** Сводка последнего прогона, приведённая к тексту. Пусто — сводки в этом месяце ещё не было. */
        readonly summary: string;
    }
}
