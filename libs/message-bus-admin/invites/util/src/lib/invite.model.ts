/**
 * Приглашение дерева, каким его читает админка.
 *
 * Сторона контракта своей копии здесь не заводит: форма строки объявлена один раз, на обе
 * стороны, и берётся отсюда — `ITreeInviteView`. Своя копия расходилась бы с приёмом молча, а
 * компилируется из двух одна.
 *
 * Уровень один: панели подробностей у приглашения нет — показывать в ней нечего. Всё, что о нём
 * известно, помещается в строку списка, а самого кода нет ни здесь, ни в хранилище.
 *
 * Сторона экрана несёт время временем, а не строкой: пояс смотрящего считается от него. И несёт
 * готовое поле `canRevoke` — доступность действия лежит полем строки, а не вызовом метода из
 * шаблона: метод пересчитывался бы на каждой проверке.
 */
import { ETreeInviteView, ITreeInviteView } from '@rt/message-bus-common';

export namespace IInvite {
    /** Строка списка: то, что видно в таблице. */
    export namespace Short {
        /** Сторона контракта. */
        export type Api = ITreeInviteView;

        /** Сторона экрана. */
        export interface State {
            /** Имя будущего дерева: его назвал владелец при выдаче. Оно же — признак строки. */
            readonly name: string;
            readonly state: ETreeInviteView;
            /**
             * Состояние по-русски: показывается оно этой строкой.
             *
             * Лежит полем, а не считается в шаблоне: шаблон методов не зовёт, а пайп ради
             * одного перевода потребовал бы разделу своего слоя вида.
             */
            readonly stateLabel: string;
            readonly issuedAt: Date;
            readonly expiresAt: Date;
            /** Признак дерева, заведённого этим приглашением. Пусто — приглашение не погашено. */
            readonly treeSlug: string;
            /** Можно ли отозвать. Отзывается одно ждущее: остальные состояния уже необратимы. */
            readonly canRevoke: boolean;
            /**
             * Вопрос перед отзывом, уже с именем дерева.
             *
             * Лежит полем по той же причине, что и подпись состояния: шаблон методов не зовёт, а
             * значение приходит из строки таблицы.
             */
            readonly revokeQuestion: string;
        }
    }
}
