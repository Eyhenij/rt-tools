import { Type } from '@angular/core';
import { RtTableSettingsAsideComponent } from '@rt-tools/ui-kit-v2';

/**
 * Панель настройки столбцов, какой её грузит маршрут админки.
 *
 * Рисует её кит, и своего кода у админки здесь нет — есть место, откуда её берут. Место важнее
 * имени: маршрут панели объявлен у корня приложения, а корень грузится первым, и динамический
 * импорт кита прямо оттуда утаскивает весь кит в первую сборку — 347 килобайт превращались в
 * мегабайт, и сборка отбивалась пределом веса. Отсюда панель приезжает тем же отложенным куском,
 * что и оболочка админки, которая и без того стоит на ките.
 *
 * Обращением сделано, а не строкой обратного вывоза: вывезенный символ читается как свой, а он
 * китовый — и проверка раскладки говорит об этом прямо.
 */
export function adminColumnsAside(): Type<unknown> {
    return RtTableSettingsAsideComponent;
}
