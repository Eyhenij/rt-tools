/**
 * Хост списочной страницы: то, что она спрашивает у своего раздела.
 *
 * Страница рисует заголовок, тулбар, место под таблицу и переключатель страниц, но ни читать
 * список, ни менять адрес не умеет вовсе — это дело раздела. Прежде она спрашивала его входами
 * и событиями, по паре на действие: счёт их рос с каждым новым действием, а забытое подключение
 * было видно только на собранном экране.
 *
 * Отсюда токен. Раздел объявляет себя хостом одной строкой, страница получает его внедрением, и
 * подключение перестаёт быть делом того, кто ставит страницу в разметку.
 *
 * Токен живёт в слое утилит общего ядра затем, чтобы его видели обе стороны: вид страницы не
 * видит либы механики раздела и никогда не увидит — механика зовёт вид, а не наоборот.
 */
import { forwardRef, InjectionToken, Provider, Signal, Type } from '@angular/core';
import { IPageModel } from '@rt-tools/utils';

import { IReadFault } from './read-fault';

/**
 * Что страница спрашивает у раздела.
 *
 * Сигналы отвечают на вопрос «в каком состоянии чтение», методы просят раздел что-то сделать.
 * Состояние страница не считает сама: две стороны, считающие одно и то же порознь, расходятся
 * на первом же отказе.
 */
export interface IAdminListHost {
    /** Идёт ли чтение сейчас. На месте строк в это время видно, что список читается. */
    readonly loading: Signal<boolean>;

    /** Чем кончилось чтение, если не грузом. Пусто — отказа нет. */
    readonly fault: Signal<IReadFault | null>;

    /** Страница, её размер и общее число записей — всё, что нужно переключателю страниц. */
    readonly pageModel: Signal<IPageModel>;

    /** Повторить чтение — то самое «одним действием», которого просит отказ. */
    retry(): void;

    /** Уйти на страницу списка. Отбор и порядок при этом остаются теми же. */
    goToPage(page: number): void;

    /** Сменить размер страницы. Считать с той же страницы нельзя: при большем размере её может не быть. */
    changeSize(size: number): void;

    /** Открыть настройку столбцов: панель везёт кит, а маршрут знает раздел. */
    openColumns(): void;
}

/** Раздел, который показывает списочную страницу. Отвечает на всё, что она спрашивает. */
export const ADMIN_LIST_HOST: InjectionToken<IAdminListHost> = new InjectionToken<IAdminListHost>('ADMIN_LIST_HOST');

/**
 * Раздел объявляет себя хостом своей списочной страницы.
 *
 * Класс передаётся вызовом, а не значением: провайдеры разбираются вместе с декоратором, когда
 * имя класса ещё не связано, и переданное значением упало бы обращением к необъявленному.
 *
 * Отвечает на спрошенное общая основа списочного экрана — здесь раздел только указывает на
 * себя: своего ответа он не пишет ни одного.
 */
export function provideAdminListHost(screen: () => Type<IAdminListHost>): Provider {
    return { provide: ADMIN_LIST_HOST, useExisting: forwardRef(screen) };
}
