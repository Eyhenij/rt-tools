/**
 * Адреса экранов входа.
 *
 * Лежат в утилитах, а не рядом с маршрутами: на вход уводят гвард, выход из оболочки и экран
 * первой записи, на первую запись — экран входа, и все они читают одно слово из одного места.
 */

/** Адрес экрана входа. Один на всё приложение: сюда уводит и гвард, и выход. */
export const SIGN_IN_PATH: string = 'sign-in';

/** Адрес экрана первой записи. Открыт, пока в приёмнике нет ни одной записи, и закрыт навсегда с первой. */
export const SETUP_PATH: string = 'setup';

/**
 * Куда человек шёл, когда его отправили на вход. Читается экраном входа после успеха, поэтому
 * имя параметра названо здесь, а не повторено строкой в обоих местах.
 */
export const RETURN_TO_PARAM: string = 'returnTo';
