/**
 * Чем кончилась попытка входа, если не входом.
 *
 * Родов ровно три, и они отвечают на разные вопросы человека. `Pair` — «я ошибся»: приёмник не
 * говорит, что именно не сошлось, и экран этого тоже не выдумывает. `Form` — «я не заполнил»:
 * отказ по форме приходит раньше пары и подбором не бывает. `Service` — «дело не во мне».
 */
export enum ESignInFault {
    Pair = 'pair',
    Form = 'form',
    Service = 'service',
}

/**
 * Род отказа по коду ответа. Чистая функция: решение о том, что человек увидит, принимается
 * здесь и проверяется без поднятого экрана.
 *
 * `401` — пара не принята. `400` — тело без имени или без пароля. Всё остальное, включая обрыв
 * связи, — отказ службы: человеку про него сказать нечего, кроме того, что он не его вина.
 */
export function signInFault(status: number): ESignInFault {
    if (status === 401) {
        return ESignInFault.Pair;
    }

    if (status === 400) {
        return ESignInFault.Form;
    }

    return ESignInFault.Service;
}
