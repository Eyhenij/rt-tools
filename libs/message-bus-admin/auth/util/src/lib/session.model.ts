/**
 * Кто вошёл. Имя и права — всё, что приёмник о вошедшем отдаёт: ни значения входа, ни его срока
 * в ответе нет и быть не может, а саму куку браузер скриптам не показывает.
 *
 * Права приезжают тем же ответом, а не складываются здесь заново: роль и точечные правки поверх
 * неё складывает приёмник, и второе сложение на этой стороне разошлось бы с первым молча.
 */
export interface IAdminSession {
    readonly name: string;
    readonly rights: readonly string[];
}

/** Пара, которой человек представляется. Живёт до отправки и нигде не сохраняется. */
export interface ISignInPair {
    readonly name: string;
    readonly password: string;
}

/** Ждёт ли узел первой записи: пока в хранилище нет ни одной, экран входа уступает место заведению. */
export interface ISetupState {
    readonly open: boolean;
}
