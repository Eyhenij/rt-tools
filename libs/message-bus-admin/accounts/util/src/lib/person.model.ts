/**
 * Человек приёмника, каким его читает админка.
 *
 * Сторона контракта своей копии здесь не заводит: форма строки объявлена один раз, на обе
 * стороны, и берётся отсюда — `IPersonView`. Своя копия расходилась бы с приёмом молча, а
 * компилируется из двух одна.
 *
 * Уровень один: строка списка. Панели подробностей у человека нет — всё, что о нём известно,
 * помещается в строку; заведение и новый пароль живут своими панелями, отключение — меню строки.
 *
 * Сторона экрана несёт время временем, а не строкой: пояс смотрящего считается от него. Состояние
 * и пустой вход лежат ключами словаря, а не готовыми словами: слово по ключу берёт экран на каждой
 * отрисовке, и выбор языка меняет его без перезагрузки страницы.
 */
import { TAdminLabelKey } from '@rt/message-bus-admin/common/core/util';
import { IPersonView } from '@rt/message-bus-common';

export namespace IPerson {
    /** Строка списка: то, что видно в таблице. */
    export namespace Short {
        /** Сторона контракта. */
        export type Api = IPersonView;

        /** Сторона экрана. */
        export interface State {
            /** Имя записи: им человек входит, и оно же — признак строки. */
            readonly name: string;
            /**
             * Имя роли. Пусто — роли у записи нет: до раздачи прав так стоит всякая запись, и
             * слово об этом на её месте показывает экран.
             */
            readonly role: string | null;
            /** Действует ли запись. Отключённая входа не заводит, а её прежние входы оборваны. */
            readonly isLive: boolean;
            /** Ключ словаря с состоянием: слово по нему берёт экран на каждой отрисовке. */
            readonly stateKey: TAdminLabelKey;
            /**
             * Время последнего входа. Пусто — этой записью ещё не входили ни разу.
             *
             * Пустота здесь законна и отличима от начала времён: запись без входов и запись,
             * вошедшая в первую секунду эпохи, — разные состояния, и нулём их не развести.
             */
            readonly lastLoginAt: Date | null;
            /**
             * Ключ слова вместо времени, когда входов не было: пустая ячейка читалась бы
             * недочитанной. Входы были — пусто, и в ячейке стоит само время.
             */
            readonly lastLoginKey: TAdminLabelKey | null;
        }
    }
}
