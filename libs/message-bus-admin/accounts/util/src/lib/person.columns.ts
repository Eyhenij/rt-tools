/**
 * Чем раздел людей отличается от остальных: столбцы, адрес операций, адреса панелей и ключ
 * настройки столбцов.
 *
 * Лежит отдельно от экрана: тот же набор читают и таблица, и панель настройки столбцов, и
 * описание — объявленный в шаблоне, он был бы известен только шаблону.
 */
import { IAdminColumn } from '@rt/message-bus-admin/common/core/util';

/** Адрес операций над людьми: чтение списка, заведение, новый пароль и отключение. */
export const PEOPLE_PATH: string = '/api/accounts';

/**
 * Сегмент адреса панели заведения.
 *
 * Панель живёт тем же аутлетом, что и панели подробностей соседних разделов, и на месте
 * признака записи у неё стоит это слово: записи, которую панель открывает, ещё нет.
 */
export const PERSON_CREATE_ROUTE: string = 'new';

/**
 * Последний сегмент адреса панели нового пароля: `people/<имя>/password`.
 *
 * Перед ним стоит имя записи — им панель узнаёт, кому пароль. Своего слова у панели поэтому
 * два: без второго адрес имени был бы адресом подробностей, которых у человека нет.
 */
export const PERSON_PASSWORD_ROUTE: string = 'password';

/**
 * Ключ, под которым хранится выбор столбцов.
 *
 * Свой у каждого раздела: столбцы у них разные, и общий ключ переносил бы скрытое в одном
 * разделе на остальные.
 */
export const PEOPLE_TABLE_ID: string = 'admin-people';

/**
 * Столбцы таблицы. Подписи идут из словаря, а порядок — тот, в котором они здесь стоят.
 *
 * Закреплено имя: человек зовётся им, и без него список перестаёт называть свои строки.
 * Роль порядка не принимает: у приёмника она вложенной записью, и порядок по ней означал бы
 * порядок по чужой таблице.
 */
export const PEOPLE_COLUMNS: readonly IAdminColumn[] = Object.freeze([
    { key: 'name', label: 'columnPersonName', sortable: true, locked: true },
    { key: 'role', label: 'columnPersonRole' },
    { key: 'state', label: 'columnPersonState', sortable: true },
    { key: 'lastLoginAt', label: 'columnLastLoginAt', sortable: true },
]);
