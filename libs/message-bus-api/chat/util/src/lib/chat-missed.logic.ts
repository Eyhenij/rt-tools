/**
 * Минута, с которой экран добирает пропущенное.
 *
 * Пропущенное считается по времени последней реплики, которая у экрана есть, а не по числу
 * событий: счёт пришлось бы вести обеим сторонам, и потерявший его экран не смог бы сказать, где
 * он остановился.
 */

/**
 * Минута из запроса. Пусто — её не прислали или прислали не минутой, и тогда добор не сужается.
 *
 * Отказа здесь нет: экран после обрыва спрашивает тем, что у него есть, и неразобранное значение
 * отдаёт ему разговор целиком, а не ошибку на месте восстановления.
 */
export function missedSince(value: unknown): Date | null {
    if (typeof value !== 'string' || !value.trim()) {
        return null;
    }

    const at: Date = new Date(value.trim());

    return Number.isNaN(at.getTime()) ? null : at;
}
