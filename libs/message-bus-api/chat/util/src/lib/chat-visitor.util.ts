/**
 * Признак посетителя: чем виджет представляется сервису между обращениями.
 *
 * Выдаёт его сервис, а не страница: опознаватель, придуманный страницей, дал бы читать чужую
 * переписку по догадке. Хранится он как выдан — открывает одну переписку одного сайта и ничего
 * кроме неё, так что хеш здесь стоил бы чтения на каждой реплике и не закрывал бы ничего.
 */
import { randomBytes } from 'node:crypto';

/** Сколько случайных байтов в признаке: столько же, сколько в токене дерева. */
const VISITOR_BYTES: number = 32;

/** Новый признак посетителя. */
export function issueVisitorToken(): string {
    return randomBytes(VISITOR_BYTES).toString('hex');
}
