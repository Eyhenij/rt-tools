/**
 * Пределы приёма реплик посетителя: длина текста и частота обращений.
 *
 * Оба числа лежат здесь одним местом: виджет узнаёт их из ответа об отказе, а не угадывает, и
 * вторая копия числа разошлась бы с первой молча — отказ называл бы один предел, а решение
 * держало другой.
 */

/** Сколько знаков принимается в одной реплике. Длиннее — отказ, и предел назван в ответе. */
export const CHAT_TEXT_LIMIT: number = 4000;

/** Сколько реплик с одного посетителя принимается за окно. */
export const CHAT_RATE_LIMIT: number = 20;

/**
 * Сколько попыток делается по одному вызову наружу.
 *
 * Предел обязателен: повтор без него держит адрес лежащего приложения вечно. Три — столько
 * переживает перезапуск принимающей стороны, и столько же стоит одна минута ожидания.
 */
export const CHAT_HOOK_ATTEMPTS: number = 3;

/** Сколько ждать между попытками вызова. */
export const CHAT_HOOK_RETRY_MS: number = 20_000;

/**
 * Сколько ждать ответа приложения площадки на один вызов.
 *
 * Без названного предела молчащее — не упавшее — приложение держит соединение столько, сколько
 * позволит среда, а это минуты: отказа нет, записывать нечего, и со стороны такое молчание от
 * здоровой работы не отличается. Обход переписок идёт по одной, и одна лежащая площадка задержала
 * бы будильник всех остальных.
 *
 * Десять секунд: столько стоит ответ приложения, которое принимает вызов и пишет его к себе.
 */
export const CHAT_HOOK_TIMEOUT_MS: number = 10_000;

/**
 * Как часто сервис смотрит, не осталась ли переписка без ответа.
 *
 * Минута: условленное время площадок называется минутами, и проверка реже назвала бы опоздание
 * позже, чем площадка его считает.
 */
export const CHAT_WAKE_SWEEP_MS: number = 60_000;

/** Сколько переписок смотрится за один обход. Остальные достаются следующему. */
export const CHAT_WAKE_BATCH: number = 100;

/**
 * Длина окна предела частоты в миллисекундах.
 *
 * Минута: столько живёт всплеск от открытой страницы, и столько же держит окно у обращения
 * дерева за токеном — второе число для того же рода защиты читалось бы как разница по существу.
 */
export const CHAT_RATE_WINDOW_MS: number = 60_000;
