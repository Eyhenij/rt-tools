/**
 * Вызов наружу: готова ли площадка его принять и чем он подписан.
 *
 * Дорога наружу у сервиса одна — адрес приложения площадки. Почты и мессенджера у него нет, и
 * чем поднять человека, решает то приложение: у него средства связи с оператором уже есть.
 *
 * Подпись обязательна: адрес приложения открыт всякому, кто видел обмен, и неподписанный вызов
 * от вызова постороннего ничем не отличается.
 */
import { createHmac } from 'node:crypto';

/** Чем площадка зовёт приложение: адрес и тайна подписи. */
export interface IChatHookSite {
    readonly hookUrl: string;
    readonly hookSecret: string;
}

/** Имя заголовка, которым подпись едет в вызове. */
export const CHAT_HOOK_SIGNATURE_HEADER: string = 'x-rt-chat-signature';

/**
 * Готова ли площадка получать вызовы.
 *
 * Пустой адрес — законное состояние: приложение вызовов не хочет. Адрес без тайны — площадка,
 * настроенная наполовину, и вызовы по ней не уходят: подписать их нечем, а неподписанный вызов
 * принимающая сторона обязана отвергнуть.
 */
export function chatHookReady(site: IChatHookSite): boolean {
    return site.hookUrl.trim() !== '' && site.hookSecret.trim() !== '';
}

/**
 * Подпись вызова тайной площадки.
 *
 * Считается по телу вызова целиком: подпись по части тела оставила бы остальное свободным для
 * подмены. Шестнадцатеричная строка — её сверяет принимающая сторона, у которой та же тайна.
 */
export function chatHookSignature(secret: string, body: string): string {
    return createHmac('sha256', secret).update(body).digest('hex');
}
