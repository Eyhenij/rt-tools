/**
 * Ответы операций чата посетителю.
 *
 * Лежат в слое, который домен отдаёт наружу: виджет и панель оператора читают те же поля, и
 * вторая копия их имён разошлась бы с первой молча.
 */

/** Ответ на заведение переписки: чем посетителю называть себя дальше и куда писать. */
export interface IChatConversationStarted {
    /** Признак переписки: его виджет шлёт с каждой репликой. */
    readonly conversationId: string;
    /**
     * Признак посетителя. Выдаётся один раз — при первом обращении; при втором обращении с уже
     * выданным признаком возвращается он же, чтобы виджет мог обойтись одним полем в памяти.
     */
    readonly visitorToken: string;
}

/** Ответ на принятую реплику. */
export interface IChatMessageTaken {
    /** Признак сообщения: по нему виджет отличает принятое от отправленного. */
    readonly messageId: string;
    /** Минута приёма сервисом: она же задаёт порядок сообщений в переписке. */
    readonly takenAt: string;
}
