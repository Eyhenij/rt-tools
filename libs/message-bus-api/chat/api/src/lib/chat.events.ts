/**
 * События потока: что приходит на открытый экран, когда в переписке появилась реплика.
 *
 * Лежат рядом с ответами операций: виджет и панель читают одни и те же поля, и вторая копия их
 * имён разошлась бы с первой молча.
 */

/** Реплика целиком: экран показывает её, не спрашивая сообщение вторым обращением. */
export interface IChatMessageEvent {
    /** Переписка, в которой появилась реплика. */
    readonly conversationId: string;
    /** Признак сообщения: по нему экран отличает пришедшее от уже показанного. */
    readonly messageId: string;
    /** Сторона разговора: посетитель или оператор. */
    readonly side: string;
    /** Текст реплики целиком. */
    readonly text: string;
    /** Минута приёма сервисом: она же задаёт порядок сообщений в переписке. */
    readonly takenAt: string;
}
