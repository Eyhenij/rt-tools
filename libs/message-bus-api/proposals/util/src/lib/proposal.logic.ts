/**
 * Форма предложения по слою правил.
 *
 * Ресурс обязателен наравне с текстом: ради счёта «сколько деревьев правят это место» линия
 * работ и заведена, а без ресурса он не берётся ниоткуда.
 */
import { createHash } from 'node:crypto';

/**
 * Признак предложения: хеш его текста.
 *
 * Им предложение узнаётся уже приехавшим — в любом месяце, а не в одном. Хеш, а не сам текст:
 * тексты идут в килобайтах, а уникальность по такому полю упирается в предел размера строки
 * индекса, и вставка отказала бы хранилищем на первом длинном предложении.
 */
export function proposalDigest(text: string): string {
    return createHash('sha256').update(text, 'utf8').digest('hex');
}

/** Обязательные поля запроса: голова груза и список записей. */
export const PROPOSALS_FIELDS: readonly string[] = ['schema', 'tree', 'items'];

/** Обязательные поля одной записи. */
export const PROPOSAL_ITEM_FIELDS: readonly string[] = ['text', 'address', 'resource'];

/**
 * Поля, по которым список предложений упорядочивается.
 *
 * Первое — умолчание домена: свежие сверху. Текста предложения здесь нет — порядок по колонке,
 * которой нет в строке списка, человеку нечем объяснить.
 */
export const PROPOSAL_SORTABLE: readonly string[] = ['arrivedAt', 'resource', 'address', 'tree'];
