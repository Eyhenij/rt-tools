/**
 * Ответ закрытия записей груза издателем редакции: чем оно кончилось.
 *
 * Отдельным объявлением, а не тем же, что у правки деревом: там ответ называет дерево, взятое из
 * токена, — здесь дерева нет вовсе. Издатель закрывает записи нескольких деревьев одним пакетом,
 * и одно имя в ответе солгало бы про весь остальной пакет.
 *
 * Отбитая строка при этом берётся готовой: причины у закрытия и у правки деревом одни и те же, и
 * вторая их копия разошлась бы с первой молча.
 */
import { ICargoStateDeniedLine } from './cargo-state.response';

/** Чем кончилось закрытие: два числа и список отбитых строк. */
export interface ICargoCloseResponse {
    /** Сколько записей закрыто. */
    readonly changed: number;
    /** Сколько уже стояло в названном состоянии: переходом это не считается. */
    readonly same: number;
    /** Строки, которые приёмник не исполнил. */
    readonly denied: readonly ICargoStateDeniedLine[];
}
