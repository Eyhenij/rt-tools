/**
 * Дерево запроса: то, что приёмник прочитал по токену, а не то, чем груз назвался.
 *
 * Признак, названный в грузе, с этим деревом сверяется — иначе дерево дописало бы чужую запись
 * месяца, назвавшись в грузе соседом. Поэтому прочитанное лежит под символом, а не под обычным
 * полем: поле с таким именем в теле запроса присланное, и перепутать их местами нельзя даже
 * опечаткой.
 *
 * Живёт в слое утилит, потому что читают его три операции приёма из трёх разных доменов, а
 * вторая копия проверки разошлась бы с первой в коде отказа.
 */

/** Дерево, опознанное по токену запроса. */
export interface IRequestTree {
    readonly id: string;
    /** Признак дерева: им груз называет отправителя, и с ним сверяется признак в грузе. */
    readonly slug: string;
    /** Читаемое имя: его называет владелец при заведении, и оно уходит в ответ приёмника. */
    readonly name: string;
}

/** Ключ, под которым опознанное дерево лежит в запросе. */
export const TREE_OF_REQUEST: unique symbol = Symbol('message-bus.tree');

/** Запрос, в который проверка токена положила дерево. */
export interface ITreeBearingRequest {
    [TREE_OF_REQUEST]?: IRequestTree;
}

/** Положить опознанное дерево в запрос. Зовёт проверка токена, и больше никто. */
export function rememberTree(request: ITreeBearingRequest, tree: IRequestTree): void {
    request[TREE_OF_REQUEST] = tree;
}

/**
 * Дерево запроса.
 *
 * Пусто здесь означает не отказ вызывающему, а дефект приложения: операция объявлена, но
 * проверкой токена не закрыта. Дереву править нечего, и отказ поэтому свой, а не его.
 */
export function treeOf(request: ITreeBearingRequest): IRequestTree {
    const tree: IRequestTree | undefined = request[TREE_OF_REQUEST];

    if (!tree) {
        throw new Error('дерево запроса не прочитано: операция не закрыта проверкой токена');
    }

    return tree;
}
