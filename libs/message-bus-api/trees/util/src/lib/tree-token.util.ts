/**
 * Токен дерева: выпуск, хеш и сверка хешей.
 *
 * В хранилище лежит только хеш: по нему токен не восстанавливается, и утёкшая выкатка или
 * снятый дамп базы доступа не дают. Сам токен печатается один раз, при выдаче, — показать его
 * второй раз неоткуда.
 *
 * Чистые функции, хранилища не знают: их зовут и проверка приёма, и команда заведения дерева, и
 * спека — последней база не нужна вовсе.
 */
import { createHash, randomBytes, timingSafeEqual } from 'node:crypto';

/**
 * Длина случайной части токена в байтах. Тридцать два: до выкатки за проксировщиком токен ходит
 * по открытому HTTP, и подбирать его должно быть не дешевле, чем ключ.
 */
const TOKEN_BYTES: number = 32;

/**
 * Новый токен дерева. Печатается вызывающим один раз и в хранилище не попадает — туда уходит
 * только его хеш.
 */
export function issueTreeToken(): string {
    return randomBytes(TOKEN_BYTES).toString('hex');
}

/**
 * Хеш токена — то, чем токен опознаётся в хранилище.
 *
 * Без соли и без растягивания намеренно: соль потребовала бы перебора всех строк таблицы на
 * каждом приёме, а растягивание — того же на каждом запросе прогона. Растягивают то, что человек
 * выбрал сам и мог выбрать коротким; здесь тридцать два случайных байта, и перебор по ним не
 * окупается ни при какой скорости хеша.
 */
export function treeTokenHash(token: string): string {
    return createHash('sha256').update(token, 'utf8').digest('hex');
}

/**
 * Сошлись ли два хеша.
 *
 * Сравнение за постоянное время: побайтовое прерывается на первом несовпадении, и по времени
 * ответа хеш добирается посимвольно. Хранилище ищет по хешу равенством, поэтому зовут это там,
 * где хеш уже прочитан, — при сверке нескольких токенов одного дерева.
 */
export function treeTokenHashesMatch(left: string, right: string): boolean {
    const first: Buffer = Buffer.from(left, 'utf8');
    const second: Buffer = Buffer.from(right, 'utf8');

    return first.length === second.length && timingSafeEqual(first, second);
}
