/**
 * Чем операция закрыта: объявление доступа и метки, которыми оно ставится.
 *
 * Способов представиться у приёмника два, и они не заменяют друг друга: дерево несёт токен и
 * зовёт приём груза, человек несёт вход и читает принятое. Утёкший с дерева токен иначе читал бы
 * груз всех деревьев.
 *
 * Объявление живёт отдельным доменом, потому что читают его обе стороны: и проверка токена, и
 * проверка входа. Положенное к одной из них, оно сделало бы вторую её потребителем — и домен
 * деревьев стал бы знать про людей, которых не заводит.
 *
 * Умолчание — **закрыто**: операция, не объявившая ничего, не отвечает никому. Направление
 * выбрано так намеренно: при обратном забытая строка открывала бы новую операцию наружу молча.
 */
import { CustomDecorator, SetMetadata } from '@nestjs/common';

/** Чем операция закрыта. Набор закрыт: третьего способа представиться у приёмника нет. */
export type TOperationAccess =
    /** Открыта всем: сегодня это одна проба живости. */
    | 'public'
    /** Закрыта токеном дерева: приём груза. */
    | 'tree'
    /** Закрыта входом человека: чтение принятого. */
    | 'session';

/** Ключ, под которым объявление лежит в метаданных операции. */
export const OPERATION_ACCESS: string = 'message-bus.operation-access';

/* eslint-disable sonarjs/function-name -- фабрики декораторов зовутся с прописной буквы: так их называет сам каркас, и так они читаются в месте применения */

/** Операция, открытая без токена и без входа. */
export function PublicOperation(): CustomDecorator<string> {
    return SetMetadata(OPERATION_ACCESS, 'public');
}

/** Операция приёма груза: закрыта токеном дерева. */
export function TreeOperation(): CustomDecorator<string> {
    return SetMetadata(OPERATION_ACCESS, 'tree');
}

/** Операция чтения принятого: закрыта входом человека. */
export function SessionOperation(): CustomDecorator<string> {
    return SetMetadata(OPERATION_ACCESS, 'session');
}
