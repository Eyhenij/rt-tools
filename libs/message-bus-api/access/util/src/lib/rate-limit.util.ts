/**
 * Ограничитель частоты: сколько обращений с одного ключа клиента приём принимает за окно.
 *
 * Заведён вместе с первой публичной операцией, заводящей запись. Права её не сторожат, и без
 * предела скорость роста таблицы задаёт отправитель, а не владелец.
 *
 * Решение отделено от хранения счётчиков: считает чистая функция, а где лежат отметки — дело
 * того, кто её зовёт. Так предел проверяется вызовом, а не ожиданием у настоящего приёма.
 *
 * Момент времени приходит доводом. Часы машины здесь не читаются: окно, зависящее от них,
 * проверялось бы подкруткой времени вокруг спеки.
 */

/** Сколько обращений с одного ключа принимается за окно. */
export const ENROLL_LIMIT: number = 5;

/** Длина окна в миллисекундах: минута — столько же, сколько занимает одна попытка человека. */
export const ENROLL_WINDOW_MS: number = 60_000;

/** Отметки о прошлых обращениях с одного ключа: время каждого, свежие в конце. */
export type TRateMarks = readonly number[];

/** Что решил ограничитель: пускать ли обращение и с какими отметками остаётся ключ. */
export interface IRateVerdict {
    readonly allowed: boolean;
    /** Отметки после решения: принятое обращение сюда уже входит. */
    readonly marks: TRateMarks;
}

/**
 * Решение по одному обращению.
 *
 * Отметки старше окна выбрасываются здесь же: чистка отдельным ходом означала бы, что список
 * растёт, пока по ключу не пришло нового обращения, — а приходят они как раз с тех ключей,
 * которые и надо ограничить.
 */
export function rateVerdict(marks: TRateMarks, at: Date, limit: number = ENROLL_LIMIT, windowMs: number = ENROLL_WINDOW_MS): IRateVerdict {
    const now: number = at.getTime();
    const fresh: number[] = marks.filter((mark: number): boolean => now - mark < windowMs);

    return fresh.length >= limit ? { allowed: false, marks: fresh } : { allowed: true, marks: [...fresh, now] };
}
