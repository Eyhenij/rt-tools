/**
 * Имя учётной записи: то, как его назвал владелец, и то, по чему оно опознаётся.
 *
 * Опознаётся запись приведённым именем, а показывается названным: `Иван` рядом с `иван`
 * означает, что вход перестал отвечать, кто именно вошёл. Уникальность держит хранилище по
 * приведённому виду, поэтому приведение здесь одно на всё приложение — зовут его и команда
 * заведения, и вход.
 */

/**
 * Приведённое имя: края обрезаны, регистр снят.
 *
 * Регистр снимается без учёта языка вызывающего: в турецкой локали `toLocaleLowerCase` делает
 * из `I` букву с точкой, и одно и то же имя опознавалось бы по-разному на разных машинах.
 */
export function accountNameKey(name: string): string {
    return name.trim().toLowerCase();
}

/** Годится ли имя в учётную запись: пустое и состоящее из одних пробелов не годится. */
export function accountNameOk(name: string): boolean {
    return accountNameKey(name).length > 0;
}
