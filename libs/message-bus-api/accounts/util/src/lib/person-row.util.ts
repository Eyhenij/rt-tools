/**
 * Запись хранилища в строку списка людей.
 *
 * Отдельно от строки списка команд: та собирается для печати в терминал и роли не знает вовсе —
 * роли не было, когда её писали. Одна строка на двоих означала бы, что печать команды поедет
 * следом за каждой правкой раздела админки.
 *
 * Сама форма строки объявлена не здесь, а в общей либе: её читает админка, и своей копии ни одна
 * из сторон не заводит.
 */
import { IPersonView } from '@rt/message-bus-common';

/** Запись хранилища, как её отдаёт выборка: роль приезжает вложенной и бывает пустой. */
export interface IPersonSource {
    readonly name: string;
    readonly role: { readonly name: string } | null;
    readonly disabledAt: Date | null;
    readonly lastLoginAt: Date | null;
}

/**
 * Строка ответа из записи хранилища.
 *
 * Отдельным вызовом, а не выборкой в запросе: пустая роль — законное состояние, и то, во что она
 * превращается в ответе, проверяется вызовом, без базы. Слова «роли нет» здесь не появляются:
 * приёмник отдаёт пустоту, а называет её словами экран — иначе подпись жила бы в двух местах и
 * разошлась бы на первой правке словаря.
 *
 * Времена уезжают строкой всемирного времени: пояс смотрящего считается на его стороне, а не на
 * стороне приёма — приём не знает, из какого пояса на список смотрят.
 */
export function personRowOf(source: IPersonSource): IPersonView {
    return {
        name: source.name,
        role: source.role?.name ?? null,
        disabledAt: source.disabledAt?.toISOString() ?? null,
        lastLoginAt: source.lastLoginAt?.toISOString() ?? null,
    };
}
