/**
 * На сколько удлиняется ответ после неудачных попыток входа подряд.
 *
 * Служба стоит в интернете, и перебор, отвечающий с той же скоростью, ограничен только сетью.
 * Учётная запись при этом не запирается: запертую запись отпирать некому — админки учёток нет,
 * и запирание превратило бы перебор чужого имени в способ выключить чужого человека.
 *
 * Первая неудача отвечает без задержки: ошибиться паролем — обычное дело, и наказывать за это
 * ожиданием значит наказывать того, кто просто промахнулся по клавише.
 */

/** Задержка после второй неудачи подряд; каждая следующая удваивает её. */
export const LOGIN_DELAY_BASE_MS: number = 250;

/**
 * Предел задержки.
 *
 * Без него восьмая неудача держала бы соединение полминуты, а десятая — минуты: перебору это
 * стоит одного соединения из тысячи, а человеку, вспомнившему пароль с третьего раза, — всего
 * ожидания целиком.
 */
export const LOGIN_DELAY_MAX_MS: number = 5000;

/** Сколько неудача помнится. Пережившая этот срок счёта не удлиняет: перебор столько не ждёт. */
export const LOGIN_ATTEMPT_TTL_MS: number = 15 * 60 * 1000;

/** Задержка ответа при стольких-то неудачах подряд, считая нынешнюю. */
export function loginDelayMs(failed: number): number {
    if (failed <= 1) {
        return 0;
    }

    return Math.min(LOGIN_DELAY_BASE_MS * 2 ** (failed - 2), LOGIN_DELAY_MAX_MS);
}
